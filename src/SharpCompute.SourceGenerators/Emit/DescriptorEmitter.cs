using System;
using System.Globalization;
using System.Linq;

namespace SharpCompute.SourceGenerators;

/// <summary>Writes the partial that implements <c>IComputeShaderDescriptor&lt;TSelf&gt;</c> for one shader.</summary>
internal static class DescriptorEmitter
{
    private const string Descriptor = "global::SharpCompute.IComputeShaderDescriptor";
    private const string Writer = "global::SharpCompute.ShaderArgumentWriter";
    private const string ConstantsStruct = "__Constants";
    private const string InstanceMethod = "__SharpCompute_SetArguments";

    public static string Emit(ShaderModel model)
    {
        var writer = new CodeWriter();
        string self = model.FullyQualifiedName;
        string contract = $"{Descriptor}<{self}>";

        writer.Line("// <auto-generated/>");
        writer.Line("#pragma warning disable");
        writer.Line("#nullable enable");
        writer.Line();

        if (model.Namespace is not null)
        {
            writer.Line("namespace " + model.Namespace);
            writer.Line("{");
            writer.Indent++;
        }

        for (int i = 0; i < model.Types.Count; i++)
        {
            TypeDeclarationInfo type = model.Types[i];
            bool isShader = i == model.Types.Count - 1;

            if (isShader && !model.IsStub)
            {
                // The record that build tools find the shader by, in the assembly's metadata (see
                // GeneratedShaderRecordAttribute). A stub has no MSL to precompile, so it gets none.
                writer.Line(
                    $"[global::SharpCompute.GeneratedShaderRecord({Literal(model.EntryPoint)}, (global::SharpCompute.ShaderCompileOptions){model.CompileOptions.ToString(CultureInfo.InvariantCulture)})]");
            }

            writer.Line($"partial {type.Keyword} {type.Name}{(isShader ? " : " + contract : string.Empty)}");
            writer.Line("{");
            writer.Indent++;
        }

        if (model.IsStub)
        {
            EmitStub(writer, model, contract);
        }
        else
        {
            EmitDescriptor(writer, model, contract);
        }

        for (int i = 0; i < model.Types.Count; i++)
        {
            writer.Indent--;
            writer.Line("}");
        }

        if (model.Namespace is not null)
        {
            writer.Indent--;
            writer.Line("}");
        }

        return writer.ToString();
    }

    /// <summary>
    /// Emitted when the shader has errors: it keeps <c>device.For(..., shader)</c> call sites from
    /// producing a second wave of confusing errors on top of the SharpCompute diagnostics.
    /// </summary>
    private static void EmitStub(CodeWriter writer, ShaderModel model, string contract)
    {
        const string Throw = "throw new global::System.NotSupportedException(\"This shader has SharpCompute errors; see the build output.\")";

        writer.Line("// This shader has SharpCompute errors (SCGxxxx diagnostics); no MSL was generated for it.");
        writer.Line($"static string {contract}.EntryPoint => {Throw};");
        writer.Line();
        writer.Line($"static string {contract}.MslSource => {Throw};");
        writer.Line();
        writer.Line($"static int {contract}.ThreadGroupSizeX => {Throw};");
        writer.Line();
        writer.Line($"static int {contract}.ThreadGroupSizeY => {Throw};");
        writer.Line();
        writer.Line($"static int {contract}.ThreadGroupSizeZ => {Throw};");
        writer.Line();
        writer.Line($"static void {contract}.SetArguments(in {model.FullyQualifiedName} shader, ref {Writer} writer) => {Throw};");
    }

    private static void EmitDescriptor(CodeWriter writer, ShaderModel model, string contract)
    {
        writer.Line("/// <summary>The name of the kernel function in the generated MSL.</summary>");
        writer.Line($"static string {contract}.EntryPoint => \"{model.EntryPoint}\";");
        writer.Line();

        // Use a delimiter longer than any run of quotes in the MSL (it only quotes static_assert messages).
        int quotes = Math.Max(3, LongestQuoteRun(model.MslSource) + 1);
        string delimiter = new('"', quotes);

        writer.Line("/// <summary>The Metal Shading Language translation of this shader.</summary>");
        writer.Line($"static string {contract}.MslSource =>");
        writer.Indent++;
        writer.Line(delimiter);
        writer.Lines(model.MslSource.TrimEnd('\n'));
        writer.Line(delimiter + ";");
        writer.Indent--;
        writer.Line();

        writer.Line($"static int {contract}.ThreadGroupSizeX => {model.ThreadGroupSizeX.ToString(CultureInfo.InvariantCulture)};");
        writer.Line();
        writer.Line($"static int {contract}.ThreadGroupSizeY => {model.ThreadGroupSizeY.ToString(CultureInfo.InvariantCulture)};");
        writer.Line();
        writer.Line($"static int {contract}.ThreadGroupSizeZ => {model.ThreadGroupSizeZ.ToString(CultureInfo.InvariantCulture)};");
        writer.Line();

        if (model.GridWindowIndex >= 0)
        {
            // Without this member the interface's default (-1) applies: the shader cannot be split.
            writer.Line("/// <summary>The buffer index of the hidden grid window bound by partial-grid (CPU+GPU split) dispatches.</summary>");
            writer.Line($"static int {contract}.GridWindowIndex => {model.GridWindowIndex.ToString(CultureInfo.InvariantCulture)};");
            writer.Line();
        }

        if (model.UsesAtomics)
        {
            // Without this member the interface's default (false) applies.
            writer.Line(model.UsesDeviceAtomics
                ? "/// <summary>The kernel uses atomic operations on buffer elements, so a CPU+GPU split dispatch must not divide it between the two.</summary>"
                : "/// <summary>The kernel uses atomic operations.</summary>");
            writer.Line($"static bool {contract}.UsesAtomics => true;");
            writer.Line();

            if (!model.UsesDeviceAtomics)
            {
                // Without this member the interface's default (UsesAtomics) applies.
                writer.Line("/// <summary>All of them are on threadgroup memory, which the threads of one threadgroup share: a CPU+GPU split dispatch may divide the kernel.</summary>");
                writer.Line($"static bool {contract}.UsesDeviceAtomics => false;");
                writer.Line();
            }
        }

        if (model.UsesThreadgroupMemory)
        {
            // Without these members the interface's defaults (false, 0) apply.
            writer.Line("/// <summary>The kernel uses threadgroup memory or barriers: on the CPU its threadgroups run as groups of cooperating threads.</summary>");
            writer.Line($"static bool {contract}.UsesThreadgroupMemory => true;");
            writer.Line();
        }

        if (model.ThreadgroupMemoryLength > 0)
        {
            writer.Line("/// <summary>The bytes of threadgroup memory the kernel declares for its [GroupShared] fields.</summary>");
            writer.Line($"static int {contract}.ThreadgroupMemoryLength => {model.ThreadgroupMemoryLength.ToString(CultureInfo.InvariantCulture)};");
            writer.Line();
        }

        if (model.CompileOptions != 0)
        {
            // Without this member the interface's default (None) applies.
            const string Options = "global::SharpCompute.ShaderCompileOptions";
            var flags = new System.Collections.Generic.List<string>();

            if ((model.CompileOptions & ShaderModel.FastMath) != 0)
            {
                flags.Add(Options + ".FastMath");
            }

            if ((model.CompileOptions & ShaderModel.NoFpContract) != 0)
            {
                flags.Add(Options + ".NoFpContract");
            }

            writer.Line("/// <summary>How the runtime compiles the kernel, from the shader's [ShaderOptions] attribute.</summary>");
            writer.Line($"static {Options} {contract}.CompileOptions => {string.Join(" | ", flags)};");
            writer.Line();
        }

        if (model.UsesSimdGroups)
        {
            // Without this member the interface's default (false) applies.
            writer.Line("/// <summary>The kernel uses SIMD-group operations: the lanes of a SIMD group compute their results together.</summary>");
            writer.Line($"static bool {contract}.UsesSimdGroups => true;");
            writer.Line();
        }

        writer.Line($"static void {contract}.SetArguments(in {model.FullyQualifiedName} shader, ref {Writer} writer)");
        writer.Line("{");
        writer.Indent++;

        if (model.UsesInstanceAccess)
        {
            // Primary-constructor parameters are only in scope inside instance members.
            writer.Line($"shader.{InstanceMethod}(ref writer);");
            writer.Indent--;
            writer.Line("}");
            writer.Line();
            writer.Line("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
            writer.Line($"private readonly void {InstanceMethod}(ref {Writer} __writer)");
            writer.Line("{");
            writer.Indent++;
            EmitBindings(writer, model, "__writer");
        }
        else
        {
            EmitBindings(writer, model, "writer");
        }

        writer.Indent--;
        writer.Line("}");

        if (model.Constants.Count > 0)
        {
            writer.Line();
            const string Interop = "global::System.Runtime.InteropServices.";
            bool isExplicit = model.ExplicitConstantsSize > 0;

            writer.Line("/// <summary>The C# mirror of the MSL <c>__Constants</c> struct bound after the buffers.</summary>");

            if (isExplicit)
            {
                // A 64-bit integer is aligned to 8 in MSL, which Pack = 4 would not reproduce: state the
                // offsets the MSL asserts instead of relying on a packing rule.
                writer.Line("/// <remarks>It holds a 64-bit integer, which MSL aligns to 8 bytes: every field is placed at the offset the MSL asserts.</remarks>");
                writer.Line($"[{Interop}StructLayout({Interop}LayoutKind.Explicit, Size = {model.ExplicitConstantsSize.ToString(CultureInfo.InvariantCulture)})]");
            }
            else
            {
                writer.Line($"[{Interop}StructLayout({Interop}LayoutKind.Sequential, Pack = 4)]");
            }

            writer.Line($"private struct {ConstantsStruct}");
            writer.Line("{");
            writer.Indent++;

            foreach (ConstantArgument constant in model.Constants)
            {
                string offset = isExplicit ? $"[{Interop}FieldOffset({constant.Offset.ToString(CultureInfo.InvariantCulture)})] " : string.Empty;
                writer.Line($"{offset}public {constant.TypeName} {constant.FieldName};");
            }

            writer.Indent--;
            writer.Line("}");
        }
    }

    private static void EmitBindings(CodeWriter writer, ShaderModel model, string writerName)
    {
        foreach (BufferArgument buffer in model.Buffers)
        {
            // `default(Shader)` has null buffers: name the shader and field rather than the writer's parameter.
            string message = $"The buffer '{buffer.DisplayName}' is null. Create the shader with its constructor (not 'default') and pass a buffer.";
            writer.Line($"{writerName}.SetBuffer({buffer.Index.ToString(CultureInfo.InvariantCulture)}, {buffer.Access} ?? throw new global::System.ArgumentNullException({Literal(buffer.DisplayName)}, {Literal(message)}));");
        }

        foreach (BufferArgument texture in model.Textures)
        {
            string message = $"The texture '{texture.DisplayName}' is null. Create the shader with its constructor (not 'default') and pass a texture.";
            writer.Line($"{writerName}.SetTexture({texture.Index.ToString(CultureInfo.InvariantCulture)}, {texture.Access} ?? throw new global::System.ArgumentNullException({Literal(texture.DisplayName)}, {Literal(message)}));");
        }

        if (model.Constants.Count == 0)
        {
            return;
        }

        writer.Line($"{ConstantsStruct} __constants = default;");

        foreach (ConstantArgument constant in model.Constants)
        {
            writer.Line($"__constants.{constant.FieldName} = {constant.Value};");
        }

        writer.Line($"{writerName}.SetBytes({model.ConstantsIndex.ToString(CultureInfo.InvariantCulture)}, in __constants);");
    }

    /// <summary>A C# string literal for <paramref name="text"/>.</summary>
    private static string Literal(string text) =>
        "\"" + text.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    private static int LongestQuoteRun(string text)
    {
        int longest = 0;
        int current = 0;

        foreach (char c in text)
        {
            current = c == '"' ? current + 1 : 0;
            longest = Math.Max(longest, current);
        }

        return longest;
    }
}
