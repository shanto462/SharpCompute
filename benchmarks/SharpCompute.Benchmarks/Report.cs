using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using BenchmarkDotNet.Reports;
using BenchmarkDotNet.Running;
using SharpCompute.Benchmarks.Workloads;
using Row = SharpCompute.Benchmarks.BenchmarkRow;

namespace SharpCompute.Benchmarks;

/// <summary>Renders benchmarks/RESULTS.md from BenchmarkDotNet summaries plus the verify and first-dispatch results.</summary>
public static class Report
{
    private static readonly string[] WorkloadOrder = ["SAXPY", "Mandelbrot", "Gaussian blur", "Matrix multiply", "N-body", "Batching and async"];

    /// <summary>
    /// Turns BenchmarkDotNet's reports into rows, ordered by workload (as declared in Benchmarks.cs)
    /// and then by problem size, so sweeps read small to large.
    /// </summary>
    public static List<BenchmarkRow> ToRows(IEnumerable<Summary> summaries) =>
        summaries.SelectMany(s => s.Reports)
            .Where(r => r.ResultStatistics is not null)
            .Select(r => new BenchmarkRow(
                r.BenchmarkCase.Descriptor.Categories.FirstOrDefault() ?? r.BenchmarkCase.Descriptor.Type.Name,
                SizeLabel(r.BenchmarkCase),
                SizeKey(r.BenchmarkCase),
                r.BenchmarkCase.Descriptor.WorkloadMethodDisplayInfo.Trim('\''),
                r.BenchmarkCase.Descriptor.Baseline,
                r.ResultStatistics!.Mean,
                r.ResultStatistics.ConfidenceInterval.Margin,
                r.ResultStatistics.StandardDeviation))
            .ToList();

    public static string Build(RunData data)
    {
        (Machine machine, Machine.Snapshot before, Machine.Snapshot after, IReadOnlyList<Check> checks, IReadOnlyList<FirstDispatch> firstDispatches, IReadOnlyList<BenchmarkRow> allRows, bool quick, double elapsedMinutes, IReadOnlyList<Rerun>? reruns) = data;
        reruns ??= [];
        List<Row> rows = allRows
            .OrderBy(r => Array.IndexOf(WorkloadOrder, r.Workload) is int i && i >= 0 ? i : int.MaxValue)
            .ThenBy(r => r.SizeKey)
            .ToList();

        var groups = rows.GroupBy(r => (r.Workload, r.Size)).ToList();
        StringBuilder md = new();

        md.AppendLine("# SharpCompute benchmarks: GPU vs CPU");
        md.AppendLine();
        string job = quick ? "ShortRun (3 warmup + 3 measured iterations, 1 launch)" : "Default (adaptive warmup and iteration count)";
        md.AppendLine(Invariant($"Generated by `scripts/run-benchmarks.sh{(quick ? " --quick" : "")}` on {before.Time:yyyy-MM-dd HH:mm zzz}. BenchmarkDotNet job: **{job}**; the benchmark run took {elapsedMinutes:F0} min. Source: `benchmarks/SharpCompute.Benchmarks`."));

        foreach (Rerun rerun in reruns)
        {
            md.AppendLine();
            md.AppendLine(Invariant($"Re-run on {rerun.Before.Time:yyyy-MM-dd HH:mm zzz} ({(rerun.Quick ? "ShortRun" : "Default")} job, {rerun.ElapsedMinutes:F0} min): **{string.Join(", ", rerun.Workloads)}**. Those rows replace the earlier ones; everything else is from the first run. Verification and first-dispatch results are from the re-run."));
        }

        md.AppendLine();

        md.AppendLine("## Machine");
        md.AppendLine();
        md.AppendLine("| | |");
        md.AppendLine("|---|---|");
        md.AppendLine($"| Model | {machine.Model} |");
        md.AppendLine($"| CPU | {machine.Cpu}, {machine.Cores} cores |");
        md.AppendLine($"| GPU | {machine.Gpu} |");
        md.AppendLine($"| Memory | {machine.Memory} |");
        md.AppendLine($"| OS | {machine.Os} |");
        md.AppendLine($"| Runtime | {machine.Runtime} |");
        md.AppendLine($"| Power | {machine.Power} |");
        md.AppendLine();

        md.AppendLine("### Background load");
        md.AppendLine();
        md.AppendLine("This machine was shared (other builds and test runs may have been active), and the same GPU dispatch has been seen to vary "
            + "by 2–3× between runs under load. The load at the start and end of the run is below. **Treat the numbers as pessimistic**: "
            + "both CPU and GPU variants can only get faster on an idle machine, and the multi-threaded CPU variants suffer most from contention.");
        md.AppendLine();
        AppendSnapshot(md, "Start", before);
        AppendSnapshot(md, "End", after);

        foreach (Rerun rerun in reruns)
        {
            AppendSnapshot(md, $"Re-run start ({string.Join(", ", rerun.Workloads)})", rerun.Before);
            AppendSnapshot(md, "Re-run end", rerun.After);
        }

        md.AppendLine();

        md.AppendLine("## Headline: GPU speedup over the best CPU variant");
        md.AppendLine();
        md.AppendLine("\"Best CPU\" is the fastest CPU variant measured for that row (whatever its kind), not the scalar baseline. "
            + "Speedup = best CPU mean / GPU mean; below 1× the CPU wins.");
        md.AppendLine();
        md.AppendLine("| Workload | Size | Best CPU variant | Best CPU | GPU (generated) | GPU speedup vs best CPU | GPU speedup vs baseline |");
        md.AppendLine("|---|---|---|---:|---:|---:|---:|");

        foreach (var group in groups)
        {
            Row? gpu = group.FirstOrDefault(r => r.IsGeneratedGpu);
            Row? best = group.Where(r => !r.IsGpu).MinBy(r => r.Mean);
            Row? baseline = group.FirstOrDefault(r => r.Baseline);

            if (gpu is null || best is null || baseline is null)
            {
                continue;
            }

            md.AppendLine(Invariant($"| {group.Key.Workload} | {group.Key.Size} | {best.Variant} | {Time(best.Mean)} | {Time(gpu.Mean)} | **{Speedup(best.Mean / gpu.Mean)}** | {Speedup(baseline.Mean / gpu.Mean)} ({baseline.Variant}) |"));
        }

        md.AppendLine();
        AppendCrossover(md, groups.Select(g => (g.Key.Workload, g.Key.Size, Rows: g.ToList())).ToList());
        AppendGeneratedVsHandWritten(md, rows);
        AppendHowToRead(md, rows);

        md.AppendLine("## Results per workload");
        md.AppendLine();
        md.AppendLine("Mean and Error come from BenchmarkDotNet (Error = half-width of the 99.9 % confidence interval). "
            + "Ratio = mean / baseline mean (lower is faster); the baseline is marked †. "
            + "Variant labels say what each CPU baseline is: *scalar (1 thread)*, *SIMD (1 thread)*, *Parallel.For* (all cores, scalar inner loop) "
            + "or *Parallel.For + SIMD*.");
        md.AppendLine();

        foreach (var workload in groups.GroupBy(g => g.Key.Workload))
        {
            md.AppendLine($"### {workload.Key}");
            md.AppendLine();
            md.AppendLine(WorkloadNote(workload.Key));
            md.AppendLine();
            md.AppendLine("| Size | Variant | Mean | Error | StdDev | Ratio |");
            md.AppendLine("|---|---|---:|---:|---:|---:|");

            foreach (var group in workload)
            {
                Row? baseline = group.FirstOrDefault(r => r.Baseline);

                foreach (Row row in group)
                {
                    string ratio = baseline is null ? "?" : Invariant($"{row.Mean / baseline.Mean:F3}");
                    string variant = row.Baseline ? $"{row.Variant} †" : row.Variant;
                    md.AppendLine($"| {group.Key.Size} | {variant} | {Time(row.Mean)} | {Time(row.Error)} | {Time(row.StdDev)} | {ratio} |");
                }
            }

            md.AppendLine();
        }

        AppendFirstDispatch(md, firstDispatches);

        md.AppendLine("## Verification (`--verify`)");
        md.AppendLine();
        md.AppendLine("Run before benchmarking; the script stops if any check fails. Bit-exactness is only expected of single "
            + "arithmetic ops, so every float result is compared with a relative tolerance of 1e-5 (the bit-exact share is reported as a detail). "
            + "Mandelbrot compares iteration counts (±1 allowed) against a CPU reference that fuses the same multiply-adds Metal's default FP "
            + "contraction fuses; against the unfused CPU loop, a fraction of a percent of boundary pixels follow a different chaotic orbit. "
            + "N-body compares per-body vectors, with the relative error's denominator floored at the RMS magnitude over all bodies.");
        md.AppendLine();
        md.Append(Verify.ToMarkdown(checks));

        return md.ToString();
    }

    private static void AppendSnapshot(StringBuilder md, string label, Machine.Snapshot snapshot)
    {
        md.AppendLine(Invariant($"- **{label}** ({snapshot.Time:HH:mm}): `{snapshot.Uptime}`"));
    }

    /// <summary>For the workloads measured at several sizes: the smallest size at which the GPU beats every CPU variant.</summary>
    private static void AppendCrossover(StringBuilder md, List<(string Workload, string Size, List<Row> Rows)> groups)
    {
        md.AppendLine("**Crossover** (smallest measured size where the GPU beats the best CPU variant):");
        md.AppendLine();

        // Only GPU-vs-CPU workloads have a crossover (the batching rows compare GPU submission paths).
        foreach (var workload in groups.GroupBy(g => g.Workload).Where(w => w.Count() > 1 && w.Any(g => g.Rows.Any(r => !r.IsGpu))))
        {
            var first = workload.FirstOrDefault(g =>
                g.Rows.FirstOrDefault(r => r.IsGeneratedGpu) is { } gpu && g.Rows.Where(r => !r.IsGpu).All(r => r.Mean > gpu.Mean));
            string sizes = string.Join(", ", workload.Select(w => w.Size));

            md.AppendLine(first.Rows is null
                ? $"- {workload.Key}: the CPU wins at every measured size ({sizes})."
                : $"- {workload.Key}: GPU wins from **{first.Size}** on (measured: {sizes}).");
        }

        md.AppendLine();
    }

    private static void AppendGeneratedVsHandWritten(StringBuilder md, List<Row> rows)
    {
        var pairs = rows.Where(r => r.Workload == "SAXPY").GroupBy(r => r.Size)
            .Select(g => (Size: g.Key, Generated: g.FirstOrDefault(r => r.IsGeneratedGpu), Hand: g.FirstOrDefault(r => r.Variant.StartsWith("GPU hand-written", StringComparison.Ordinal))))
            .Where(p => p.Generated is not null && p.Hand is not null)
            .ToList();

        if (pairs.Count == 0)
        {
            return;
        }

        md.AppendLine("### Generated shader vs hand-written MSL (SAXPY)");
        md.AppendLine();
        md.AppendLine("Same kernel, same threadgroup size (256), same binding. The generated descriptor is checked at startup to really be the "
            + "generator's output (its MSL differs from the hand-written string and contains its own `kernel void`), and `--verify` checks that both produce bit-identical results.");
        md.AppendLine();
        md.AppendLine("| Size | Generated | Hand-written | Generated / hand-written |");
        md.AppendLine("|---|---:|---:|---:|");

        foreach (var (size, generated, hand) in pairs)
        {
            md.AppendLine(Invariant($"| {size} | {Time(generated!.Mean)} ± {Time(generated.Error)} | {Time(hand!.Mean)} ± {Time(hand.Error)} | {generated.Mean / hand.Mean:F3} |"));
        }

        md.AppendLine();
    }

    private static void AppendHowToRead(StringBuilder md, List<Row> rows)
    {
        Row? smallest = rows.Where(r => r.Workload == "SAXPY" && r.IsGeneratedGpu).MinBy(r => r.Mean);
        string floor = smallest is null ? "" : $" (measured here: the {smallest.Size} SAXPY dispatch, which does almost no work, takes {Time(smallest.Mean)})";

        md.AppendLine("## How to read this");
        md.AppendLine();
        md.AppendLine("- **What a GPU number includes:** one `device.For(...)` call: encoding the dispatch into a new command buffer, `commit`, and "
            + "`waitUntilCompleted`, plus reading one element of the result back through the shared buffer (to keep the result observable). "
            + "It is the real synchronous cost of a dispatch as SharpCompute v1 exposes it. The blur is two `For` calls, so it pays that twice.");
        md.AppendLine("- **What it excludes:** buffer allocation, uploading inputs and reading back the full result. All buffers are allocated and filled "
            + "once in `[GlobalSetup]`, and the pipeline is compiled there too, by a warm-up dispatch. The one-off compile cost is measured "
            + "separately under [First dispatch](#first-dispatch-pipeline-compile).");
        md.AppendLine("- **Unified memory, zero copy:** SharpCompute buffers are `MTLStorageModeShared`. CPU and GPU see the same physical memory, so "
            + "there is no PCIe-style upload or download to amortize. A discrete GPU would add a copy each way; here, \"reading the result\" is "
            + "a pointer dereference. That is why moving data is not in the GPU time. It's also why bandwidth-bound kernels (SAXPY) can't beat a "
            + "multi-threaded CPU by much: both read the same LPDDR5X through the same memory controller.");
        md.AppendLine("- **Small workloads:** every dispatch has a fixed floor of roughly 0.1–0.2 ms (command buffer creation, commit, GPU wake-up, "
            + $"completion wait){floor}. A workload the CPU finishes faster than that can't win on the GPU, which is where the crossover above "
            + "comes from. Zero copy lowers the crossover compared to a discrete GPU (no transfer to amortize), but doesn't remove the floor. "
            + "Batching several dispatches into one command buffer with a `ComputeContext` amortizes it; see Batching and async.");
        md.AppendLine("- **Caches:** at 1M floats SAXPY touches 8 MB, which largely stays in the CPU's on-chip caches between iterations, so the "
            + "multi-threaded CPU can exceed DRAM bandwidth there. At 16M floats (192 MB of traffic per call) both sides are DRAM-bound.");
        md.AppendLine("- **CPU variants** run on managed arrays. *scalar (1 thread)* is a plain loop; *SIMD* uses `TensorPrimitives`, "
            + "`Vector<T>` or `Vector128<T>` (128-bit NEON, 4 floats); *Parallel.For* spreads rows, chunks or bodies across all cores. The CPU matmul gets Bᵀ (transposed "
            + "once in setup, not timed); the N-body SIMD variant gets a structure-of-arrays copy (also built once in setup).");
        md.AppendLine("- **FP contraction:** Metal fuses `a*b + c` into fma by default, so GPU results match the CPU to rounding, "
            + "not bit for bit. That's what `--verify` checks.");
        md.AppendLine("- **GPU-private storage:** `MTLStorageModePrivate` buffers were measured against shared ones on this machine with a "
            + "4K `float4` blur-style kernel, in every combination of private and shared input and output: all took 1.91 ms (within 0.2 %). "
            + "On Apple silicon, private storage pays off for textures (lossless compression), not for buffers, so SharpCompute keeps "
            + "every buffer shared and CPU-visible.");
        md.AppendLine();
    }

    private static void AppendFirstDispatch(StringBuilder md, IReadOnlyList<FirstDispatch> samples)
    {
        md.AppendLine("## First dispatch (pipeline compile)");
        md.AppendLine();
        md.AppendLine("A plain `Stopwatch`, not BenchmarkDotNet. Each sample is a fresh process (`--first-dispatch`) that creates the default device and "
            + "then dispatches the 1920×1080, 512-iteration Mandelbrot. The first dispatch compiles the generated MSL into a pipeline "
            + "(`newLibraryWithSource` + `newComputePipelineState`) and then runs it. Compile ≈ first − steady. macOS keeps a system-wide "
            + "Metal shader cache, so these are typically warm-cache compiles; a never-seen shader on a clean cache takes longer.");
        md.AppendLine();
        md.AppendLine("| Sample | Device creation | First dispatch (compile + run) | Second dispatch | Steady (mean of 20) | Compile ≈ |");
        md.AppendLine("|---|---:|---:|---:|---:|---:|");

        for (int i = 0; i < samples.Count; i++)
        {
            FirstDispatch s = samples[i];
            md.AppendLine(Invariant($"| {i + 1} | {s.DeviceMs:F1} ms | {s.FirstMs:F1} ms | {s.SecondMs:F2} ms | {s.SteadyMs:F2} ms | {s.FirstMs - s.SteadyMs:F1} ms |"));
        }

        md.AppendLine();
    }

    private static string WorkloadNote(string workload) => workload switch
    {
        "SAXPY" => "`y = a·x + y` in place on float arrays (4 sizes, to show the crossover). Memory-bound: 12 bytes moved per 2 flops. "
            + "Baseline: CPU scalar (1 thread), which is fine even at 16M elements.",
        "Mandelbrot" => "Escape time, 512 iterations max, packed RGBA in a `uint` (iteration count in the low 16 bits), the full set framed 3 units tall. "
            + "Compute-bound. Baseline: CPU scalar (1 thread).",
        "Gaussian blur" => "Separable, radius 8 (17 taps, σ = 4), single-channel float, 3840×2160. Horizontal pass into a temp buffer, then vertical, "
            + "clamped edges. Baseline: CPU scalar (1 thread).",
        "Matrix multiply" => "Naive `C = A·B`, 1024×1024 float, row-major; the GPU runs one thread per output element and reads B column-wise. "
            + "Baseline: CPU Parallel.For (a scalar single thread is about 1 s per run and adds nothing).",
        "N-body" => "One O(n²) step with softening (ε² = 0.01), positions `Float4` (xyz + mass) and velocities `Float4`; reads the current "
            + "state and writes the next into separate buffers. Baseline: CPU Parallel.For (scalar single thread is too slow at 16K bodies).",
        "Image pipeline" => "Zero-copy data paths. A decoded 3840×2160 RGBA8 image (one `uint` per pixel) blurred (radius 8, separable, clamped) into "
            + "RGBA8 ready to encode; decoding and encoding are identical for every variant and not timed. *Zero copy* has the decoder write "
            + "into the buffer's shared memory (`AsSpan`); two kernels read the bytes, blur and write bytes, and the encoder reads the output in "
            + "place. *Copies in and out* runs the same two kernels on bytes kept in managed arrays, so the difference is the cost of the two "
            + "33 MB copies alone. *CPU conversions + copies* is a pipeline on `Float4` arrays: the CPU converts bytes to floats, 133 MB is "
            + "copied in, Float4 kernels blur, 133 MB is copied out and the CPU converts back. Baseline: the CPU pipeline, Parallel.For over rows "
            + "with one `Vector4` (one NEON register) per pixel.",
        "File to GPU" => "Zero-copy data paths. Sum 256 MB of floats from a file on the GPU, starting from the path: get the data into a buffer, one "
            + "reduction dispatch, add 65,536 partial sums on the CPU. The file is in the page cache (read every iteration), so this measures "
            + "copies and page mapping, not the disk; every variant creates and disposes its buffer per call. *No copy* is `MapReadOnlyBuffer` "
            + "(`newBufferWithBytesNoCopy` over a read-only `mmap`). There is no CPU variant: the point is the cost of getting data to the GPU.",
        "Batching and async" => "GPU submission paths compared with each other, not with the CPU. K = 1/10/100: K dependent SAXPY dispatches of "
            + "4,096 floats (in place on one buffer) as K `device.For` calls, one `ComputeContext` (one command buffer, one wait) or K `ForAsync` "
            + "calls awaited together. Blur: the two passes as two `For` calls or one context. Overlap: 8 frames of a 1920×1080 Mandelbrot "
            + "render plus a single-threaded CPU histogram of each frame, sync (render, wait, analyze) vs double-buffered `ForAsync`. "
            + "Baseline: the synchronous v1 path.",
        _ => "",
    };

    private static long SizeKey(BenchmarkCase benchmark)
    {
        foreach (string name in (string[])["N", "Bodies", "K"])
        {
            if (benchmark.Parameters.Items.Any(p => p.Name == name))
            {
                return Convert.ToInt64(benchmark.Parameters[name], CultureInfo.InvariantCulture);
            }
        }

        if (benchmark.Parameters.Items.Any(p => p.Name == "Size"))
        {
            (int width, int height) = Sizes.Parse(benchmark.Parameters["Size"]?.ToString() ?? "0x0");
            return (long)width * height;
        }

        // The parameterless batching benchmarks sort after the K sweep, blur before overlap.
        return benchmark.Descriptor.Type.Name switch
        {
            nameof(BatchingBlurBenchmarks) => 1_000,
            nameof(BatchingOverlapBenchmarks) => 1_001,
            _ => 0,
        };
    }

    private static string SizeLabel(BenchmarkCase benchmark)
    {
        string category = benchmark.Descriptor.Categories.FirstOrDefault() ?? "";

        return category switch
        {
            "SAXPY" => Invariant($"{Convert.ToInt32(benchmark.Parameters["N"], CultureInfo.InvariantCulture):N0} floats"),
            "Mandelbrot" => (benchmark.Parameters["Size"]?.ToString() ?? "?").Replace('x', '×'),
            "N-body" => Invariant($"{Convert.ToInt32(benchmark.Parameters["Bodies"], CultureInfo.InvariantCulture):N0} bodies"),
            "Gaussian blur" => Invariant($"{Sizes.BlurWidth}×{Sizes.BlurHeight}, r = {Sizes.BlurRadius}"),
            "Matrix multiply" => Invariant($"{Sizes.MatMul}×{Sizes.MatMul}"),
            "Image pipeline" => Invariant($"{Sizes.BlurWidth}×{Sizes.BlurHeight} RGBA8, r = {Sizes.BlurRadius}"),
            "File to GPU" => Invariant($"{Sizes.FileFloats * 4L / (1 << 20)} MB"),
            "Batching and async" => benchmark.Descriptor.Type.Name switch
            {
                nameof(BatchingSmallDispatchBenchmarks) => Invariant($"K = {Convert.ToInt32(benchmark.Parameters["K"], CultureInfo.InvariantCulture)} SAXPY dispatches of 4,096 floats"),
                nameof(BatchingBlurBenchmarks) => Invariant($"blur {Sizes.BlurWidth}×{Sizes.BlurHeight}, r = {Sizes.BlurRadius} (2 passes)"),
                nameof(BatchingOverlapBenchmarks) => Invariant($"{FrameOverlap.Frames} frames {FrameOverlap.Width}×{FrameOverlap.Height}, GPU render + CPU analysis"),
                _ => benchmark.Parameters.DisplayInfo,
            },
            _ => benchmark.Parameters.DisplayInfo,
        };
    }

    private static string Time(double ns) => ns switch
    {
        double.NaN => "?",
        < 1e3 => Invariant($"{ns:F1} ns"),
        < 1e6 => Invariant($"{ns / 1e3:F2} µs"),
        < 1e9 => Invariant($"{ns / 1e6:F2} ms"),
        _ => Invariant($"{ns / 1e9:F3} s"),
    };

    private static string Speedup(double factor) => factor switch
    {
        >= 10 => Invariant($"{factor:F0}×"),
        >= 0.995 => Invariant($"{factor:F2}×"),
        _ => Invariant($"{factor:0.###}× (CPU {1 / factor:0.#}× faster)"),
    };

    private static string Invariant(FormattableString value) => value.ToString(CultureInfo.InvariantCulture);
}
