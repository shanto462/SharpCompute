@dataclass(frozen=True)
class Scalar:
    cs: str  # C# keyword or type name
    name: str  # for shader and family names
    kind: str  # "int", "float", "half"
    bits: int = 32
    signed: bool = True

    @property
    def promoted(self) -> str:
        # The type of `x + y` in C#: the small integers are promoted to int.
        return "int" if self.kind == "int" and self.bits < 32 else self.cs

    @property
    def min(self) -> str:
        return f"{self.cs}.MinValue"


BYTE = Scalar("byte", "Byte", "int", 8, False)
SBYTE = Scalar("sbyte", "SByte", "int", 8, True)
SHORT = Scalar("short", "Short", "int", 16, True)
USHORT = Scalar("ushort", "UShort", "int", 16, False)
INT = Scalar("int", "Int", "int", 32, True)
UINT = Scalar("uint", "UInt", "int", 32, False)
LONG = Scalar("long", "Long", "int", 64, True)
ULONG = Scalar("ulong", "ULong", "int", 64, False)
FLOAT = Scalar("float", "Float", "float")
HALF = Scalar("Half", "Half", "half", 16)

INTEGERS = (BYTE, SBYTE, SHORT, USHORT, INT, UINT, LONG, ULONG)
SCALARS = INTEGERS + (FLOAT, HALF)


def kind_of(type_name: str) -> str:
    """The ResultKind of a slot that holds a value of this C# type."""
    if type_name == "bool":
        return "Integer"
    if type_name == "float":
        return "Float"
    if type_name == "Half":
        return "Half"
    return "Integer"


def store(expr: str, type_name: str) -> str:
    """The expression that turns a value of `type_name` into the long of its slot."""
    if type_name == "bool":
        return f"({expr}) ? 1L : 0L"
    if type_name == "float":
        return f"Gpu.AsUInt({expr})"
    if type_name == "Half":
        return f"Gpu.AsUShort({expr})"
    return f"(long)({expr})"


@dataclass
class Slot:
    name: str  # what the report shows: the C# of the slot
    value: str  # the expression whose value is stored
    type: str  # its C# type
    check: str = "Exact"  # Exact, Ftz, Ulp, Unspecified
    ulps: int = 0
    reason: str = ""
    setup: str = ""  # statements that run first (compound assignments)


@dataclass
class Family:
    name: str  # C# identifier of the family; the shader is Conformance{name}
    title: str  # what the report calls it
    element: str  # C# type of the input buffers' elements
    lanes: int  # elements per operand per thread
    prologue: list[str]  # declares x, y, z (and n) from the buffers
    slots: list[Slot] = field(default_factory=list)
    values: str = ""  # the value set of the operands (ConformanceValues), the element type's by default

    def add(self, name: str, type_name: str, check: str = "Exact", ulps: int = 0, value: str | None = None, setup: str = "", reason: str = "") -> None:
        self.slots.append(Slot(name, value if value is not None else name, type_name, check, ulps, reason, setup))


def scalar_prologue(element: str) -> list[str]:
    return [
        f"{element} x = a[i];",
        f"{element} y = b[i];",
        f"{element} z = c[i];",
        "int n = s[i];",
    ]


LANE_NAMES = "XYZW"


def vector_prologue(vector: str, element: str, lanes: int, convert: str = "{0}") -> list[str]:
    lines = []
    for var, buf in (("x", "a"), ("y", "b"), ("z", "c")):
        parts = ", ".join(convert.format(f"{buf}[{lanes} * i + {k}]") for k in range(lanes))
        lines.append(f"{vector} {var} = new {vector}({parts});")
    lines.append("int n = s[i];")
    return lines


# ---- integer operators ---------------------------------------------------------------------------


def division_guard(t: Scalar) -> str:
    """The condition under which `x / y` and `x % y` throw in C#: y == 0, and for int and long also MinValue / -1."""
    if t.signed and t.bits >= 32:
        return f"y == 0 || (x == {t.min} && y == -1)"
    return "y == 0"


def integer_operators(t: Scalar) -> Family:
    f = Family(f"{t.name}Operators", f"{t.cs} operators", t.cs, 1, scalar_prologue(t.cs))
    p = t.promoted
    guard = division_guard(t)
    f.add("+x", p)
    if t.cs != "ulong":
        # -x on a uint is a long in C#; on a ulong it does not compile.
        f.add("-x", "long" if t.cs == "uint" else p)
    f.add("~x", p)
    for op in ("+", "-", "*"):
        f.add(f"x {op} y", p)
    f.add(f"x / y", p, value=f"({guard}) ? ({p})0 : x / y", reason="")
    f.add(f"x % y", p, value=f"({guard}) ? ({p})0 : x % y")
    for op in ("&", "|", "^"):
        f.add(f"x {op} y", p)
    for op in ("<<", ">>", ">>>"):
        f.add(f"x {op} n", p)
    for op in ("==", "!=", "<", "<=", ">", ">="):
        f.add(f"x {op} y", "bool")
    if t.bits < 32:
        # The result of the promoted operation, cast back: wraps at the width of the type.
        for expr in ("x + y", "x - y", "x * y", "x << n", "-x", "~x"):
            f.add(f"({t.cs})({expr})", t.cs)
    # Compound assignments and increments: in C# they convert back to the type of the target on
    # every step (truncating a small integer), and a division by zero still throws.
    k = 0
    for op in ("+=", "-=", "*=", "&=", "|=", "^="):
        f.add(f"t {op} y", t.cs, value=f"t{k}", setup=f"{t.cs} t{k} = x; t{k} {op} y;")
        k += 1
    for op in ("/=", "%="):
        f.add(f"t {op} y", t.cs, value=f"t{k}", setup=f"{t.cs} t{k} = x; if (!({guard})) {{ t{k} {op} y; }}")
        k += 1
    for op in ("<<=", ">>=", ">>>="):
        f.add(f"t {op} n", t.cs, value=f"t{k}", setup=f"{t.cs} t{k} = x; t{k} {op} n;")
        k += 1
    for op in ("t++", "t--", "++t", "--t"):
        # The value of the expression and the variable afterwards, in one slot each.
        f.add(f"{op} (value)", t.cs, value=f"u{k}", setup=f"{t.cs} t{k} = x; {t.cs} u{k} = {op.replace('t', f't{k}')};")
        f.add(f"{op} (variable)", t.cs, value=f"t{k}")
        k += 1
    return f


def integer_intrinsics(t: Scalar) -> Family:
    f = Family(f"{t.name}Intrinsics", f"{t.cs} intrinsics", t.cs, 1, scalar_prologue(t.cs))
    for fn in ("Abs", "CountBits", "LeadingZeroCount", "TrailingZeroCount", "ReverseBits"):
        f.add(f"Gpu.{fn}(x)", t.cs)
    f.add("Gpu.Min(x, y)", t.cs)
    f.add("Gpu.Max(x, y)", t.cs)
    f.add("Gpu.Clamp(x, Gpu.Min(y, z), Gpu.Max(y, z))", t.cs)
    f.add("Gpu.Clamp(x, y, z)", t.cs, value="Gpu.Clamp(x, y, z)")
    f.add("Gpu.RotateLeft(x, n)", t.cs)
    f.add("Gpu.RotateRight(x, n)", t.cs)
    # System.Math. Abs of the minimum of a signed type throws in C#, and inverted Clamp bounds throw:
    # those are pinned on the GPU alone (ConformanceTests.ThrowingDotNetCases_...).
    if t.cs != "ulong":
        # The overload C# picks: Math.Abs(short) for a byte, (int) for a ushort, (long) for a uint.
        abs_type = {"byte": "short", "ushort": "int", "uint": "long"}.get(t.cs, t.cs)
        if t.signed:
            f.add("Math.Abs(x)", abs_type, value=f"x == {t.min} ? ({abs_type})0 : Math.Abs(x)")
        else:
            f.add("Math.Abs(x)", abs_type)
    f.add("Math.Min(x, y)", t.cs)
    f.add("Math.Max(x, y)", t.cs)
    f.add("Math.Clamp(x, Math.Min(y, z), Math.Max(y, z))", t.cs)
    return f


# ---- float and half operators --------------------------------------------------------------------


def float_operators(t: Scalar) -> Family:
    f = Family(f"{t.name}Operators", f"{t.cs} operators", t.cs, 1, scalar_prologue(t.cs))
    arith = "Ftz" if t is FLOAT else "Exact"
    f.add("-x", t.cs)
    f.add("+x", t.cs)
    for op in ("+", "-", "*", "/"):
        f.add(f"x {op} y", t.cs, arith)
    f.add("x % y", t.cs, arith)
    for op in ("==", "!=", "<", "<=", ">", ">="):
        f.add(f"x {op} y", "bool", arith)
    k = 0
    for op in ("+=", "-=", "*=", "/=", "%="):
        f.add(f"t {op} y", t.cs, arith, value=f"t{k}", setup=f"{t.cs} t{k} = x; t{k} {op} y;")
        k += 1
    for op in ("t++", "t--"):
        f.add(f"{op} (variable)", t.cs, arith, value=f"t{k}", setup=f"{t.cs} t{k} = x; {op.replace('t', f't{k}')};")
        k += 1
    if t is FLOAT:
        f.add("x * y + z", t.cs, "Unspecified", reason="the GPU contracts it into one fused multiply-add ([ShaderOptions(FpContract = false)] turns that off); ForCpu rounds twice")
    return f


# ---- float intrinsics: Gpu.* and System.Math / MathF -----------------------------------------------

TRANSCENDENTAL_1 = ("Sin", "Cos", "Tan", "Asin", "Acos", "Atan", "Sinh", "Cosh", "Tanh", "Exp", "Exp2", "Exp10", "Log", "Log2", "Log10")
EXACT_1 = ("Abs", "Sign", "Saturate", "Floor", "Ceil", "Round", "Trunc", "Fract", "Sqrt", "Rsqrt", "Radians", "Degrees")

# The checks of the functions that are not Ftz: Abs and CopySign copy the operand's bits (a subnormal
# passes through unflushed), and Min and Max compare flushed operands but return one of them.
BIT_COPIES = {"Abs": "Exact", "CopySign": "Exact", "Min": "Value", "Max": "Value"}


def gpu_float_intrinsics() -> Family:
    f = Family("FloatIntrinsics", "Gpu float intrinsics", "float", 1, scalar_prologue("float"))
    for fn in EXACT_1:
        f.add(f"Gpu.{fn}(x)", "float", BIT_COPIES.get(fn, "Ftz"))
    for fn in ("Min", "Max", "Fmod", "Step", "CopySign"):
        f.add(f"Gpu.{fn}(x, y)", "float", BIT_COPIES.get(fn, "Ftz"))
    f.add("Gpu.Clamp(x, y, z)", "float", "Value")
    f.add("Gpu.Lerp(x, y, z)", "float", "Near")
    f.add("Gpu.Fma(x, y, z)", "float", "Ftz")
    f.add("Gpu.Smoothstep(x, y, z)", "float", "Near")
    for fn in ("IsNaN", "IsInfinity", "IsFinite"):
        f.add(f"Gpu.{fn}(x)", "bool")
    f.add("Gpu.AsUInt(x)", "uint")
    f.add("Gpu.AsInt(x)", "int")
    f.add("Gpu.AsUInt(Gpu.AsFloat(Gpu.AsUInt(x) ^ 0x80000000u))", "uint")
    for fn in TRANSCENDENTAL_1:
        f.add(f"Gpu.{fn}(x)", "float", "Ulp", 4)
    f.add("Gpu.Atan2(x, y)", "float", "Ulp", 4)
    f.add("Gpu.Pow(x, y)", "float", "Ulp", 4)
    return f


def math_float_intrinsics() -> Family:
    """System.Math, MathF and float statics in a shader: ForCpu runs .NET's implementations."""
    f = Family("MathFloat", "System.Math and MathF on floats", "float", 1, scalar_prologue("float"))
    f.add("MathF.Abs(x)", "float")
    for cls in ("MathF", "Math", "float"):
        f.add(f"{cls}.Max(x, y)", "float", "Value")
        f.add(f"{cls}.Min(x, y)", "float", "Value")
    for cls in ("Math", "float"):
        # Inverted bounds throw ArgumentException in .NET; they are pinned on the GPU alone.
        f.add(f"{cls}.Clamp(x, y, z)", "float", "Value", value=f"y > z ? 0f : {cls}.Clamp(x, y, z)")
    f.add("MathF.Sign(x)", "int", "Ftz", value="float.IsNaN(x) ? 0 : MathF.Sign(x)")
    for fn in ("Sqrt", "Floor", "Ceiling", "Truncate", "Round"):
        f.add(f"MathF.{fn}(x)", "float", "Ftz")
    f.add("MathF.CopySign(x, y)", "float")
    f.add("MathF.FusedMultiplyAdd(x, y, z)", "float", "Ftz")
    f.add("MathF.ScaleB(x, n)", "float", "Ftz")
    f.add("MathF.ILogB(x)", "int", "Ftz")
    f.add("float.IsNaN(x)", "bool")
    f.add("float.IsInfinity(x)", "bool")
    f.add("float.IsFinite(x)", "bool")
    f.add("float.Lerp(x, y, z)", "float", "Near")
    for fn in ("Sin", "Cos", "Tan", "Asin", "Acos", "Atan", "Sinh", "Cosh", "Tanh", "Exp", "Log", "Log2", "Log10"):
        f.add(f"MathF.{fn}(x)", "float", "Ulp", 4)
    f.add("float.Exp2(x)", "float", "Ulp", 4)
    f.add("float.Exp10(x)", "float", "Ulp", 4)
    f.add("MathF.Atan2(x, y)", "float", "Ulp", 4)
    f.add("MathF.Pow(x, y)", "float", "Ulp", 4)
    f.add("MathF.ReciprocalSqrtEstimate(x)", "float", "Unspecified", reason="an estimate by definition: .NET's precision is the CPU's (about 8 bits on arm64), the GPU's rsqrt is precise")
    return f


# ---- vectors ---------------------------------------------------------------------------------------

@dataclass(frozen=True)
class VectorKind:
    prefix: str  # Float, Half, Int, UInt
    element: str  # C# element type
    kind: str  # float, half, int


VECTORS = (
    VectorKind("Float", "float", "float"),
    VectorKind("Half", "Half", "half"),
    VectorKind("Int", "int", "int"),
    VectorKind("UInt", "uint", "int"),
)


def lanes_of(f: Family, name: str, vector_expr: str, element: str, lanes: int, check: str = "Exact", ulps: int = 0, setup: str = "", reason: str = "", lane_type: str | None = None) -> None:
    """Adds one slot per lane of a vector-valued expression."""
    k = len(f.slots)
    var = f"v{k}"
    f.slots.append(Slot(f"{name} .{LANE_NAMES[0]}", f"{var}.{LANE_NAMES[0]}", lane_type or element, check, ulps, reason, setup + f" var {var} = {vector_expr};"))
    for lane in range(1, lanes):
        f.slots.append(Slot(f"{name} .{LANE_NAMES[lane]}", f"{var}.{LANE_NAMES[lane]}", lane_type or element, check, ulps, reason, ""))


def vector_operators(v: VectorKind, lanes: int) -> Family:
    vector = f"{v.prefix}{lanes}"
    f = Family(f"{vector}Operators", f"{vector} operators", v.element, lanes, vector_prologue(vector, v.element, lanes))
    arith = "Ftz" if v.kind == "float" else "Exact"
    if v.kind != "int":
        # Integer vector negation is left out: see ConformanceTests (a Metal compiler issue with
        # negated integer vectors is worked around separately).
        lanes_of(f, "-x", "-x", v.element, lanes)
    lanes_of(f, "x + y", "x + y", v.element, lanes, arith)
    lanes_of(f, "x - y", "x - y", v.element, lanes, arith)
    lanes_of(f, "x * y", "x * y", v.element, lanes, arith)
    if v.kind == "int":
        zero = f"Gpu.Equal(y, 0)"
        if v.element == "int":
            zero += f" | (Gpu.Equal(x, int.MinValue) & Gpu.Equal(y, -1))"
        safe = f"Gpu.Select({zero}, new {vector}(1), y)"
        lanes_of(f, "x / y", f"x / d", v.element, lanes, setup=f"{vector} d = {safe};")
        lanes_of(f, "x % y", f"x % d", v.element, lanes, setup="")
        for op in ("&", "|", "^"):
            lanes_of(f, f"x {op} y", f"x {op} y", v.element, lanes)
        lanes_of(f, "~x", "~x", v.element, lanes)
        lanes_of(f, "x << y (counts per lane)", "x << y", v.element, lanes)
        lanes_of(f, "x >> y (counts per lane)", "x >> y", v.element, lanes)
        lanes_of(f, "x << n", "x << n", v.element, lanes)
        lanes_of(f, "x >> n", "x >> n", v.element, lanes)
    else:
        lanes_of(f, "x / y", "x / y", v.element, lanes, arith)
        lanes_of(f, "x % y", "x % y", v.element, lanes, arith)
    scalar = f"y.X"
    lanes_of(f, "x + y.X", f"x + {scalar}", v.element, lanes, arith)
    lanes_of(f, "y.X - x", f"{scalar} - x", v.element, lanes, arith)
    lanes_of(f, "x * y.X", f"x * {scalar}", v.element, lanes, arith)
    for op in ("<", "<=", ">", ">="):
        lanes_of(f, f"x {op} y", f"x {op} y", v.element, lanes, arith, lane_type="bool")
    lanes_of(f, "Gpu.Equal(x, y)", "Gpu.Equal(x, y)", v.element, lanes, arith, lane_type="bool")
    lanes_of(f, "Gpu.NotEqual(x, y)", "Gpu.NotEqual(x, y)", v.element, lanes, arith, lane_type="bool")
    # The comparison sees flushed operands; the component it picks is copied unflushed.
    lanes_of(f, "Gpu.Select(x < y, x, z)", "Gpu.Select(x < y, x, z)", v.element, lanes, arith if v.kind != "float" else "Value")
    lanes_of(f, "t += y", "t", v.element, lanes, arith, setup=f"{vector} t = x; t += y;")
    lanes_of(f, "t *= y", "t2", v.element, lanes, arith, setup=f"{vector} t2 = x; t2 *= y;")
    return f


def bool_vector_operators(lanes: int) -> Family:
    vector = f"Bool{lanes}"
    f = Family(f"{vector}Operators", f"{vector} operators", "int", lanes, vector_prologue(vector, "int", lanes, "{0} != 0"), values="bool")
    lanes_of(f, "!x", "!x", "bool", lanes)
    for op in ("&", "|", "^"):
        lanes_of(f, f"x {op} y", f"x {op} y", "bool", lanes)
    f.add("Gpu.Any(x)", "bool")
    f.add("Gpu.All(x)", "bool")
    lanes_of(f, "Gpu.Select(x, y, z)", "Gpu.Select(x, y, z)", "bool", lanes)
    return f


# ---- vector intrinsics --------------------------------------------------------------------------

def vector_intrinsics(v: VectorKind, lanes: int) -> Family:
    vector = f"{v.prefix}{lanes}"
    f = Family(f"{vector}Intrinsics", f"{vector} intrinsics", v.element, lanes, vector_prologue(vector, v.element, lanes))
    exact = "Ftz" if v.kind == "float" else "Exact"
    ulps = 4 if v.kind == "float" else 1
    def check(fn: str) -> str:
        if fn in ("Min", "Max", "Clamp"):
            return "Value"
        if fn in ("Lerp", "Smoothstep"):
            return "Near" if v.kind == "float" else "Exact"
        return BIT_COPIES.get(fn, exact) if v.kind == "float" else exact
    for fn in EXACT_1:
        lanes_of(f, f"Gpu.{fn}(x)", f"Gpu.{fn}(x)", v.element, lanes, check(fn))
    for fn in ("Min", "Max", "Fmod", "Step", "CopySign"):
        lanes_of(f, f"Gpu.{fn}(x, y)", f"Gpu.{fn}(x, y)", v.element, lanes, check(fn))
    for fn in ("Clamp", "Lerp", "Fma", "Smoothstep"):
        lanes_of(f, f"Gpu.{fn}(x, y, z)", f"Gpu.{fn}(x, y, z)", v.element, lanes, check(fn))
    for fn in ("IsNaN", "IsInfinity", "IsFinite"):
        lanes_of(f, f"Gpu.{fn}(x)", f"Gpu.{fn}(x)", v.element, lanes, lane_type="bool")
    for fn in TRANSCENDENTAL_1:
        lanes_of(f, f"Gpu.{fn}(x)", f"Gpu.{fn}(x)", v.element, lanes, "Ulp", ulps)
    lanes_of(f, "Gpu.Atan2(x, y)", "Gpu.Atan2(x, y)", v.element, lanes, "Ulp", ulps)
    lanes_of(f, "Gpu.Pow(x, y)", "Gpu.Pow(x, y)", v.element, lanes, "Ulp", ulps)
    # The geometric functions.
    geometric = "Near" if v.kind == "float" else "Ulp"
    f.add("Gpu.Dot(x, y)", v.element, geometric, ulps)
    f.add("Gpu.Length(x)", v.element, geometric, ulps)
    f.add("Gpu.Distance(x, y)", v.element, geometric, ulps)
    lanes_of(f, "Gpu.Normalize(x)", "Gpu.Normalize(x)", v.element, lanes, geometric, ulps)
    lanes_of(f, "Gpu.Reflect(x, y)", "Gpu.Reflect(x, y)", v.element, lanes, geometric, ulps)
    if lanes == 3:
        lanes_of(f, "Gpu.Cross(x, y)", "Gpu.Cross(x, y)", v.element, lanes, geometric, ulps)
    if v.kind == "float" and lanes == 4:
        f.add("Gpu.PackUnorm4x8(x)", "uint")
        lanes_of(f, "Gpu.UnpackUnorm4x8(Gpu.AsUInt(x.X))", "Gpu.UnpackUnorm4x8(Gpu.AsUInt(x.X))", "float", lanes)
    return f


# ---- conversions -------------------------------------------------------------------------------

def conversions(source: Scalar) -> Family:
    f = Family(f"{source.name}Conversions", f"conversions from {source.cs}", source.cs, 1, scalar_prologue(source.cs))
    for target in SCALARS:
        if target is source:
            continue
        # A float source flushes its subnormals first on the GPU: (double)... is not in a shader, so
        # every conversion of a float subnormal gives the conversion of zero.
        check = "Ftz" if source is FLOAT else "Exact"
        f.add(f"({target.cs})x", target.cs, check)
    return f


VECTOR_CONVERSION_SOURCES = ("Float", "Half", "Int", "UInt")


def vector_conversions(prefix: str) -> Family:
    v = next(k for k in VECTORS if k.prefix == prefix)
    vector = f"{prefix}4"
    f = Family(f"{vector}Conversions", f"conversions from {vector}", v.element, 4, vector_prologue(vector, v.element, 4))
    for target in VECTORS:
        if target.prefix == prefix:
            continue
        check = "Ftz" if prefix == "Float" else "Exact"
        lanes_of(f, f"({target.prefix}4)x", f"({target.prefix}4)x", target.element, 4, check)
    return f


# ---- emission ------------------------------------------------------------------------------------

def families() -> list[Family]:
    result: list[Family] = []
    for t in INTEGERS:
        result.append(integer_operators(t))
        result.append(integer_intrinsics(t))
    result.append(float_operators(FLOAT))
    result.append(float_operators(HALF))
    result.append(gpu_float_intrinsics())
    result.append(math_float_intrinsics())
    for v in VECTORS:
        for lanes in (2, 3, 4):
            result.append(vector_operators(v, lanes))
    for lanes in (2, 3, 4):
        result.append(bool_vector_operators(lanes))
    for v in VECTORS[:2]:
        for lanes in (3, 4):
            result.append(vector_intrinsics(v, lanes))
    for t in SCALARS:
        result.append(conversions(t))
    for prefix in VECTOR_CONVERSION_SOURCES:
        result.append(vector_conversions(prefix))
    return result


def cs_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit(all_families: list[Family]) -> str:
    out: list[str] = [HEADER]
    out.append("using System;")
    out.append("")
    out.append("namespace SharpCompute.Tests.Conformance;")
    out.append("")
    for f in all_families:
        shader = f"Conformance{f.name}"
        out.append(f"/// <summary>The {f.title}: {len(f.slots)} slots per thread (see <see cref=\"ConformanceFamilies.{f.name}\"/>).</summary>")
        out.append("[GeneratedComputeShaderDescriptor]")
        out.append(f"public readonly partial struct {shader}(ReadOnlyBuffer<{f.element}> a, ReadOnlyBuffer<{f.element}> b, ReadOnlyBuffer<{f.element}> c, ReadOnlyBuffer<int> s, ReadWriteBuffer<long> output) : IComputeShader")
        out.append("{")
        out.append(f"    public const int Slots = {len(f.slots)};")
        out.append("")
        out.append("    public void Execute()")
        out.append("    {")
        out.append("        int i = ThreadIds.X;")
        out.append("        int o = i * Slots;")
        for line in f.prologue:
            out.append("        " + line)
        for k, slot in enumerate(f.slots):
            if slot.setup:
                out.append("        " + slot.setup.strip())
            out.append(f"        output[o + {k}] = {store(slot.value, slot.type)};")
        out.append("    }")
        out.append("}")
        out.append("")
    out.append("/// <summary>The families of the conformance suite, one per shader above.</summary>")
    out.append("internal static partial class ConformanceFamilies")
    out.append("{")
    for f in all_families:
        shader = f"Conformance{f.name}"
        out.append(f"    public static readonly ConformanceFamily<{f.element}> {f.name} = new(")
        out.append(f"        {cs_string(f.title)},")
        out.append(f"        {cs_string(f.values or f.element)},")
        out.append(f"        {f.lanes},")
        out.append("        [")
        for slot in f.slots:
            args = [cs_string(slot.name), f"ResultKind.{kind_of(slot.type)}", f"Check.{slot.check}"]
            if slot.ulps or slot.reason:
                args.append(str(slot.ulps))
            if slot.reason:
                args.append(cs_string(slot.reason))
            out.append(f"            new({', '.join(args)}),")
        out.append("        ],")
        out.append(f"        static (device, cpu, threads, a, b, c, s, output) => ConformanceHarness.Dispatch(device, cpu, threads, new {shader}(a, b, c, s, output)));")
        out.append("")
    out.append(f"    /// <summary>Every family, for the coverage summary.</summary>")
    out.append(f"    public static readonly IConformanceFamily[] All =")
    out.append("    [")
    for f in all_families:
        out.append(f"        {f.name},")
    out.append("    ];")
    out.append("}")
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the generated file is out of date")
    args = parser.parse_args()
    text = emit(families())
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print(f"stale: {OUTPUT.relative_to(ROOT)} (run python3 -I tools/gen_conformance.py)")
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
