# Vector core: fields, constructors, X/Y/Z/W, operators, conversions, ToString
# --------------------------------------------------------------------------------------------


def compositions(n: int) -> list[tuple[int, ...]]:
    """All ordered ways to write n as a sum of parts in 1..n-1 (MSL composite constructors)."""
    result: list[tuple[int, ...]] = []

    def rec(remaining: int, acc: tuple[int, ...]) -> None:
        if remaining == 0:
            result.append(acc)
            return
        for part in range(1, min(remaining, n - 1) + 1):
            rec(remaining - part, acc + (part,))

    rec(n, ())
    return result


def gen_constructors(kind: Kind, n: int) -> list[str]:
    t = kind.vec(n)
    s = kind.scalar
    lines: list[str] = []

    # Broadcast.
    lines.append(f"    /// <summary>Sets every component to <paramref name=\"value\"/> (MSL <c>{kind.msl_vec(n)}(value)</c>).</summary>")
    lines.append(f"    public {t}({s} value)")
    lines.append("    {")
    for i in range(n):
        lines.append(f"        {field(i)} = value;")
    lines.append("    }")
    lines.append("")

    # Per-component and composites, in MSL constructor order.
    for parts in sorted(compositions(n), key=lambda p: (len(p) != n, p)):
        params: list[str] = []
        assigns: list[str] = []
        offset = 0
        for part in parts:
            name = COMPONENTS[offset : offset + part]
            if part == 1:
                params.append(f"{s} {name}")
                assigns.append(f"        {field(offset)} = {name};")
            else:
                params.append(f"{kind.vec(part)} {name}")
                for j in range(part):
                    assigns.append(f"        {field(offset + j)} = {name}.{prop(j)};")
            offset += part
        if len(parts) == n:
            lines.append(f"    /// <summary>Creates a vector from its components (MSL <c>{kind.msl_vec(n)}(...)</c>).</summary>")
        else:
            lines.append(f"    /// <summary>Composite constructor, filling components in order (MSL <c>{kind.msl_vec(n)}(...)</c>).</summary>")
        lines.append(f"    public {t}({', '.join(params)})")
        lines.append("    {")
        lines.extend(assigns)
        lines.append("    }")
        lines.append("")
    return lines


def binary_ops(kind: Kind) -> list[tuple[str, str]]:
    ops = [("+", "Componentwise addition."), ("-", "Componentwise subtraction."),
           ("*", "Componentwise multiplication.")]
    if kind.is_float:
        ops.append(("/", "Componentwise division."))
        ops.append(("%", "Componentwise C <c>fmod</c> (<see cref=\"Gpu.Fmod(float, float)\"/>): truncated remainder with "
                         "the sign of the dividend. Translated to <c>metal::fmod</c>, which matches bit for bit under "
                         "precise math (MSL has no float <c>%</c>)."))
    else:
        throws = ("Throws <see cref=\"System.DivideByZeroException\"/> for a zero divisor"
                  + (" and <see cref=\"System.OverflowException\"/> for <c>int.MinValue</c> and <c>-1</c>" if kind is INT else "")
                  + " (.NET behaviour, even in an unchecked context); MSL does not trap.")
        ops.append(("/", "Componentwise truncating division. " + throws))
        ops.append(("%", "Componentwise truncated remainder (sign of the dividend). " + throws))
        ops += [("&", "Componentwise bitwise AND."), ("|", "Componentwise bitwise OR."),
                ("^", "Componentwise bitwise XOR.")]
    return ops


def gen_operators(kind: Kind, n: int) -> list[str]:
    t = kind.vec(n)
    s = kind.scalar
    r = range(n)
    lines: list[str] = []

    def op(doc: str, sig: str, body: str) -> None:
        lines.append(f"    /// <summary>{doc}</summary>")
        lines.append(f"    public static {t} operator {sig} => {body};")
        lines.append("")

    if kind.is_float or kind is INT:
        op("Componentwise negation.", f"-({t} value)", new(kind, n, [f"-value.{field(i)}" for i in r]))
    if kind.is_integer:
        op("Componentwise bitwise complement.", f"~({t} value)", new(kind, n, [f"~value.{field(i)}" for i in r]))

    for sym, doc in binary_ops(kind):
        if kind.is_float and sym == "%":
            def apply(a: str, b: str) -> str:
                return f"Gpu.Fmod({a}, {b})"
        else:
            def apply(a: str, b: str, sym: str = sym) -> str:
                return f"{a} {sym} {b}"
        op(doc, f"{sym}({t} left, {t} right)", new(kind, n, [apply(f"left.{field(i)}", f"right.{field(i)}") for i in r]))
        op(doc, f"{sym}({t} left, {s} right)", new(kind, n, [apply(f"left.{field(i)}", "right") for i in r]))
        op(doc, f"{sym}({s} left, {t} right)", new(kind, n, [apply("left", f"right.{field(i)}") for i in r]))

    if kind.is_integer:
        count_cast = "(int)" if kind is UINT else ""
        for sym, what in (("<<", "left shift"), (">>", "arithmetic right shift" if kind is INT else "logical right shift")):
            doc = f"Componentwise {what}. Like C#, the shift count is masked to 0..31 (out-of-range counts are UB in MSL)."
            op(doc, f"{sym}({t} value, {t} count)",
               new(kind, n, [f"value.{field(i)} {sym} {count_cast}count.{field(i)}" for i in r]))
            op(doc, f"{sym}({t} value, int count)", new(kind, n, [f"value.{field(i)} {sym} count" for i in r]))
    return lines


def gen_conversions(kind: Kind, n: int) -> list[str]:
    t = kind.vec(n)
    lines: list[str] = []
    for other in KINDS:
        if other is kind:
            continue
        src = other.vec(n)
        if kind.is_float:
            doc = f"Converts each component to <c>float</c> (MSL <c>{kind.msl_vec(n)}(v)</c>)."
        elif other.is_float:
            doc = (f"Converts each component to <c>{kind.scalar}</c>, rounding toward zero and saturating "
                   f"out-of-range values; NaN becomes 0 (MSL <c>{kind.msl_vec(n)}(v)</c>).")
        else:
            doc = f"Reinterprets each component's bits as <c>{kind.scalar}</c> (MSL <c>{kind.msl_vec(n)}(v)</c>)."
        exprs = [f"({kind.scalar})value.{prop(i)}" for i in range(n)]
        body = f"unchecked(new {t}({', '.join(exprs)}))"
        lines.append(f"    /// <summary>{doc}</summary>")
        lines.append(f"    public static explicit operator {t}({src} value) => {body};")
        lines.append("")
    return lines


def gen_core(kind: Kind, n: int) -> str:
    t = kind.vec(n)
    msl = kind.msl_vec(n)
    out: list[str] = [HEADER]
    out.append("using System.Globalization;")
    out.append("using System.Runtime.InteropServices;")
    out.append("")
    out.append("namespace SharpCompute;")
    out.append("")
    out.append(f"/// <summary>MSL <c>{msl}</c>. Tightly packed (4-byte alignment) to match <c>packed_{msl}</c>.</summary>")
    out.append("/// <remarks>")
    out.append("/// Members map 1:1 to MSL: constructors to <c>" + msl + "(...)</c>, properties to swizzles,")
    out.append("/// operators to native operators. There is deliberately no <c>==</c>/<c>!=</c>: in MSL they")
    out.append("/// return a <c>bool" + str(n) + "</c>, not a <c>bool</c>.")
    out.append("/// </remarks>")
    out.append(f"[MslType(\"{msl}\", Packed = \"packed_{msl}\")]")
    out.append("[StructLayout(LayoutKind.Sequential, Pack = 4)]")
    out.append(f"public partial struct {t}")
    out.append("{")
    for i in range(n):
        out.append(f"    private {kind.scalar} {field(i)};")
    out.append("")
    out.extend(gen_constructors(kind, n))
    for i in range(n):
        out.append(f"    /// <summary>The {COMPONENTS[i]} component.</summary>")
        out.append(f"    public {kind.scalar} {prop(i)} {{ readonly get => {field(i)}; set => {field(i)} = value; }}")
        out.append("")
    out.extend(gen_operators(kind, n))
    out.extend(gen_conversions(kind, n))
    fmt = ", ".join("{" + field(i) + "}" for i in range(n))
    out.append("    /// <summary>Formats the vector as <c>&lt;x, y, ...&gt;</c> using the invariant culture.</summary>")
    out.append(f"    public readonly override string ToString() => string.Create(CultureInfo.InvariantCulture, $\"<{fmt}>\");")
    out.append("}")
    return "\n".join(out) + "\n"


