def swizzles(n: int) -> list[tuple[int, ...]]:
    result: list[tuple[int, ...]] = []
    for length in (2, 3, 4):
        result.extend(itertools.product(range(n), repeat=length))
    return result


def gen_swizzles(kind: Kind, n: int) -> str:
    t = kind.vec(n)
    out: list[str] = [HEADER]
    out.append("using System.ComponentModel;")
    out.append("")
    out.append("namespace SharpCompute;")
    out.append("")
    out.append(f"public partial struct {t}")
    out.append("{")
    for sw in swizzles(n):
        name = "".join(prop(i) for i in sw)
        rt = kind.vec(len(sw))
        get = f"new {rt}({', '.join(field(i) for i in sw)})"
        distinct = len(set(sw)) == len(sw)
        ascending = distinct and list(sw) == sorted(sw)
        if not ascending:
            # Keep IntelliSense usable: only in-order swizzles (XY, XZ, YZW, XYZW, ...) are listed.
            out.append("    [EditorBrowsable(EditorBrowsableState.Never)]")
        if distinct:
            sets = " ".join(f"{field(c)} = value.{prop(j)};" for j, c in enumerate(sw))
            out.append(f"    public {rt} {name} {{ readonly get => {get}; set {{ {sets} }} }}")
        else:
            out.append(f"    public readonly {rt} {name} => {get};")
        out.append("")
    if out[-1] == "":
        out.pop()
    out.append("}")
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------------------------
# Matrices. Float2x2 and Float3x3 are locals only ([MslType] without Packed: MSL pads float3x3
# columns to 16 bytes and aligns float2x2 to 8). Float4x4 has no padding, 64 bytes of floats on
# both sides, so it may cross the CPU/GPU boundary; its Packed type is a prelude struct of four
# packed_float4 columns (4-byte instead of 16-byte alignment), which the generator converts with
# the prelude's __ms_unpack / __ms_pack on every load and store (see prelude_msl).
# --------------------------------------------------------------------------------------------

MATRIX_SIZES = (2, 3, 4)

# Matrix sizes whose C# layout is exactly the MSL layout, mapped to their boundary (Packed) type.
PACKED_MATRICES = {4: "__ms_packed_float4x4"}


def mat(n: int) -> str:
    return f"Float{n}x{n}"


def mfield(r: int, c: int) -> str:
    return f"_m{r}{c}"


def fma_chain(products: list[tuple[str, str]]) -> str:
    """Sum of products as an fma chain in order: fma(an, bn, ... fma(a1, b1, a0 * b0))."""
    (a0, b0), rest = products[0], products[1:]
    expr = f"{a0} * {b0}"
    for a, b in rest:
        expr = f"MathF.FusedMultiplyAdd({a}, {b}, {expr})"
    return expr


def gen_matrix(n: int) -> str:
    t, msl, row = mat(n), f"float{n}x{n}", FLOAT.vec(n)
    rc = [(r, c) for r in range(n) for c in range(n)]
    out: list[str] = [HEADER]
    out.append("using System.Globalization;")
    out.append("using System.Runtime.InteropServices;")
    out.append("")
    out.append("namespace SharpCompute;")
    out.append("")
    packed = PACKED_MATRICES.get(n)
    out.append(f"/// <summary>MSL <c>{msl}</c>, built from <b>rows</b> (HLSL/ComputeSharp convention).</summary>")
    out.append("/// <remarks>")
    out.append(f"/// The generator passes the constructor arguments unchanged to MSL's <c>{msl}(...)</c>, which takes")
    out.append(f"/// <b>columns</b>, so the MSL value is the transpose of this matrix. <see cref=\"Gpu.Mul({row}, {t})\"/>")
    out.append("/// compensates by swapping its operands, so every result has HLSL semantics with no explicit transpose.")
    if packed:
        out.append(f"/// Unlike the smaller matrices it can cross the CPU/GPU boundary (buffer elements, constants,")
        out.append(f"/// struct fields): both sides store {n * n} floats with no padding, the C# rows where MSL keeps its")
        out.append(f"/// columns, which is the same transpose the constructor applies. The memory layout is also that of")
        out.append("/// <c>System.Numerics.Matrix4x4</c> (row-major, row vectors), so the two can be reinterpreted.")
        out.append(f"/// In MSL the boundary type is the prelude's <c>{packed}</c>: four <c>packed_float4</c> columns,")
        out.append(f"/// 4-byte aligned where <c>{msl}</c> is 16-byte aligned, so it packs next to other fields like the")
        out.append("/// vectors do. The generator converts on every load and store (<c>__ms_unpack</c>, <c>__ms_pack</c>).")
    else:
        out.append("/// Locals only in v1: there is no <c>Packed</c> layout, so a matrix in a buffer, the constants or a")
        out.append("/// struct field is a generator diagnostic.")
    out.append("/// There is no unary minus (invalid MSL; write <c>m * -1f</c>),")
    out.append("/// no matrix <c>*</c> operator (HLSL's is componentwise, MSL's is a product; use <c>Gpu.Mul</c>) and")
    out.append("/// no element access in v1.")
    out.append("/// </remarks>")
    out.append(f"[MslType(\"{msl}\", Packed = \"{packed}\")]" if packed else f"[MslType(\"{msl}\")]")
    out.append("[StructLayout(LayoutKind.Sequential, Pack = 4)]" if packed else "[StructLayout(LayoutKind.Sequential)]")
    out.append(f"public partial struct {t}")
    out.append("{")
    out.append("    // Row-major CPU storage: _mRC is row R, column C.")
    for r, c in rc:
        out.append(f"    internal float {mfield(r, c)};")
    out.append("")
    out.append(f"    /// <summary>Creates a matrix from its elements in row-major order (MSL <c>{msl}(...)</c>, which reads them as columns).</summary>")
    out.append(f"    public {t}({', '.join(f'float m{r}{c}' for r, c in rc)})")
    out.append("    {")
    for r, c in rc:
        out.append(f"        {mfield(r, c)} = m{r}{c};")
    out.append("    }")
    out.append("")
    out.append(f"    /// <summary>Creates a matrix from its rows (MSL <c>{msl}(...)</c>, which reads them as columns).</summary>")
    out.append(f"    public {t}({', '.join(f'{row} row{r}' for r in range(n))})")
    out.append("    {")
    for r, c in rc:
        out.append(f"        {mfield(r, c)} = row{r}.{prop(c)};")
    out.append("    }")
    out.append("")

    def op(doc: str, sig: str, exprs: list[str]) -> None:
        out.append(f"    /// <summary>{doc}</summary>")
        out.append(f"    public static {t} operator {sig} => new {t}({', '.join(exprs)});")
        out.append("")

    op("Componentwise addition.", f"+({t} left, {t} right)", [f"left.{mfield(r, c)} + right.{mfield(r, c)}" for r, c in rc])
    op("Componentwise subtraction.", f"-({t} left, {t} right)", [f"left.{mfield(r, c)} - right.{mfield(r, c)}" for r, c in rc])
    op("Multiplies every element by a scalar.", f"*({t} left, float right)", [f"left.{mfield(r, c)} * right" for r, c in rc])
    op("Multiplies every element by a scalar.", f"*(float left, {t} right)", [f"left * right.{mfield(r, c)}" for r, c in rc])
    op("Divides every element by a scalar.", f"/({t} left, float right)", [f"left.{mfield(r, c)} / right" for r, c in rc])

    rows = ", ".join("(" + ", ".join("{" + mfield(r, c) + "}" for c in range(n)) + ")" for r in range(n))
    out.append("    /// <summary>Formats the rows as <c>[(m00, m01), (m10, m11)]</c> using the invariant culture.</summary>")
    out.append(f"    public readonly override string ToString() => string.Create(CultureInfo.InvariantCulture, $\"[{rows}]\");")
    out.append("}")
    return "\n".join(out) + "\n"


def gen_gpu_matrices() -> str:
    out: list[str] = [HEADER]
    out.append("using System;")
    out.append("")
    out.append("namespace SharpCompute;")
    out.append("")
    out.append("public static partial class Gpu")
    out.append("{")
    out.append("    // HLSL mul() with row vectors. The MSL matrix is the transpose of the C# one (see Float2x2), so")
    out.append("    // [MslBinaryOperator(\"*\", SwapOperands = true)] emits mul(a, b) as (b * a): mul(v, M) -> (m * v),")
    out.append("    // mul(M, v) -> (v * m), mul(A, B) -> (b * a). Sums are fma chains in index order, as on Apple GPUs.")
    out.append("")
    attr = "    [MslBinaryOperator(\"*\", SwapOperands = true)]"
    for n in MATRIX_SIZES:
        t, v = mat(n), FLOAT.vec(n)
        idx = range(n)
        out.append("    /// <summary>HLSL <c>mul(v, m)</c>: row vector times matrix, <c>result[j] = sum_k v[k] * m[k][j]</c>. Emitted as <c>(m * v)</c>.</summary>")
        out.append(attr)
        comps = [fma_chain([(f"v.{prop(k)}", f"m.{mfield(k, j)}") for k in idx]) for j in idx]
        out.append(f"    public static {v} Mul({v} v, {t} m) => new {v}(")
        out.append("        " + ",\n        ".join(comps) + ");")
        out.append("")
        out.append("    /// <summary>HLSL <c>mul(m, v)</c>: matrix times column vector, <c>result[i] = sum_k m[i][k] * v[k]</c>. Emitted as <c>(v * m)</c>.</summary>")
        out.append(attr)
        comps = [fma_chain([(f"v.{prop(k)}", f"m.{mfield(i, k)}") for k in idx]) for i in idx]
        out.append(f"    public static {v} Mul({t} m, {v} v) => new {v}(")
        out.append("        " + ",\n        ".join(comps) + ");")
        out.append("")
        out.append("    /// <summary>HLSL <c>mul(a, b)</c>: matrix product, <c>result[i][j] = sum_k a[i][k] * b[k][j]</c>. Emitted as <c>(b * a)</c>.</summary>")
        out.append(attr)
        comps = [fma_chain([(f"a.{mfield(i, k)}", f"b.{mfield(k, j)}") for k in idx]) for i in idx for j in idx]
        out.append(f"    public static {t} Mul({t} a, {t} b) => new {t}(")
        out.append("        " + ",\n        ".join(comps) + ");")
        out.append("")
    out.append("    // transpose and determinant commute with the C#/MSL transpose convention: the MSL transpose of")
    out.append("    // the transposed matrix is the transposed C# transpose, and det(M) == det(transpose(M)).")
    out.append("")
    for n in MATRIX_SIZES:
        t = mat(n)
        out.append("    /// <summary>The transpose: rows become columns (<c>result[i][j] = m[j][i]</c>). Exact.</summary>")
        out.append("    [MslIntrinsic(\"metal::transpose\")]")
        out.append(f"    public static {t} Transpose({t} m) => new {t}(")
        out.append("        " + ",\n        ".join(", ".join(f"m.{mfield(c, r)}" for c in range(n)) for r in range(n)) + ");")
        out.append("")
    for n in MATRIX_SIZES:
        t = mat(n)
        out.append("    /// <summary>")
        out.append("    /// The determinant, by cofactor expansion with fused multiply-adds. The GPU evaluates the same")
        out.append("    /// polynomial in its own order, so results agree to rounding (a few ULP of the largest term),")
        out.append("    /// not bit for bit; a nearly singular matrix can differ in every digit, as with any determinant.")
        out.append("    /// </summary>")
        out.append("    [MslIntrinsic(\"metal::determinant\")]")
        if n == 2:
            out.append(f"    public static float Determinant({t} m) => Det2(m._m00, m._m01, m._m10, m._m11);")
        elif n == 3:
            out.append(f"    public static float Determinant({t} m) => Det3(")
            out.append("        m._m00, m._m01, m._m02,")
            out.append("        m._m10, m._m11, m._m12,")
            out.append("        m._m20, m._m21, m._m22);")
        else:
            # Expansion along the first row; each minor is a 3x3 determinant of the other rows.
            out.append(f"    public static float Determinant({t} m)")
            out.append("    {")
            for c in range(4):
                cols = [k for k in range(4) if k != c]
                rows = ",\n            ".join(", ".join(f"m.{mfield(r, k)}" for k in cols) for r in (1, 2, 3))
                out.append(f"        float c{c} = Det3(")
                out.append(f"            {rows});")
            out.append("        return MathF.FusedMultiplyAdd(m._m00, c0, -(m._m01 * c1)) + MathF.FusedMultiplyAdd(m._m02, c2, -(m._m03 * c3));")
            out.append("    }")
        out.append("")
    out.append("    private static float Det2(float a, float b, float c, float d) => MathF.FusedMultiplyAdd(a, d, -(b * c));")
    out.append("")
    out.append("    private static float Det3(float a, float b, float c, float d, float e, float f, float g, float h, float i) =>")
    out.append("        MathF.FusedMultiplyAdd(a, Det2(e, f, h, i), MathF.FusedMultiplyAdd(-b, Det2(d, f, g, i), c * Det2(d, e, g, h)));")
    out.append("}")
    return "\n".join(out) + "\n"


