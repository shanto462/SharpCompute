def gen_gpu() -> str:
    out: list[str] = [HEADER]
    out.append("using System;")
    out.append("")
    out.append("namespace SharpCompute;")
    out.append("")
    out.append("public static partial class Gpu")
    out.append("{")

    def method(msl: str, ret: str, name: str, params: list[str], body: str) -> None:
        out.append(f"    [MslIntrinsic(\"metal::{msl}\")]")
        out.append(f"    public static {ret} {name}({', '.join(params)}) => {body};")
        out.append("")

    for f in FUNCS:
        out.append(f"    // {f.name} -> metal::{f.msl} (componentwise)")
        out.append("")
        for kind in f.kinds:
            for n in WIDTHS:
                t = kind.vec(n)
                for scalars in ((),) + f.mixed:
                    params = [f"{kind.scalar if i in scalars else t} {p}" for i, p in enumerate(f.params)]
                    comps = []
                    for c in range(n):
                        args = [p if i in scalars else f"{p}.{prop(c)}" for i, p in enumerate(f.params)]
                        comps.append(f"{f.name}({', '.join(args)})")
                    method(f.msl, t, f.name, params, f"new {t}({', '.join(comps)})")

    out.append("    // MSL prelude helpers (see MslPrelude). Same constant and single multiply as the MSL helper.")
    out.append("")
    for f in PRELUDE_SCALES:
        out.append(f"    /// <summary>{f.doc}.</summary>")
        out.append(f"    [MslIntrinsic(\"{f.msl}\")]")
        out.append(f"    public static float {f.name}(float x) => x * {f.constant};")
        out.append("")
        for n in WIDTHS:
            t = FLOAT.vec(n)
            out.append(f"    /// <summary>{f.doc}, componentwise.</summary>")
            out.append(f"    [MslIntrinsic(\"{f.msl}\")]")
            out.append(f"    public static {t} {f.name}({t} x) => new {t}({', '.join(f'{f.name}(x.{prop(i)})' for i in range(n))});")
            out.append("")

    out.append("    // Geometric functions (float vectors only; MSL has no scalar overloads). Evaluated the way")
    out.append("    // Apple GPUs evaluate them under precise math (bit-exact except for subnormal flushing):")
    out.append("    // dot is an fma chain in component order; length/normalize scale by an exact power of two.")
    out.append("")

    def comps(v: str, n: int) -> list[str]:
        return [f"{v}.{prop(i)}" for i in range(n)]

    def fma_chain(a: list[str], b: list[str]) -> str:
        expr = f"{a[0]} * {b[0]}"
        for x, y in zip(a[1:], b[1:]):
            expr = f"MathF.FusedMultiplyAdd({x}, {y}, {expr})"
        return expr

    def max_abs(v: str, n: int) -> str:
        expr = f"MathF.Abs({v}.X)"
        for c in comps(v, n)[1:]:
            expr = f"MathF.Max({expr}, MathF.Abs({c}))"
        return expr

    def block(msl: str, ret: str, name: str, params: list[str], body: list[str], doc: str) -> None:
        out.append(f"    /// <summary>{doc}</summary>")
        out.append(f"    [MslIntrinsic(\"metal::{msl}\")]")
        out.append(f"    public static {ret} {name}({', '.join(params)})")
        out.append("    {")
        out.extend(("        " + line) if line else "" for line in body)
        out.append("    }")
        out.append("")

    for n in WIDTHS:
        t = FLOAT.vec(n)
        out.append("    /// <summary>Dot product, evaluated as an fma chain in component order (as on Apple GPUs).</summary>")
        method("dot", "float", "Dot", [f"{t} x", f"{t} y"], fma_chain(comps("x", n), comps("y", n)))
    for n in WIDTHS:
        t = FLOAT.vec(n)
        block("length", "float", "Length", [f"{t} x"], [
            f"float m = {max_abs('x', n)};",
            "if (m == 0f || !float.IsFinite(m))",
            "{",
            "    return Sqrt(Dot(x, x)); // 0, +inf or NaN",
            "}",
            "",
            "int e = MathF.ILogB(m);",
            "Float" + str(n) + " s = ScaleB(x, -e);",
            "return MathF.ScaleB(Sqrt(Dot(s, s)), e);",
        ], "Euclidean length. Scales by an exact power of two first, so it neither overflows nor underflows "
           "(<c>length(0, 0, FLT_MAX) == FLT_MAX</c>).")
    for n in WIDTHS:
        t = FLOAT.vec(n)
        out.append("    /// <summary><c>length(x - y)</c>.</summary>")
        method("distance", "float", "Distance", [f"{t} x", f"{t} y"], "Length(x - y)")
    for n in WIDTHS:
        t = FLOAT.vec(n)
        block("normalize", t, "Normalize", [f"{t} x"], [
            f"float m = {max_abs('x', n)};",
            "if (m == 0f)",
            "{",
            "    return x; // zero vector -> itself, signed zeros kept (as on Apple GPUs)",
            "}",
            "",
            "if (!float.IsFinite(m))",
            "{",
            f"    return new {t}(float.NaN); // any infinity or NaN -> NaN (as on Apple GPUs)",
            "}",
            "",
            f"{t} s = ScaleB(x, -MathF.ILogB(m));",
            "return s * Rsqrt(Dot(s, s));",
        ], "Unit vector in the direction of <paramref name=\"x\"/>, scaled by an exact power of two first "
           "so it neither overflows nor underflows. A zero vector is returned unchanged (signed zeros kept, no NaN); any infinite or NaN component gives NaN in every component.")
    for n in WIDTHS:
        t = FLOAT.vec(n)
        body = ", ".join(f"MathF.FusedMultiplyAdd(k, n.{prop(i)}, i.{prop(i)})" for i in range(n))
        block("reflect", t, "Reflect", [f"{t} i", f"{t} n"], [
            "float k = -2f * Dot(n, i);",
            f"return new {t}({body});",
        ], "Reflection of <paramref name=\"i\"/> about the normal <paramref name=\"n\"/>: "
           "<c>i - 2 * dot(n, i) * n</c>, evaluated as <c>fma(-2 * dot(n, i), n, i)</c> (as on Apple GPUs).")
    for n in WIDTHS:
        t = FLOAT.vec(n)
        body = ", ".join(f"MathF.ScaleB(v.{prop(i)}, e)" for i in range(n))
        out.append(f"    private static {t} ScaleB({t} v, int e) => new {t}({body});")
        out.append("")
    if out[-1] == "":
        out.pop()
    out.append("}")
    return "\n".join(out) + "\n"


