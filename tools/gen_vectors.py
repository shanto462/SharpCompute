@dataclass(frozen=True)
class PreludeScale:
    name: str  # C# name
    msl: str  # prelude helper name
    constant: str  # float literal, identical in MSL and C#
    doc: str
    half_constant: str  # the HalfMath field that holds the constant rounded to half
    half_value: str  # that half, for the doc comment
    half_doc: str


# For halves the helper is one half multiplication by the constant rounded to half, `half(constant)`
# in MSL and (Half)constant in C#: the same half on both sides, and one rounding.
PRELUDE_SCALES = (
    PreludeScale("Radians", "__ms_radians", "0.017453292519943295f", "Converts degrees to radians: <c>x * 0.017453292519943295f</c>",
                 "RadiansPerDegree", "0.017456055", "Converts degrees to radians in half precision"),
    PreludeScale("Degrees", "__ms_degrees", "57.29577951308232f", "Converts radians to degrees: <c>x * 57.29577951308232f</c>",
                 "DegreesPerRadian", "57.28125", "Converts radians to degrees in half precision"),
)

# Lowers a scalar Half overload below the float (and int, uint) overload of the same name. Half converts
# implicitly from byte and sbyte, so without it Gpu.Radians(90), and a SIMD-group operation on a byte,
# would be ambiguous calls; with it they keep meaning what they meant before the Half overload existed.
HALF_PRIORITY = "    [OverloadResolutionPriority(-1)]"


# The strong compare-and-swap behind Gpu.AtomicCompareExchange. MSL only has the weak form, which
# may fail spuriously (leaving `expected` equal to the comparand): retry until it succeeds or reads
# another value. The memory order must be a compile-time constant in MSL, so it cannot be a
# parameter; relaxed is the only order there is. One overload per atomic type and address space.
PRELUDE_ATOMIC_CAS = "__ms_atomic_compare_exchange"

# Conversions between a prelude boundary type and its native type (overloaded per type). The
# generator emits them by these names for every [MslType] whose Packed type starts with __ms_.
PRELUDE_UNPACK = "__ms_unpack"
PRELUDE_PACK = "__ms_pack"
# The float add on threadgroup memory behind Gpu.AtomicAdd(ref float, float). MSL 3.2 defines the
# atomic<float> functions for device memory only, so this views the element as an atomic_uint and
# swaps in the bits of the sum until no other thread got in between (a spurious failure of the weak
# form leaves `expected` as it was and simply retries). Bits are compared, not floats, so a NaN or a
# negative zero in the element cannot stall the loop.
PRELUDE_ATOMIC_FLOAT_ADD = "__ms_atomic_fetch_add_float"

# The float to long conversion. On an Apple GPU `long(x)` wraps for a float outside the range of a
# long (2^63 gives long.MinValue, 1e30 gives 0), where every other float to integer conversion
# saturates as .NET does. This clamps first: NaN fails both comparisons and converts to 0, which is
# what `long(NaN)` gives. 9223372036854775808.0f is 2^63, exactly representable as a float.
PRELUDE_FLOAT_TO_LONG = "__ms_float_to_long"

# Rotates behind Gpu.RotateLeft / Gpu.RotateRight. C# takes the count as an int and reduces it modulo
# the width; metal::rotate takes it in the type of the value. The mask makes the reduction explicit,
# and a right rotate is a left rotate by the negated count (negated as unsigned: -int.MinValue
# overflows, which is undefined in MSL).
PRELUDE_ROTATE_LEFT = "__ms_rotate_left"
PRELUDE_ROTATE_RIGHT = "__ms_rotate_right"


@dataclass(frozen=True)
class IntegerType:
    scalar: str  # C# keyword
    msl: str  # MSL scalar name
    bits: int
    signed: bool

    @property
    def unsigned_scalar(self) -> str:
        return {"sbyte": "byte", "short": "ushort", "int": "uint", "long": "ulong"}.get(self.scalar, self.scalar)


BYTE = IntegerType("byte", "uchar", 8, False)
SBYTE = IntegerType("sbyte", "char", 8, True)
SHORT = IntegerType("short", "short", 16, True)
USHORT = IntegerType("ushort", "ushort", 16, False)
LONG = IntegerType("long", "long", 64, True)
ULONG = IntegerType("ulong", "ulong", 64, False)

# The integers besides int and uint (whose intrinsics are hand-written in Gpu.cs, with vector
# overloads in Gpu.g.cs). They have no vectors, so each intrinsic is one scalar overload per type.
SMALL_AND_WIDE = (BYTE, SBYTE, SHORT, USHORT, LONG, ULONG)

# Rotates are new for every integer type, int and uint included.
ROTATE_TYPES = (BYTE, SBYTE, SHORT, USHORT, IntegerType("int", "int", 32, True), IntegerType("uint", "uint", 32, False), LONG, ULONG)

PRELUDE_ATOMICS = tuple(
    (space, t, atomic)
    for space in ("device", "threadgroup")
    for t, atomic in (("int", "metal::atomic_int"), ("uint", "metal::atomic_uint")))


def prelude_msl() -> list[str]:
    lines = ["// SharpCompute prelude (MslPrelude.Source)."]
    for f in PRELUDE_SCALES:
        for t in ("float", "float2", "float3", "float4"):
            lines.append(f"inline {t} {f.msl}({t} x) {{ return x * {f.constant}; }}")
        for t in ("half", "half2", "half3", "half4"):
            lines.append(f"inline {t} {f.msl}({t} x) {{ return x * half({f.constant}); }}")
    for space, t, atomic in PRELUDE_ATOMICS:
        lines.append(
            f"inline {t} {PRELUDE_ATOMIC_CAS}({space} {atomic}* location, {t} comparand, {t} value) "
            f"{{ {t} expected = comparand; while (!metal::atomic_compare_exchange_weak_explicit(location, &expected, value, "
            f"metal::memory_order_relaxed, metal::memory_order_relaxed) && expected == comparand) {{ }} return expected; }}")
    lines.append(
        f"inline float {PRELUDE_ATOMIC_FLOAT_ADD}(threadgroup metal::atomic_uint* location, float value) "
        "{ uint expected = metal::atomic_load_explicit(location, metal::memory_order_relaxed); "
        "while (!metal::atomic_compare_exchange_weak_explicit(location, &expected, as_type<uint>(as_type<float>(expected) + value), "
        "metal::memory_order_relaxed, metal::memory_order_relaxed)) { } return as_type<float>(expected); }")
    lines.append(
        f"inline long {PRELUDE_FLOAT_TO_LONG}(float x) "
        "{ return x >= 9223372036854775808.0f ? 9223372036854775807L : (x < -9223372036854775808.0f ? (-9223372036854775807L - 1L) : long(x)); }")
    for t in ROTATE_TYPES:
        mask = f"{t.bits - 1}u"
        lines.append(f"inline {t.msl} {PRELUDE_ROTATE_LEFT}({t.msl} x, int count) {{ return metal::rotate(x, {t.msl}(uint(count) & {mask})); }}")
        lines.append(f"inline {t.msl} {PRELUDE_ROTATE_RIGHT}({t.msl} x, int count) {{ return metal::rotate(x, {t.msl}((0u - uint(count)) & {mask})); }}")
    for n, packed in PACKED_MATRICES.items():
        msl, column = f"float{n}x{n}", f"float{n}"
        # The boundary form of a matrix: its columns as packed vectors, so the struct has the
        # alignment of a float and sits at any 4-byte offset, like the C# struct does. It is a
        # distinct type on purpose: the generator loads it with __ms_unpack and stores it with
        # __ms_pack, so native (16-byte aligned) matrix code never touches under-aligned storage.
        lines.append(f"struct {packed} {{ packed_{column} columns[{n}]; }};")
        lines.append(f"static_assert(sizeof({packed}) == {4 * n * n} && alignof({packed}) == 4, \"SharpCompute: layout of '{packed}' does not match its C# layout\");")
        columns = ", ".join(f"{column}(m.columns[{c}])" for c in range(n))
        lines.append(f"inline {msl} {PRELUDE_UNPACK}({packed} m) {{ return {msl}({columns}); }}")
        columns = ", ".join(f"m[{c}]" for c in range(n))
        lines.append(f"inline {packed} {PRELUDE_PACK}({msl} m) {{ return {packed}{{{{{columns}}}}}; }}")
    lines.extend(wave_all_equal_msl())
    lines.extend(wave_matrix_msl())
    return lines


def gen_prelude() -> str:
    out: list[str] = [HEADER]
    out.append("namespace SharpCompute;")
    out.append("")
    out.append("/// <summary>")
    out.append("/// MSL helpers and types that have no <c>metal::</c> equivalent. The generator emits")
    out.append("/// <see cref=\"Source\"/> after <c>using namespace metal;</c> when a shader uses one of them. They")
    out.append("/// are named <c>__ms_*</c> and are referenced by <c>[MslIntrinsic(\"__ms_...\")]</c> and")
    out.append("/// <c>[MslAtomic(\"__ms_...\")]</c> on the matching <see cref=\"Gpu\"/> methods, by")
    out.append("/// <c>[MslType(..., Packed = \"__ms_...\")]</c> on <see cref=\"Float4x4\"/>, and by the generator for the")
    out.append("/// loads and products of <see cref=\"WaveMatrix8x8\"/> and <see cref=\"WaveMatrixHalf8x8\"/>.")
    out.append("/// </summary>")
    out.append("public static class MslPrelude")
    out.append("{")
    out.append("    /// <summary>The prelude's MSL source.</summary>")
    out.append('    public const string Source = """')
    out.extend("        " + line for line in prelude_msl())
    out.append('        """;')
    out.append("}")
    return "\n".join(out) + "\n"


