def outputs() -> dict[Path, str]:
    files: dict[Path, str] = {}
    for kind in KINDS:
        for n in WIDTHS:
            files[VECTORS_DIR / f"{kind.vec(n)}.g.cs"] = gen_core(kind, n)
            files[VECTORS_DIR / f"{kind.vec(n)}.Swizzles.g.cs"] = gen_swizzles(kind, n)
    for n in MATRIX_SIZES:
        files[VECTORS_DIR / f"{mat(n)}.g.cs"] = gen_matrix(n)
    files[INTRINSICS_DIR / "Gpu.g.cs"] = gen_gpu()
    files[INTRINSICS_DIR / "Gpu.Matrices.g.cs"] = gen_gpu_matrices()
    files[INTRINSICS_DIR / "MslPrelude.g.cs"] = gen_prelude()
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    parser.add_argument("--msl-probe", type=Path, help="write an MSL probe kernel to this path")
    args = parser.parse_args()

    stale: list[Path] = []
    for path, content in outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT)}")

    if args.msl_probe:
        args.msl_probe.write_text(gen_msl_probe(), encoding="utf-8", newline="\n")
        print(f"wrote {args.msl_probe}")

    if stale:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        print("run: python3 -I tools/gen_vectors.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
