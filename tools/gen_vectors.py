    Func("Tan", "tan", ("x",)),
    Func("Asin", "asin", ("x",)),
    Func("Acos", "acos", ("x",)),
    Func("Atan", "atan", ("x",)),
    Func("Atan2", "atan2", ("y", "x")),
    Func("Sinh", "sinh", ("x",)),
