#!/usr/bin/env python3
"""Generates the SharpCompute vector surface and the vector overloads of the Gpu intrinsics.

Usage (from the repo root; paths are resolved relative to this script, so any cwd works):

    python3 -I tools/gen_vectors.py                 # rewrite all generated files
    python3 -I tools/gen_vectors.py --check         # exit 1 if any generated file is stale
    python3 -I tools/gen_vectors.py --msl-probe F   # also write an MSL file that calls every
                                                    # operator/intrinsic overload, for compiling
                                                    # with tools/compile_msl.swift

Outputs (checked in; edit this script, not the files):
    src/SharpCompute/Vectors/{Float,Half,Int,UInt}{2,3,4}.g.cs       fields, ctors, X/Y/Z/W,
                                                                   operators, comparisons,
                                                                   conversions
    src/SharpCompute/Vectors/Bool{2,3,4}.g.cs                        fields, ctors, X/Y/Z/W,
                                                                   logical operators
    src/SharpCompute/Vectors/{...}{2,3,4}.Swizzles.g.cs              2-4 component swizzles
    src/SharpCompute/Vectors/Float{2x2,3x3,4x4}.g.cs                 matrices (rows in, MSL transpose)
    src/SharpCompute/Intrinsics/Gpu.g.cs                             vector overloads of Gpu.*,
                                                                   Radians/Degrees
    src/SharpCompute/Intrinsics/Gpu.Matrices.g.cs                    Gpu.Mul ([MslBinaryOperator]),
                                                                   Transpose, Determinant
    src/SharpCompute/Intrinsics/Gpu.Integers.g.cs                    the byte, sbyte, short, ushort,
                                                                   long and ulong overloads of the
                                                                   integer intrinsics, and the rotates
    src/SharpCompute/Intrinsics/Gpu.Wave.g.cs                        typed SIMD-group operations
                                                                   (Gpu.Wave*, Gpu.Quad*)
    src/SharpCompute/Intrinsics/MslPrelude.g.cs                      MslPrelude.Source (__ms_* helpers
                                                                   and types)

Scalar intrinsics for float, int and uint (and Gpu.Cross, the unorm8 packing and the atomics) are
hand-written in src/SharpCompute/Intrinsics/Gpu.cs and Gpu.Atomics.cs; the vector overloads
generated here are componentwise calls to those scalar implementations. The half vectors call the
scalar implementations of src/SharpCompute/Intrinsics/HalfMath.cs instead, which are internal: a
public Gpu.Sqrt(Half) next to Gpu.Sqrt(float) would make Gpu.Sqrt(2) ambiguous. The few scalar Half
overloads there are (Radians, Degrees, the SIMD-group operations) carry
[OverloadResolutionPriority(-1)], so that a call both overloads accept keeps meaning the other one.

Requires only the Python 3 standard library.
"""

from __future__ import annotations

import argparse
import itertools
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VECTORS_DIR = ROOT / "src" / "SharpCompute" / "Vectors"
INTRINSICS_DIR = ROOT / "src" / "SharpCompute" / "Intrinsics"

HEADER = (
    "// This file is generated by tools/gen_vectors.py. Do not edit it by hand;\n"
    "// change the script and run: python3 -I tools/gen_vectors.py\n"
)

COMPONENTS = "xyzw"
WIDTHS = (2, 3, 4)


@dataclass(frozen=True)
class Kind:
    prefix: str  # C# type prefix: Float, Half, Int, UInt, Bool
    scalar: str  # C# scalar type: float, Half, int, uint, bool
    msl: str  # MSL scalar name
    size: int = 4  # bytes per component, also the alignment of the packed MSL vector

    @property
    def is_float(self) -> bool:
        return self.scalar == "float"

    @property
    def is_half(self) -> bool:
        return self.scalar == "Half"

    @property
    def is_floating(self) -> bool:
        return self.is_float or self.is_half

    @property
    def is_integer(self) -> bool:
        return self.scalar in ("int", "uint")

    @property
    def is_bool(self) -> bool:
        return self.scalar == "bool"

    def vec(self, n: int) -> str:
        return f"{self.prefix}{n}"

    def msl_vec(self, n: int) -> str:
        return f"{self.msl}{n}"


FLOAT = Kind("Float", "float", "float")
HALF = Kind("Half", "Half", "half", size=2)
INT = Kind("Int", "int", "int")
UINT = Kind("UInt", "uint", "uint")
BOOL = Kind("Bool", "bool", "bool", size=1)

# The 32-bit kinds: what the SIMD-group operations and the prelude are defined for.
KINDS = (FLOAT, INT, UINT)

# Every kind with arithmetic, comparisons and a packed MSL vector (bool vectors have none of those).
NUMERIC_KINDS = (FLOAT, HALF, INT, UINT)


def field(i: int) -> str:
    return "_" + COMPONENTS[i]


def prop(i: int) -> str:
    return COMPONENTS[i].upper()


def new(kind: Kind, n: int, exprs: list[str]) -> str:
    """`new T(e0, e1, ...)`, in unchecked(...) for integer kinds so + - * and negation wrap like MSL.

    Integer / and % still throw on a zero divisor and on int.MinValue / -1 (.NET traps; MSL does not).
    """
    expr = f"new {kind.vec(n)}({', '.join(exprs)})"
    return f"unchecked({expr})" if kind.is_integer else expr


