def gen_msl_probe() -> str:
    lines = ["#include <metal_stdlib>", "using namespace metal;", ""] + prelude_msl() + ["",
             "kernel void probe(device float* sink [[buffer(0)]], uint tid [[thread_position_in_grid]])", "{",
             "    float acc = 0;"]
    vals = {FLOAT: "1.5f", INT: "3", UINT: "3u"}
    for kind in KINDS:
        s = kind.msl
        lines.append(f"    {s} s{kind.msl} = {s}(tid) + {vals[kind]};")
        for n in WIDTHS:
            v = f"v{kind.msl_vec(n)}"
            lines.append(f"    {kind.msl_vec(n)} {v} = {kind.msl_vec(n)}(s{kind.msl});")
            # Constructors.
            for parts in compositions(n):
                args = [f"s{kind.msl}" if p == 1 else f"v{kind.msl_vec(p)}" for p in parts]
                lines.append(f"    acc += float({kind.msl_vec(n)}({', '.join(args)}).x);")
            # Packed round trip + swizzles.
            lines.append(f"    packed_{kind.msl_vec(n)} p{v} = {v};")
            for sw in swizzles(n):
                name = "".join(COMPONENTS[i] for i in sw)
                lines.append(f"    acc += float({v}.{name}.x) + float(p{v}.{name}.x);")
                if len(set(sw)) == len(sw):
                    lines.append(f"    {v}.{name} = {v}.{name}; p{v}.{name} = {v}.{name};")
            lines.append(f"    {v} = p{v};")
            # Operators.
            ops = [sym for sym, _ in binary_ops(kind)]
            for sym in ops:
                lhs, rhs, sc = v, v, f"s{kind.msl}"
                if kind.is_float and sym == "%":
                    for a, b in ((lhs, rhs), (lhs, sc), (sc, rhs)):
                        lines.append(f"    acc += float(metal::fmod({a}, {b}).x);")
                    continue
                for a, b in ((lhs, rhs), (lhs, sc), (sc, rhs)):
                    lines.append(f"    acc += float(({a} {sym} {b}).x);")
            if kind.is_float or kind is INT:
                lines.append(f"    acc += float((-{v}).x);")
            if kind.is_integer:
                lines.append(f"    acc += float((~{v}).x);")
                for sym in ("<<", ">>"):
                    lines.append(f"    acc += float(({v} {sym} {v}).x);")
                    lines.append(f"    acc += float(({v} {sym} int(tid)).x);")
            # Conversions.
            for other in KINDS:
                if other is not kind:
                    lines.append(f"    acc += float({other.msl_vec(n)}({v}).x);")
    # Intrinsics.
    for f in FUNCS:
        for kind in f.kinds:
            sc = f"s{kind.msl}"
            lines.append(f"    acc += float(metal::{f.msl}({', '.join([sc] * len(f.params))}));")
            for n in WIDTHS:
                v = f"v{kind.msl_vec(n)}"
                for scalars in ((),) + f.mixed:
                    args = [sc if i in scalars else v for i in range(len(f.params))]
                    lines.append(f"    acc += float(metal::{f.msl}({', '.join(args)}).x);")
    for n in WIDTHS:
        v = f"vfloat{n}"
        lines.append(f"    acc += metal::dot({v}, {v}) + metal::length({v}) + metal::distance({v}, {v}) + metal::normalize({v}).x + metal::reflect({v}, {v}).x;")
    lines.append("    acc += metal::cross(vfloat3, vfloat3).x;")
    # Prelude helpers.
    for f in PRELUDE_SCALES:
        lines.append(f"    acc += {f.msl}(sfloat);")
        for n in WIDTHS:
            lines.append(f"    acc += {f.msl}(vfloat{n}).x;")

    # Matrices: constructors take the C# arguments unchanged (C# rows become MSL columns), and
    # Gpu.Mul ([MslBinaryOperator("*", SwapOperands = true)]) emits mul(a0, a1) as (a1 * a0).
    def mul(a0: str, a1: str) -> str:
        return f"({a1} * {a0})"

    for n in MATRIX_SIZES:
        t, v = f"float{n}x{n}", f"vfloat{n}"
        m, r = f"m{n}", f"r{n}"
        scalars = ", ".join(f"sfloat + {k}.0f" for k in range(n * n))
        lines.append(f"    {t} {m} = {t}({scalars}); // new Float{n}x{n}(m00, m01, ...)")
        lines.append(f"    {t} {r} = {t}({', '.join([v] * n)}); // new Float{n}x{n}(row0, row1, ...)")
        for expr in (f"{m} + {r}", f"{m} - {r}", f"{m} * sfloat", f"sfloat * {m}", f"{m} / sfloat"):
            lines.append(f"    acc += ({expr})[0].x;")
        lines.append(f"    {m} += {r}; {m} -= {r}; {m} *= sfloat; {m} /= sfloat;")
        lines.append(f"    acc += {mul(v, m)}.x; // Gpu.Mul(v, M)")
        lines.append(f"    acc += {mul(m, v)}.x; // Gpu.Mul(M, v)")
        lines.append(f"    acc += {mul(m, r)}[0].x; // Gpu.Mul(A, B)")
    lines.append("    sink[tid] = acc;")
    lines.append("}")
    return "\n".join(lines) + "\n"


