def reverse_bits_body(t: IntegerType) -> str:
    """The CPU bit reversal, built on the 32-bit one in Gpu.cs."""
    u = t.unsigned_scalar
    if t.bits == 64:
        value = "x" if not t.signed else "(ulong)x"
        reversed_bits = f"((ulong)ReverseBits((uint){value}) << 32) | ReverseBits((uint)({value} >> 32))"
        return reversed_bits if not t.signed else f"unchecked((long)({reversed_bits}))"
    widened = "x" if not t.signed else f"({u})x"
    return f"unchecked(({t.scalar})(ReverseBits((uint){widened}) >> {32 - t.bits}))"


def gen_gpu_integers() -> str:
    out: list[str] = [HEADER]
    out.append("using System;")
    out.append("")
    out.append("namespace SharpCompute;")
    out.append("")
    out.append("/// <content>")
    out.append("/// The integer intrinsics for <c>byte</c>, <c>sbyte</c>, <c>short</c>, <c>ushort</c>, <c>long</c> and")
    out.append("/// <c>ulong</c>, and the rotates for every integer type. As in MSL the result has the type of the")
    out.append("/// argument, so a count of bits is at most the width of that type: <c>LeadingZeroCount((byte)1)</c>")
    out.append("/// is 7, not 31. These types have no vectors, so there are no componentwise overloads.")
    out.append("/// </content>")
    out.append("/// <remarks>")
    out.append("/// C# promotes a <c>byte</c> or a <c>short</c> to <c>int</c> in arithmetic, and an <c>int</c> literal")
    out.append("/// is an <c>int</c>: <c>Gpu.Min(b, 5)</c> is ambiguous between the <c>byte</c> and the <c>int</c>")
    out.append("/// overload, exactly as <c>Math.Min(b, 5)</c> is. Cast the literal (<c>Gpu.Min(b, (byte)5)</c>) or")
    out.append("/// the value, depending on the width the result should have.")
    out.append("/// </remarks>")
    out.append("public static partial class Gpu")
    out.append("{")

    def method(doc: str, msl: str, ret: str, name: str, params: str, body: str) -> None:
        out.append(f"    /// <summary>{doc}</summary>")
        out.append(f"    [MslIntrinsic(\"{msl}\")]")
        out.append(f"    public static {ret} {name}({params}) => {body};")
        out.append("")

    for t in SMALL_AND_WIDE:
        s, b = t.scalar, t.bits
        cref = {"byte": "byte", "sbyte": "sbyte", "short": "short", "ushort": "ushort", "long": "long", "ulong": "ulong"}[s]
        out.append(f"    // ---- {s} (MSL {t.msl}) " + "-" * (78 - len(s) - len(t.msl)))
        out.append("")
        if t.signed:
            method(f"Absolute value; wraps for <see cref=\"{cref}.MinValue\"/> (no overflow exception), like MSL.",
                   "metal::abs", s, "Abs", f"{s} x", f"x < 0 ? unchecked(({s})(-x)) : x")
        else:
            method("Absolute value: the value itself, as it is unsigned (MSL <c>abs</c>).", "metal::abs", s, "Abs", f"{s} x", "x")
        method("The smaller of two values (MSL <c>min</c>).", "metal::min", s, "Min", f"{s} x, {s} y", "Math.Min(x, y)")
        method("The larger of two values (MSL <c>max</c>).", "metal::max", s, "Max", f"{s} x, {s} y", "Math.Max(x, y)")
        method("<c>min(max(x, minValue), maxValue)</c>, as MSL defines it; never throws when the bounds are reversed.",
               "metal::clamp", s, "Clamp", f"{s} x, {s} minValue, {s} maxValue", "Math.Min(Math.Max(x, minValue), maxValue)")
        method(f"The number of set bits among the {b} (MSL <c>popcount</c>).", "metal::popcount", s, "CountBits", f"{s} x", f"{s}.PopCount(x)")
        negative = " and 0 for negative values" if t.signed else ""
        method(f"The number of zero bits above the highest set bit; {b} for 0{negative} (MSL <c>clz</c>).",
               "metal::clz", s, "LeadingZeroCount", f"{s} x", f"{s}.LeadingZeroCount(x)")
        method(f"The number of zero bits below the lowest set bit; {b} for 0 (MSL <c>ctz</c>).",
               "metal::ctz", s, "TrailingZeroCount", f"{s} x", f"{s}.TrailingZeroCount(x)")
        method(f"Reverses the order of the {b} bits: bit 0 becomes bit {b - 1} (MSL <c>reverse_bits</c>).",
               "metal::reverse_bits", s, "ReverseBits", f"{s} x", reverse_bits_body(t))

    out.append("    // ---- rotates " + "-" * 76)
    out.append("    // metal::rotate takes the count in the type of the value; the prelude helpers take the int of")
    out.append("    // C# and reduce it modulo the width, as the .NET rotates do.")
    out.append("")
    for name, helper, direction in (("RotateLeft", PRELUDE_ROTATE_LEFT, "left"), ("RotateRight", PRELUDE_ROTATE_RIGHT, "right")):
        for t in ROTATE_TYPES:
            method(f"Rotates the {t.bits} bits {direction} by <paramref name=\"count\"/>, taken modulo {t.bits} (MSL <c>rotate</c>).",
                   helper, t.scalar, name, f"{t.scalar} x, int count", f"{t.scalar}.{name}(x, count)")

    while out[-1] == "":
        out.pop()
    out.append("}")
    return "\n".join(out) + "\n"


def gen_msl_probe() -> str:
    lines = ["#include <metal_stdlib>", "using namespace metal;", ""] + prelude_msl() + ["",
             "kernel void probe(device float* sink [[buffer(0)]], uint tid [[thread_position_in_grid]])", "{",
             "    threadgroup int tgint[4];",
             "    threadgroup uint tguint[4];",
             "    threadgroup float tgfloat[4];",
             "    float acc = 0;"]
    vals = {FLOAT: "1.5f", HALF: "1.5h", INT: "3", UINT: "3u"}
    lines.append("    bool sbool = (tid & 1u) != 0u;")
    for kind in NUMERIC_KINDS:
        s = kind.msl
        lines.append(f"    {s} s{kind.msl} = {s}(tid) + {vals[kind]};")
        for n in WIDTHS:
            v = f"v{kind.msl_vec(n)}"
            lines.append(f"    {kind.msl_vec(n)} {v} = {kind.msl_vec(n)}(s{kind.msl});")
            # Constructors.
            for parts in compositions(n):
                args = [f"s{kind.msl}" if p == 1 else f"v{kind.msl_vec(p)}" for p in parts]
                lines.append(f"    acc += float({kind.msl_vec(n)}({', '.join(args)}).x);")
            # Packed round trip + swizzles.
            lines.append(f"    packed_{kind.msl_vec(n)} p{v} = {v};")
            for sw in swizzles(n):
                name = "".join(COMPONENTS[i] for i in sw)
                lines.append(f"    acc += float({v}.{name}.x) + float(p{v}.{name}.x);")
                if len(set(sw)) == len(sw):
                    lines.append(f"    {v}.{name} = {v}.{name}; p{v}.{name} = {v}.{name};")
            lines.append(f"    {v} = p{v};")
            # Operators.
            ops = [sym for sym, _ in binary_ops(kind)]
            for sym in ops:
                lhs, rhs, sc = v, v, f"s{kind.msl}"
                if kind.is_floating and sym == "%":
                    for a, b in ((lhs, rhs), (lhs, sc), (sc, rhs)):
                        lines.append(f"    acc += float(metal::fmod({a}, {b}).x);")
                    continue
                for a, b in ((lhs, rhs), (lhs, sc), (sc, rhs)):
                    lines.append(f"    acc += float(({a} {sym} {b}).x);")
            # Comparisons: a bool vector, also from the packed form and against a scalar. Gpu.Equal and
            # Gpu.NotEqual ([MslBinaryOperator]) convert their vector operands to the native type.
            bv = f"b{kind.msl_vec(n)}"
            lines.append(f"    bool{n} {bv} = {v} < {v};")
            for sym, _, _ in COMPARISONS:
                for a, b in ((v, v), (v, f"s{kind.msl}"), (f"s{kind.msl}", v), (f"p{v}", f"p{v}"), (f"p{v}", f"s{kind.msl}")):
                    lines.append(f"    {bv} = {a} {sym} {b};")
            for _, sym, _ in EQUALITIES:
                lines.append(f"    {bv} = ({kind.msl_vec(n)}({v}) {sym} {kind.msl_vec(n)}(p{v})); {bv} = ({kind.msl_vec(n)}(p{v}) {sym} s{kind.msl});")
            # Gpu.Select(mask, whenTrue, whenFalse) is emitted with its arguments reversed.
            lines.append(f"    acc += float(metal::select({v}, p{v}, {bv}).x) + float(metal::any({bv})) + float(metal::all({bv}));")
            if kind.is_floating or kind is INT:
                lines.append(f"    acc += float((-{v}).x);")
            if kind.is_integer:
                lines.append(f"    acc += float((~{v}).x);")
                for sym in ("<<", ">>"):
                    lines.append(f"    acc += float(({v} {sym} {v}).x);")
                    lines.append(f"    acc += float(({v} {sym} int(tid)).x);")
            # Conversions.
            for other in NUMERIC_KINDS:
                if other is not kind:
                    lines.append(f"    acc += float({other.msl_vec(n)}({v}).x);")
    # Bool vectors: constructors, swizzles, the logical operators, any/all/select and a zero value.
    for n in WIDTHS:
        v = f"vbool{n}"
        lines.append(f"    bool{n} {v} = bool{n}(sbool);")
        for parts in compositions(n):
            args = ["sbool" if p == 1 else f"vbool{p}" for p in parts]
            lines.append(f"    acc += float(bool{n}({', '.join(args)}).x);")
        for sw in swizzles(n):
            name = "".join(COMPONENTS[i] for i in sw)
            lines.append(f"    acc += float({v}.{name}.x);")
            if len(set(sw)) == len(sw):
                lines.append(f"    {v}.{name} = {v}.{name};")
        lines.append(f"    {v} = !{v}; {v} = {v} & {v}; {v} = {v} | {v}; {v} = {v} ^ {v}; {v} &= {v}; {v} |= {v}; {v} ^= {v};")
        lines.append(f"    acc += float(metal::any({v})) + float(metal::all({v})) + float(metal::select({v}, {v}, {v}).x) + float(bool{n}(false).x);")
    # Intrinsics.
    for f in FUNCS:
        for kind in f.kinds:
            sc = f"s{kind.msl}"
            lines.append(f"    acc += float(metal::{f.msl}({', '.join([sc] * len(f.params))}));")
            for n in WIDTHS:
                v = f"v{kind.msl_vec(n)}"
                for scalars in ((),) + f.mixed:
                    args = [sc if i in scalars else v for i in range(len(f.params))]
                    lines.append(f"    acc += float(metal::{f.msl}({', '.join(args)}).x);")
    # Bit reinterpretation.
    for _, sources, result in REINTERPRETS:
        for source in sources:
            lines.append(f"    acc += float(as_type<{result.msl}>(s{source.msl}));")
            for n in WIDTHS:
                lines.append(f"    acc += float(as_type<{result.msl_vec(n)}>(v{source.msl_vec(n)}).x);")
    # Scalar-only intrinsics of Gpu.cs.
    lines.append("    acc += float(metal::isnan(sfloat)) + float(metal::isinf(sfloat)) + float(metal::isfinite(sfloat));")
    lines.append("    acc += float(metal::pack_float_to_unorm4x8(vfloat4)) + metal::unpack_unorm4x8_to_float(suint).x;")
    for kind in (FLOAT, HALF):
        for n in WIDTHS:
            v = f"v{kind.msl_vec(n)}"
            lines.append(f"    acc += float(metal::dot({v}, {v})) + float(metal::length({v})) + float(metal::distance({v}, {v})) + float(metal::normalize({v}).x) + float(metal::reflect({v}, {v}).x);")
            for _, msl, _ in CLASSIFICATIONS:
                lines.append(f"    bool{n} c{msl}{kind.msl}{n} = metal::{msl}({v}); acc += float(c{msl}{kind.msl}{n}.x) + float(metal::{msl}(p{v}).x);")
        lines.append(f"    acc += float(metal::cross(v{kind.msl_vec(3)}, v{kind.msl_vec(3)}).x);")
    # Prelude helpers.
    for f in PRELUDE_SCALES:
        for kind in (FLOAT, HALF):
            lines.append(f"    acc += float({f.msl}(s{kind.msl}));")
            for n in WIDTHS:
                lines.append(f"    acc += float({f.msl}(v{kind.msl_vec(n)}).x);")
    # The bits of a half (Gpu.AsUShort, AsShort, AsHalf and the BitConverter methods they stand for).
    lines.append("    ushort hbits = as_type<ushort>(shalf); short hsigned = as_type<short>(shalf);")
    lines.append("    acc += float(as_type<half>(hbits)) + float(as_type<half>(hsigned));")

    # Matrices: constructors take the C# arguments unchanged (C# rows become MSL columns), and
    # Gpu.Mul ([MslBinaryOperator("*", SwapOperands = true)]) emits mul(a0, a1) as (a1 * a0).
    def mul(a0: str, a1: str) -> str:
        return f"({a1} * {a0})"

    for n in MATRIX_SIZES:
        t, v = f"float{n}x{n}", f"vfloat{n}"
        m, r = f"m{n}", f"r{n}"
        scalars = ", ".join(f"sfloat + {k}.0f" for k in range(n * n))
        lines.append(f"    {t} {m} = {t}({scalars}); // new Float{n}x{n}(m00, m01, ...)")
        lines.append(f"    {t} {r} = {t}({', '.join([v] * n)}); // new Float{n}x{n}(row0, row1, ...)")
        for expr in (f"{m} + {r}", f"{m} - {r}", f"{m} * sfloat", f"sfloat * {m}", f"{m} / sfloat"):
            lines.append(f"    acc += ({expr})[0].x;")
        lines.append(f"    {m} += {r}; {m} -= {r}; {m} *= sfloat; {m} /= sfloat;")
        lines.append(f"    acc += {mul(v, m)}.x; // Gpu.Mul(v, M)")
        lines.append(f"    acc += {mul(m, v)}.x; // Gpu.Mul(M, v)")
        lines.append(f"    acc += {mul(m, r)}[0].x; // Gpu.Mul(A, B)")
        lines.append(f"    acc += metal::transpose({m})[0].x + metal::determinant({m});")
        if n in PACKED_MATRICES:
            # The boundary type: read, written and used in place through device memory.
            p = f"((device {PACKED_MATRICES[n]}*)sink)"
            lines.append(f"    {m} = {PRELUDE_UNPACK}({p}[tid]); {p}[tid] = {PRELUDE_PACK}({m}); acc += {mul(v, PRELUDE_UNPACK + '(' + p + '[tid])')}.x;")
    # Atomics (Gpu.Atomic*) on device memory and on threadgroup memory: every function for int and
    # uint and the prelude's strong compare-and-swap, in both address spaces. The float add is MSL's
    # own for device memory and the prelude's loop over the bits for threadgroup memory (MSL 3.2
    # defines no atomic<float> functions there).
    order = "metal::memory_order_relaxed"
    for t, atomic in (("int", "metal::atomic_int"), ("uint", "metal::atomic_uint")):
        for a in (f"(device {atomic}*)&(((device {t}*)sink)[tid])", f"(threadgroup {atomic}*)&(tg{t}[tid & 3u])"):
            for fn in ("fetch_add", "fetch_sub", "fetch_min", "fetch_max", "fetch_and", "fetch_or", "fetch_xor", "exchange"):
                lines.append(f"    acc += float(metal::atomic_{fn}_explicit({a}, s{t}, {order}));")
            lines.append(f"    acc += float({PRELUDE_ATOMIC_CAS}({a}, s{t}, s{t}));")
    lines.append(f"    acc += metal::atomic_fetch_add_explicit((device metal::atomic<float>*)&(sink[tid]), sfloat, {order});")
    lines.append(f"    acc += {PRELUDE_ATOMIC_FLOAT_ADD}((threadgroup metal::atomic_uint*)&(tgfloat[tid & 3u]), sfloat);")
    # The small and wide integers: every intrinsic of Gpu.Integers.g.cs, the saturating float to long
    # conversion, and the one 64-bit atomic pair MSL 3.2 has (minimum and maximum of a ulong in
    # device memory, which return nothing).
    for t in SMALL_AND_WIDE:
        v = f"s{t.msl}"
        lines.append(f"    {t.msl} {v} = {t.msl}(tid) + {t.msl}(3);")
        for fn, arity in (("abs", 1), ("min", 2), ("max", 2), ("clamp", 3), ("popcount", 1), ("clz", 1), ("ctz", 1), ("reverse_bits", 1)):
            lines.append(f"    {v} = metal::{fn}({', '.join([v] * arity)});")
        lines.append(f"    acc += float({v});")
    for t in ROTATE_TYPES:
        v = f"rot{t.msl}"
        lines.append(f"    {t.msl} {v} = {t.msl}(tid) + {t.msl}(3);")
        lines.append(f"    acc += float({PRELUDE_ROTATE_LEFT}({v}, int(tid))) + float({PRELUDE_ROTATE_RIGHT}({v}, int(tid)));")
    lines.append(f"    acc += float({PRELUDE_FLOAT_TO_LONG}(sfloat));")
    for fn in ("min", "max"):
        lines.append(f"    metal::atomic_{fn}_explicit((device metal::atomic_ulong*)&(((device ulong*)sink)[tid]), sulong, {order});")
    lines += gen_wave_msl_probe()
    lines.append("    sink[tid] = acc;")
    lines.append("}")
    return "\n".join(lines) + "\n"


