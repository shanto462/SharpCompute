def wave_types(w: Wave) -> list[tuple[Kind, int]]:
    """Every (kind, width) the operation has an overload for; width 1 is the scalar."""
    kinds = (INT, UINT) if w.integer_only else KINDS + (HALF,)
    return [(kind, n) for kind in kinds for n in (1,) + WIDTHS]


def wave_all_equal_msl() -> list[str]:
    """The prelude's all-equal helpers: Metal has no SIMD-group function that compares the lanes."""
    lines = []
    for kind in KINDS + (HALF,):
        for n in (1,) + WIDTHS:
            t = kind.msl if n == 1 else kind.msl_vec(n)
            same = "v == metal::simd_broadcast_first(v)"
            lines.append(f"inline bool __ms_wave_all_equal({t} v) {{ return metal::simd_all({same if n == 1 else 'metal::all(' + same + ')'}); }}")
    return lines


def wave_matrix_msl() -> list[str]:
    """The prelude's wave-matrix helpers. Metal's simdgroup_load, simdgroup_multiply and
    simdgroup_multiply_accumulate return their result through a reference parameter; these return it,
    so that WaveMatrix8x8.Load(...) and the products are expressions, as they are in C#. They inline to
    the plain calls (measured: the same GFLOP/s). A load is overloaded on the address space of its
    source, a buffer (device) or a [GroupShared] array (threadgroup), and takes its element type from
    it; a product takes the result's element type as R and those of its operands from the arguments,
    which is every mix of half and float that Metal allows."""
    m = "metal::simdgroup_matrix"
    lines = []
    for space in ("device", "threadgroup"):
        lines.append(
            f"template <typename T> inline {m}<T, 8, 8> __ms_wave_matrix_load(const {space} T* source, ulong stride, bool transpose) "
            f"{{ {m}<T, 8, 8> matrix; metal::simdgroup_load(matrix, source, stride, ulong2(0), transpose); return matrix; }}")
    lines.append(
        f"template <typename R, typename T, typename U> inline {m}<R, 8, 8> __ms_wave_matrix_multiply({m}<T, 8, 8> a, {m}<U, 8, 8> b) "
        f"{{ {m}<R, 8, 8> product; metal::simdgroup_multiply(product, a, b); return product; }}")
    lines.append(
        f"template <typename R, typename T, typename U, typename V> inline {m}<R, 8, 8> __ms_wave_matrix_multiply_accumulate({m}<T, 8, 8> a, {m}<U, 8, 8> b, {m}<V, 8, 8> c) "
        f"{{ {m}<R, 8, 8> sum; metal::simdgroup_multiply_accumulate(sum, a, b, c); return sum; }}")
    return lines


def gen_gpu_wave() -> str:
    out: list[str] = [HEADER]
    out.append("using System;")
    out.append("using System.Runtime.CompilerServices;")
    out.append("")
    out.append("namespace SharpCompute;")
    out.append("")
    out.append("// The typed SIMD-group operations. The generator maps them to Metal's simd_* and quad_* functions by")
    out.append("// name (MslTranslator.SimdGroups.cs); on the CPU they all go through CpuSimdGroup.")
    out.append("public static partial class Gpu")
    out.append("{")
    for w in WAVES:
        note = f" with {w.msl_extra}" if w.msl_extra else ""
        prefix = "" if w.msl.startswith("__ms_") else "metal::"
        out.append(f"    // {w.name} -> {prefix}{w.msl}{note}")
        out.append("")
        for kind, n in wave_types(w):
            t = kind.scalar if n == 1 else kind.vec(n)
            out.append(f"    /// <summary>{w.doc}</summary>")
            if w.remarks:
                out.append(f"    /// <remarks>{w.remarks}</remarks>")
            out.append("    /// <param name=\"value\">This lane's value.</param>")
            params = [f"{t} value"]
            if w.kind == "fill":
                out.append("    /// <param name=\"fill\">This lane's fill value (see remarks for which lane's fill a lane gets).</param>")
                params.append(f"{t} fill")
            if w.extra:
                out.append(f"    /// <param name=\"{w.extra}\">{w.extra_doc}</param>")
                params.append(f"int {w.extra}")
            out.extend(CALL_SITE_DOCS)
            params.extend(CALL_SITE_PARAMS)
            site = "callerFile, callerLine"
            # A half travels through the lane executor as its 16 bits in a 32-bit component, like
            # every other value: SimdHalf.Widen on the way in, SimdHalf.Narrow on the way out.
            value, fill = ("SimdHalf.Widen(value)", "SimdHalf.Widen(fill)") if kind.is_half else ("value", "fill")
            if w.kind == "reduce":
                ret, body = t, f"CpuSimdGroup.Reduce(SimdOp.{w.op}, SimdScalar.{kind.prefix}, {value}, {site})"
            elif w.kind == "equal":
                ret, body = "bool", f"CpuSimdGroup.AllEqual(SimdScalar.{kind.prefix}, {value}, {site})"
            elif w.kind == "fill":
                ret, body = t, f"CpuSimdGroup.Exchange(SimdOp.{w.op}, {value}, {fill}, {w.extra}, {site})"
            else:
                ret, body = t, f"CpuSimdGroup.Exchange(SimdOp.{w.op}, {value}, {value}, {w.extra or '0'}, {site})"
            if kind.is_half and w.kind != "equal":
                body = f"SimdHalf.Narrow({body})"
            if kind.is_half and n == 1:
                out.append(HALF_PRIORITY)
            out.append(f"    public static {ret} {w.name}({', '.join(params)}) =>")
            out.append(f"        {body};")
            out.append("")
    if out[-1] == "":
        out.pop()
    out.append("}")
    return "\n".join(out) + "\n"


def gen_wave_msl_probe() -> list[str]:
    """Calls every typed SIMD-group overload the way the generator emits it."""
    lines: list[str] = []
    for w in WAVES:
        for kind, n in wave_types(w):
            v = f"s{kind.msl}" if n == 1 else f"v{kind.msl_vec(n)}"
            second = f", ushort({w.msl_extra})" if w.msl_extra else ", ushort(int(tid) & 3)" if w.extra else ""
            if w.kind == "fill":
                second = f", {v}{second}"
            prefix = "" if w.msl.startswith("__ms_") else "metal::"
            call = f"{prefix}{w.msl}({v}{second})"
            lines.append(f"    acc += float({call}{'' if n == 1 or w.kind == 'equal' else '.x'});")
    lines.append("    acc += float(metal::simd_is_first()) + float(metal::simd_any(acc > 0.0f)) + float(metal::simd_all(acc > 0.0f));")
    lines.append("    acc += float(uint(metal::simd_vote::vote_t(metal::simd_ballot(acc > 0.0f))));")
    lines.append("    acc += float(metal::simd_sum(int(acc > 0.0f)) + metal::simd_prefix_exclusive_sum(int(acc > 0.0f)));")
    lines.append("    acc += float(metal::quad_any(acc > 0.0f)) + float(metal::quad_all(acc > 0.0f));")
    lines.append("    acc += float(uint(metal::quad_vote::vote_t(metal::quad_ballot(acc > 0.0f))));")
    return lines


