def run(cmd: list[str], env: dict | None = None, quiet: bool = True) -> subprocess.CompletedProcess:
    result = subprocess.run(cmd, cwd=ROOT, env=env, capture_output=quiet, text=True)
    return result


def build_and_run(source: Path, report: Path, work: Path) -> list[dict]:
    """Builds the test project with `source` as its generated shaders, runs them, returns the mismatches."""
    build = run(["dotnet", "build", str(PROJECT), "-nologo", "-v:q", f"-p:DifferentialSource={source}"])
    if build.returncode != 0:
        log = work / "build.log"
        log.write_text(build.stdout + build.stderr)
        sys.exit(f"build failed (a generator bug: every case must compile); see {log}\n" + "\n".join(
            line for line in build.stdout.splitlines() if "error" in line)[:4000])
    if report.exists():
        report.unlink()
    env = dict(os.environ, SHARPCOMPUTE_DIFFERENTIAL_REPORT=str(report))
    test = run(["dotnet", "test", str(PROJECT), "-nologo", "--no-build", "--filter", "FullyQualifiedName~SharpCompute.Differential.Tests.DifferentialTests.RandomExpressions_GiveTheSameResultsOnTheGpuAsWithForCpu"], env=env)
    if not report.exists():
        if test.returncode == 0:
            return []
        (work / "test.log").write_text(test.stdout + test.stderr)
        sys.exit(f"the test run failed without reporting a mismatch; see {work / 'test.log'}")
    entries = [json.loads(line) for line in report.read_text().splitlines() if line.strip()]
    CRASHES.extend(e["crash"] for e in entries if "crash" in e)
    return [e for e in entries if "case" in e]


# The shaders whose pipeline Metal's compiler crashed building (XPC_ERROR_CONNECTION_INTERRUPTED) in
# this run: their cases are not compared, and the run goes on (DifferentialHarness.ReportCompilerCrash).
CRASHES: list[str] = []


def shrink_candidates(root: Node) -> list[Node]:
    """Smaller trees of the same type: each node replaced by one of its operands of its type, by an
    input or by a literal; a local or an assignment dropped."""
    result = []
    nodes = list(root.walk())
    for target in nodes:
        replacements: list[Node] = [a for a in target.args if a.t is target.t]
        if target.kind not in ("var", "lit"):
            replacements.append(var(VARS_BY_TYPE[target.t][0]))
            g = Gen(random.Random(0))
            if target is not root:
                replacements.append(g.literal(target.t))
        for r in replacements:
            candidate = replace(root, target, r)
            if candidate is not None and candidate.kind not in ("var", "lit") and valid(candidate):
                result.append(candidate)
    # Inputs renamed to the first of their type, so that the repro needs fewer.
    for n in nodes:
        if n.kind == "var" and n.text != VARS_BY_TYPE[n.t][0].name:
            candidate = replace(root, n, var(VARS_BY_TYPE[n.t][0]))
            if candidate is not None:
                result.append(candidate)
    return result


def replace(root: Node, target: Node, replacement: Node) -> Node | None:
    if root is target:
        return replacement.copy()
    copy = Node(root.t, root.kind, root.text, [], root.flags, root.bind, root.guard, root.ulps)
    copy.args = [replace(a, target, replacement) for a in root.args]
    return copy


def valid(root: Node) -> bool:
    for n in root.walk():
        if n.kind == "op" and n.args and all(a.is_lit() for a in n.args):
            return False
        if n.kind == "op" and ("AsUInt" in n.text or "AsInt" in n.text or "AsUShort" in n.text or "AsShort" in n.text or "Int32Bits" in n.text) and n.args[0].t.floating:
            a = n.args[0]
            if not (a.kind == "var" or (a.kind == "op" and a.args and a.args[0].kind == "var" and ("neg" in a.flags or "Abs" in a.text))):
                return False
    return len(fused_variants(root)) <= MAX_FUSED_VARIANTS and known_difference(root) is None


def repro(case_id: str, root: Node, mismatch: dict) -> str:
    """A self-contained shader that shows the mismatch on one thread, with the inputs it reads."""
    c = Case(case_id, root)
    variables = used_vars([root])
    inputs: list[str] = []
    values: dict[str, str] = mismatch.get("inputs", {})
    lines = []
    slot = 0
    for v in variables:
        if not v.t.vector:
            lines.append(f"{v.t.cs} {v.name} = {read_slot(v.t, str(slot))};  // {values.get(v.name, '?')}")
            inputs.append(values.get(v.name + "#bits", "0") + "UL")
            slot += 1
        else:
            e = elem_of(v.t)
            parts = []
            notes = []
            for k in range(v.t.lanes):
                key = f"{v.name}.{'XYZW'[k]}"
                parts.append(read_slot(e, str(slot)))
                inputs.append(values.get(key + "#bits", "0") + "UL")
                notes.append(values.get(key, "?"))
                slot += 1
            lines.append(f"{v.t.cs} {v.name} = new {v.t.cs}({', '.join(parts)});  // ({', '.join(notes)})")
    body = emit_case(root, Ctx("t"), 0, base="")
    out = [
        f"// Case {case_id} ({check_of(c)}): {mismatch.get('detail', '')}",
        "[GeneratedComputeShaderDescriptor]",
        "public readonly partial struct Repro(ReadOnlyBuffer<ulong> input, ReadWriteBuffer<long> output) : IComputeShader",
        "{",
        "    public void Execute()",
        "    {",
    ]
    out.extend("        " + line for line in lines + body)
    out.extend([
        "    }",
        "}",
        f"// ulong[] input = [{', '.join(inputs)}];",
        f"// Run with device.For(1, ...) and device.ForCpu(1, ...) over a ReadWriteBuffer<long> of {root.t.lanes} and compare.",
    ])
    return "\n".join(out)


def fuzz(seed: int, count: int, batch: int, keep: bool) -> int:
    try:
        return fuzz_and_shrink(seed, count, batch, keep)
    finally:
        # Leave the project built with its default shaders, as a normal build would.
        run(["dotnet", "build", str(PROJECT), "-nologo", "-v:q"])


SHADERS_PER_BUILD = 300  # each shader embeds its MSL, and an assembly's strings are limited to 16 MB


def run_alone(work: Path, items: list[tuple[str, Node]]) -> dict[str, dict]:
    """Runs each tree alone in a shader of its own; returns the mismatches by key."""
    source = work / "DifferentialShaders.g.cs"
    found: dict[str, dict] = {}
    for start in range(0, len(items), SHADERS_PER_BUILD):
        chunk = items[start:start + SHADERS_PER_BUILD]
        specs = [ShaderSpec(f"Alone{k}", [Case(key, root)]) for k, (key, root) in enumerate(chunk)]
        write_if_changed(source, emit(specs, "cases alone"))
        found.update((f["case"], f) for f in build_and_run(source, work / "report.jsonl", work))
    return found


def fuzz_and_shrink(seed: int, count: int, batch: int, keep: bool) -> int:
    work = Path(tempfile.mkdtemp(prefix="sharpcompute-fuzz-"))
    source = work / "DifferentialShaders.g.cs"
    failures: dict[str, dict] = {}
    print(f"fuzz: seed {seed}, {count} expressions in batches of {batch}; working in {work}", flush=True)
    for start in range(0, count, batch):
        n = min(batch, count - start)
        specs = shaders_for(seed, start, n, f"Fuzz{seed}x{start}x")
        write_if_changed(source, emit(specs, f"seed {seed}, cases {start}..{start + n - 1}"))
        found = build_and_run(source, work / "report.jsonl", work)
        for f in found:
            failures.setdefault(f["case"], f)
        print(f"  cases {start}..{start + n - 1}: {len(found)} mismatching", flush=True)

    crashed = sorted(set(CRASHES))
    if crashed:
        print(f"  {len(crashed)} shader(s) crashed Metal's compiler building their pipeline, not compared: {', '.join(crashed)}", flush=True)
        CRASHES.clear()

    if not failures:
        print(f"fuzz: no mismatches in {count} expressions (seed {seed})")
        if not keep:
            shutil.rmtree(work, ignore_errors=True)
        return 0

    def generated(case_id: str) -> Node:
        s, i = (int(x) for x in case_id.split(":"))
        return generate_case(s, i).root

    # Each failure alone first: one that mismatches only next to other cases is reported as generated.
    current: dict[str, Node] = {cid: generated(cid) for cid in failures}
    latest = dict(failures)
    alone = run_alone(work, list(current.items()))
    for cid in list(current):
        if cid in alone:
            latest[cid] = alone[cid]
        else:
            current.pop(cid)
    print(f"  {len(current)} of {len(failures)} mismatch alone in a shader; shrinking them", flush=True)

    # Greedy shrinking: each round tries the smaller trees of every failure and keeps the smallest
    # that still mismatches; a failure that no candidate reproduces is done.
    active = set(current)
    for round_ in range(1, 25):
        items: list[tuple[str, Node]] = []
        for cid in sorted(active):
            seen = set()
            for k, cand in enumerate(sorted(shrink_candidates(current[cid]), key=lambda n: n.size())):
                key = render_key(cand)
                if key in seen:
                    continue
                seen.add(key)
                items.append((f"{cid}#{k}", cand))
                if len(seen) >= 40:
                    break
        if not items:
            break
        found = run_alone(work, items)
        best: dict[str, tuple[int, Node, dict]] = {}
        for key, cand in items:
            cid = key.split("#")[0]
            hit = found.get(key)
            if hit is not None and (cid not in best or cand.size() < best[cid][0]):
                best[cid] = (cand.size(), cand, hit)
        done = set()
        for cid in active:
            if cid in best and best[cid][0] <= current[cid].size() and render_key(best[cid][1]) != render_key(current[cid]):
                current[cid], latest[cid] = best[cid][1], best[cid][2]
            else:
                done.add(cid)
        active -= done
        print(f"  shrinking, round {round_}: {len(items)} candidates, {len(active)} still shrinking", flush=True)
        if not active:
            break

    distinct: dict[str, tuple[str, Node]] = {}
    for cid in failures:
        root = current.get(cid) or generated(cid)
        distinct.setdefault(render_key(root), (cid, root))
    print(f"\nfuzz: {len(failures)} of {count} expressions mismatched (seed {seed}); {len(distinct)} distinct after shrinking:\n")
    for key, (cid, root) in distinct.items():
        print(repro(cid, root, latest.get(cid, failures[cid])))
        print()
    if not keep:
        shutil.rmtree(work, ignore_errors=True)
    return 1


def render_key(root: Node) -> str:
    return "\n".join(emit_case(root, Ctx("t"), 0, base=""))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    gen = sub.add_parser("generate", help="write the shaders of the default mode")
    gen.add_argument("--out", required=True, type=Path)
    gen.add_argument("--seed", type=int, action="append", help="a seed (repeatable); the fixed seeds by default")
    gen.add_argument("--count", type=int, default=FAST_COUNT, help="expressions per seed")
    fz = sub.add_parser("fuzz", help="the long mode")
    fz.add_argument("--seed", type=int, required=True)
    fz.add_argument("--count", type=int, required=True)
    fz.add_argument("--batch", type=int, default=2000)
    fz.add_argument("--keep", action="store_true", help="keep the working folder")
    args = parser.parse_args()
    if args.command == "generate":
        seeds = args.seed or list(FAST_SEEDS)
        specs = []
        for s in seeds:
            specs.extend(shaders_for(s, 0, args.count, f"Random{s}x"))
        write_if_changed(args.out, emit(specs, f"seeds {', '.join(map(str, seeds))}, {args.count} cases each"))
        return 0
    return fuzz(args.seed, args.count, args.batch, args.keep)


if __name__ == "__main__":
    sys.exit(main())
