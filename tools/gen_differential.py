NUMERIC_VECTORS = tuple(v for v in VECTORS if v.kind != "bool")
INT_VECTORS = tuple(v for v in VECTORS if v.kind == "int")
FLOAT_VECTORS = tuple(v for v in VECTORS if v.floating)
BOOL_VECTORS = tuple(v for v in VECTORS if v.kind == "bool")


@production(NUMERIC_VECTORS, 4)
def p_vec_arith(g: Gen, t: Ty, d: int) -> Node:
    ops = ["+", "-", "*", "+", "-", "*"]
    ops += ["&", "|", "^"] if t.kind == "int" else ["/", "%"]
    o = g.r.choice(ops)
    e = elem_of(t)
    a = b = t
    c = g.r.random()
    if c < 0.15:
        a = e
    elif c < 0.3:
        b = e
    flags = ["arith"] if t.kind == "float" else []
    if t.floating:
        flags += {"+": ["add"], "-": ["sub"], "*": ["mul"], "/": ["div"], "%": ["div"]}.get(o, [])
    return op(t, f"({{0}} {o} {{1}})", [g.expr(a, d), g.expr(b, d)], flags)


@production(INT_VECTORS, 0.8)
def p_vec_divide(g: Gen, t: Ty, d: int) -> Node:
    o = g.r.choice(["/", "%"])
    zero = "Gpu.Equal({1}, 0)" if t.elem == "int" else "Gpu.Equal({1}, 0u)"
    if t.elem == "int":
        zero += " | (Gpu.Equal({0}, int.MinValue) & Gpu.Equal({1}, -1))"
    one = f"new {t.cs}(1)" if t.elem == "int" else f"new {t.cs}(1u)"
    return op(t, f"({{0}} {o} Gpu.Select({zero}, {one}, {{1}}))", [g.expr(t, d), g.expr(t, d)], ["div"], bind=(0, 1))


@production(INT_VECTORS, 1.2)
def p_vec_int_unary_shift(g: Gen, t: Ty, d: int) -> Node:
    c = g.r.random()
    if c < 0.3:
        if t.elem == "uint":
            raise Reject()
        return op(t, "(-{0})", [g.expr(t, d)], ["neg"])
    if c < 0.45:
        return op(t, "(~{0})", [g.expr(t, d)])
    o = g.r.choice(["<<", ">>"])
    count = t if g.r.random() < 0.5 else INT
    return op(t, f"({{0}} {o} {{1}})", [g.expr(t, d), g.expr(count, d)])


