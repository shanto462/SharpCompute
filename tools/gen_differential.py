# ---- types ---------------------------------------------------------------------------------------


@dataclass(frozen=True)
class Ty:
    cs: str
    short: str  # prefix of the input variables of this type
    kind: str  # bool, int, float, half
    bits: int = 0
    signed: bool = False
    lanes: int = 1
    elem: str = ""  # C# type of the lanes of a vector

    @property
    def vector(self) -> bool:
        return self.lanes > 1

    @property
    def floating(self) -> bool:
        return self.kind in ("float", "half")

    def __repr__(self) -> str:
        return self.cs


BOOL = Ty("bool", "b", "bool")
BYTE = Ty("byte", "by", "int", 8, False)
SBYTE = Ty("sbyte", "sb", "int", 8, True)
SHORT = Ty("short", "sh", "int", 16, True)
USHORT = Ty("ushort", "us", "int", 16, False)
INT = Ty("int", "i", "int", 32, True)
UINT = Ty("uint", "u", "int", 32, False)
LONG = Ty("long", "l", "int", 64, True)
ULONG = Ty("ulong", "ul", "int", 64, False)
FLOAT = Ty("float", "f", "float", 32, True)
HALF = Ty("Half", "h", "half", 16, True)

INTEGERS = (BYTE, SBYTE, SHORT, USHORT, INT, UINT, LONG, ULONG)
SCALARS = (BOOL,) + INTEGERS + (FLOAT, HALF)
NUMERIC = INTEGERS + (FLOAT, HALF)
BY_CS = {t.cs: t for t in SCALARS}


def make_vector(prefix: str, lanes: int) -> Ty:
    elem = {"Float": FLOAT, "Half": HALF, "Int": INT, "UInt": UINT, "Bool": BOOL}[prefix]
    return Ty(f"{prefix}{lanes}", f"{elem.short}{lanes}", elem.kind, elem.bits, elem.signed, lanes, elem.cs)


VECTORS = tuple(make_vector(p, n) for p in ("Float", "Half", "Int", "UInt", "Bool") for n in (2, 3, 4))
ALL_TYPES = SCALARS + VECTORS
BY_NAME = {t.cs: t for t in ALL_TYPES}


def vec(prefix: str, lanes: int) -> Ty:
    """The one instance of a vector type: types are compared by identity."""
    return BY_NAME[f"{prefix}{lanes}"]


def elem_of(t: Ty) -> Ty:
    return BY_CS[t.elem] if t.vector else t


def with_lanes(t: Ty, lanes: int) -> Ty:
    e = elem_of(t)
    if lanes == 1:
        return e
    prefix = {"float": "Float", "half": "Half", "bool": "Bool"}.get(e.kind) or ("Int" if e is INT else "UInt")
    return BY_NAME[f"{prefix}{lanes}"]


def promote_unary(t: Ty) -> Ty:
    return INT if t.kind == "int" and t.bits < 32 else t


def promote_binary(a: Ty, b: Ty) -> Ty | None:
    """C#'s binary numeric promotion of two scalars, or None where C# has no operator."""
    if a is HALF or b is HALF:
        return HALF if a is b else None
    if a is FLOAT or b is FLOAT:
        return FLOAT
    if a is ULONG or b is ULONG:
        other = b if a is ULONG else a
        return None if other.signed else ULONG
    if a is LONG or b is LONG:
        return LONG
    if a is UINT or b is UINT:
        other = b if a is UINT else a
        return LONG if other.signed else UINT
    return INT


# ---- variables (the shader's inputs) ------------------------------------------------------------

SCALAR_VARS = 3
VECTOR_VARS = 2


@dataclass(frozen=True)
class Var:
    name: str
    t: Ty
    slot: int  # the first of its slots in a thread's row of the input buffer


def make_layout() -> tuple[list[Var], list[str]]:
    """Every input variable and the element type of every input slot. The same for every shader."""
    variables: list[Var] = []
    slots: list[str] = []
    for t in SCALARS:
        for k in range(SCALAR_VARS):
            variables.append(Var(f"{t.short}{k}", t, len(slots)))
            slots.append(t.cs)
    for t in VECTORS:
        for k in range(VECTOR_VARS):
            variables.append(Var(f"{t.short}{'ab'[k]}", t, len(slots)))
            slots.extend([t.elem] * t.lanes)
    return variables, slots


VARIABLES, SLOTS = make_layout()
VARS_BY_TYPE: dict[Ty, list[Var]] = {}
for _v in VARIABLES:
    VARS_BY_TYPE.setdefault(_v.t, []).append(_v)
VAR_BY_NAME = {v.name: v for v in VARIABLES}


def read_slot(t: Ty, at: str) -> str:
    """The expression that reads one input slot as a value of the scalar type t."""
    if t is BOOL:
        return f"(input[{at}] & 1UL) != 0"
    if t is FLOAT:
        return f"Gpu.AsFloat((uint)input[{at}])"
    if t is HALF:
        return f"Gpu.AsHalf((ushort)input[{at}])"
    if t is ULONG:
        return f"input[{at}]"
    return f"({t.cs})input[{at}]"


def declare(v: Var, base: str) -> str:
    def at(k: int) -> str:
        return f"{base} + {v.slot + k}" if base else str(v.slot + k)

    if not v.t.vector:
        return f"{v.t.cs} {v.name} = {read_slot(v.t, at(0))};"
    e = elem_of(v.t)
    lanes = ", ".join(read_slot(e, at(k)) for k in range(v.t.lanes))
    return f"{v.t.cs} {v.name} = new {v.t.cs}({lanes});"


