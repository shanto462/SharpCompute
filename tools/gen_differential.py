# -- root-only: the functions compared within a tolerance --

TRANSCENDENTAL = ["Sin", "Cos", "Tan", "Asin", "Acos", "Atan", "Sinh", "Cosh", "Tanh", "Exp", "Exp2", "Exp10", "Log", "Log2", "Log10"]
MATHF_TRANSCENDENTAL = ["Sin", "Cos", "Tan", "Asin", "Acos", "Atan", "Sinh", "Cosh", "Tanh", "Exp", "Log", "Log2", "Log10"]


def tolerance(t: Ty, n: Node, ulps: int | None = None, near: bool = False) -> Node:
    n.flags = n.flags | {"tol", "arith"} | ({"near"} if near else set())
    n.ulps = ulps if ulps is not None else (1 if elem_of(t) is HALF else 4)
    return n


@production((FLOAT,) + FLOAT_VECTORS, root=True)
def r_transcendental(g: Gen, t: Ty, d: int) -> Node:
    if t is FLOAT and g.r.random() < 0.4:
        fn = g.r.choice(MATHF_TRANSCENDENTAL + ["Atan2", "Pow"])
        if fn in ("Atan2", "Pow"):
            return tolerance(t, op(t, f"MathF.{fn}({{0}}, {{1}})", [g.expr(t, d), g.expr(t, d)]))
        return tolerance(t, op(t, f"MathF.{fn}({{0}})", [g.expr(t, d)]))
    if t is HALF:
        raise Reject()
    fn = g.r.choice(TRANSCENDENTAL + ["Atan2", "Pow"])
    if fn in ("Atan2", "Pow"):
        return tolerance(t, op(t, f"Gpu.{fn}({{0}}, {{1}})", [g.expr(t, d), g.expr(t, d)]))
    return tolerance(t, op(t, f"Gpu.{fn}({{0}})", [g.expr(t, d)]))


@production((FLOAT, HALF) + FLOAT_VECTORS, root=True)
def r_composite(g: Gen, t: Ty, d: int) -> Node:
    if not t.vector:
        if t is HALF:
            fn = g.r.choice(["Radians", "Degrees", "Dot", "Length", "Distance"])
        else:
            fn = g.r.choice(["Radians", "Degrees", "Lerp", "Smoothstep", "Dot", "Length", "Distance", "float.Lerp"])
        if fn in ("Radians", "Degrees"):
            # A multiplication by a constant, which the GPU may fuse with what follows: root only.
            return tolerance(t, op(t, f"Gpu.{fn}({{0}})", [g.expr(t, d)]), 1 if t is FLOAT else 0)
        if fn in ("Lerp", "Smoothstep"):
            return tolerance(t, op(t, f"Gpu.{fn}({{0}}, {{1}}, {{2}})", [g.expr(t, d), g.expr(t, d), g.expr(t, d)]), near=True)
        if fn == "float.Lerp":
            return tolerance(t, op(t, "float.Lerp({0}, {1}, {2})", [g.expr(t, d), g.expr(t, d), g.expr(t, d)]), near=True)
        v = with_lanes(t, g.r.choice([2, 3, 4]))
        if fn == "Length":
            return tolerance(t, op(t, "Gpu.Length({0})", [g.expr(v, d)]), near=True)
        return tolerance(t, op(t, f"Gpu.{fn}({{0}}, {{1}})", [g.expr(v, d), g.expr(v, d)]), near=True)
    fn = g.r.choice(["Lerp", "Smoothstep", "Normalize", "Reflect", "Radians", "Degrees"] + (["Cross"] if t.lanes == 3 and t.elem == "Half" else []))
    if fn in ("Normalize", "Radians", "Degrees"):
        return tolerance(t, op(t, f"Gpu.{fn}({{0}})", [g.expr(t, d)]), near=fn == "Normalize")
    if fn in ("Reflect", "Cross"):
        return tolerance(t, op(t, f"Gpu.{fn}({{0}}, {{1}})", [g.expr(t, d), g.expr(t, d)]), near=True)
    if fn == "Lerp" and g.r.random() < 0.3:
        return tolerance(t, op(t, "Gpu.Lerp({0}, {1}, {2})", [g.expr(t, d), g.expr(t, d), g.expr(elem_of(t), d)]), near=True)
    return tolerance(t, op(t, f"Gpu.{fn}({{0}}, {{1}}, {{2}})", [g.expr(t, d), g.expr(t, d), g.expr(t, d)]), near=True)


@production(FLOAT_VECTORS, root=True)
def r_half_vector_transcendental(g: Gen, t: Ty, d: int) -> Node:
    fn = g.r.choice(TRANSCENDENTAL)
    return tolerance(t, op(t, f"Gpu.{fn}({{0}})", [g.expr(t, d)]))


@production((vec("Float", 3),), root=True)
def r_cross(g: Gen, t: Ty, d: int) -> Node:
    return tolerance(t, op(t, "Gpu.Cross({0}, {1})", [g.expr(t, d), g.expr(t, d)]), near=True)


# ---- known differences ---------------------------------------------------------------------------
#
# What the GPU is known to compute differently from ForCpu and that is not fixed: each has a skipped
# test with its repro in KnownDifferencesTests.cs. The generator leaves these patterns out, so that a
# long run reports only what is new. A shrunk tree must not fall into one either.

def may_be_constant(n: Node) -> bool:
    """Whether the Metal compiler may see n as a constant: a literal, through locals, assignments,
    increments, swizzles and either arm of a ternary."""
    if n.kind == "lit":
        return True
    if n.kind == "var":
        return False
    if n.kind in ("let", "inc"):
        return may_be_constant(n.args[0])
    if n.kind == "op" and n.text.startswith("({0} ? "):
        return may_be_constant(n.args[1]) or may_be_constant(n.args[2])
    return bool(n.args) and all(may_be_constant(a) for a in n.args)


def has_constant_part(n: Node) -> bool:
    """may_be_constant, or a vector with a constant lane."""
    if may_be_constant(n):
        return True
    if n.kind in ("let", "inc"):
        return has_constant_part(n.args[0])
    if n.kind == "op" and (n.text.startswith("({0} ? ") or n.text.startswith("new ") or n.text.startswith("{0}.") or n.text.startswith("Gpu.Select(")):
        return any(has_constant_part(a) for a in n.args if a.t is not BOOL)
    return False


CALL = re.compile(r"[A-Za-z_][A-Za-z_0-9.]*\(")


def is_constant_expression(n: Node) -> bool:
    """Whether n is a constant to C# or to the generator's folder: a literal (a constant vector
    included), or operators and casts of them, but no call, member access, local or increment."""
    if n.kind == "lit":
        return True
    return n.kind == "op" and not CALL.search(n.text) and "{0}." not in n.text and all(is_constant_expression(a) for a in n.args)


def folds_to_constant(n: Node) -> bool:
    """Whether the compiler may fold n to a constant although an operand is not one: `x | C` (all
    ones, or the bits x cannot have) and `t |= C`, `t &= C` (0), a rotate of a constant (all ones),
    Min, Max and Clamp with a constant bound, and an operator of one value twice (`x - x`)."""
    if n.kind == "compound":
        return n.text in ("|=", "&=") and has_constant_part(n.args[1])
    if n.kind != "op" or len(n.args) < 2:
        return False
    if "Rotate" in n.text and has_constant_part(n.args[0]):
        return True
    if len({render_key(a) for a in n.args}) < len(n.args):
        return True
    return any(a.kind == "lit" for a in n.args) and (" | " in n.text or any(f in n.text for f in ("Min(", "Max(", "Clamp(")))


def is_ternary(n: Node) -> bool:
    return n.kind == "op" and n.text.startswith("({0} ? ")


def through_locals(n: Node) -> Node:
    while n.kind == "let":
        n = n.args[0]
    return n


def is_swizzle(n: Node) -> bool:
    return n.kind == "op" and n.text.startswith("{0}.")


def through_swizzles(n: Node) -> Node:
    """n through locals, swizzles and increments (whose value is the target's, before or after)."""
    while n.kind in ("let", "inc") or is_swizzle(n):
        n = n.args[0]
    return n


def has_constant_lane(n: Node) -> bool:
    """has_constant_part, or a componentwise Gpu function, a conversion or arithmetic of operands
    with one: the compiler folds Gpu.Abs(new Half4(-65504, h, h, 1)), (Half4)new Float4(f, -0.5f, ...)
    and new Half3(10, 0, h) + new Half3(1000, -0, h) to vectors with constant lanes."""
    n = through_locals(n)
    if has_constant_part(n):
        return True
    if n.kind != "op":
        return False
    if n.text.startswith("Gpu.") or (n.text.startswith("((") and len(n.args) == 1):
        return any(has_constant_lane(a) for a in n.args)
    if n.t.vector and "arith" in n.flags:
        return all(has_constant_lane(a) for a in n.args)
    return False


def may_be_large(n: Node) -> bool:
    """Whether n may be a float of 2^24 or more in magnitude: an integer of 32 bits or more converted
    to a float, or a literal that large, through locals and swizzles."""
    n = through_swizzles(n)
    if n.kind == "lit":
        return any(x in n.text for x in ("e10f", "e30f", "16777216f", "2147483648f", "4294967296f", "MaxValue"))
    return n.kind == "op" and n.text.startswith("((") and len(n.args) == 1 and elem_of(n.args[0].t).kind == "int" and elem_of(n.args[0].t).bits >= 32


def is_division(n: Node) -> bool:
    return (n.kind == "op" and "div" in n.flags) or (n.kind == "compound" and n.text in ("/=", "%="))


BITS_TO_FLOAT = ("Gpu.AsFloat(", "BitConverter.Int32BitsToSingle(", "BitConverter.UInt32BitsToSingle(")


def known_difference(root: Node) -> str | None:
    """The known difference the tree would run into, or None. Each name but ZeroSignOfMinMax,
    SameOperands, ConstantSubnormal and SubnormalFromBits (policy: what IEEE leaves open, an exact
    simplification the GPU makes, constants the compiler folds without flushing, and subnormals the
    Near check cannot see among the inputs) is a test of
    KnownDifferencesTests.cs that holds a minimal repro: skipped, or, for ConstantDividend, the
    repro of the shapes the generator works around."""
    for n in root.walk():
        e = elem_of(n.t)
        if is_division(n):
            dividend, divisor = n.args[0], n.args[1]
            if e in (UINT, LONG, ULONG) and (has_constant_part(dividend) or any(folds_to_constant(m) for m in dividend.walk())) and not (
                    n.kind == "op" and is_constant_expression(through_locals(dividend))):
                # The generator divides a constant dividend near 2^32 through a helper when it can
                # see the constant: a C# constant expression or a constant vector, written in the
                # division or the initializer of a local that is never written (a let, a bound
                # operand). One the compiler only finds through the target of a compound assignment,
                # an increment, a lane or a fold is still divided wrongly.
                return "ConstantDividend"
            if e is HALF and has_constant_lane(divisor):
                return "HalfDivisionByConstant"
            if e.floating and (zero_sign_open(divisor) or zero_sign_open(dividend)):
                # Policy: which of two operands that are equal once flushed (±0, subnormals) Min and
                # Max return is open, and a division does not hide the difference.
                return "ZeroSignOfMinMax"
            if e.floating and n.kind == "op" and render_key(dividend) == render_key(divisor):
                # Policy: the compiler may simplify x / x and x % x of one value, which differ from
                # IEEE only for infinities and NaN.
                return "SameOperands"
        if n.kind != "op":
            continue
        if any("rsqrt" in through_swizzles(a).flags for a in n.args) and not is_swizzle(n):
            return "RsqrtOfZeroConsumed"
        if "rsqrt" in n.flags and zero_sign_open(n.args[0]):
            return "ZeroSignOfMinMax"
        if "sqrt" in n.flags and any("h2f" in m.flags for m in n.args[0].walk()):
            return "SqrtOfConvertedHalf"
        if "tol" in n.flags and any(zero_sign_open(a) for a in n.args):
            # Policy: Atan2 and Pow of a zero of either sign, which Min and Max leave open, differ by π or ∞.
            return "ZeroSignOfMinMax"
        if n.text.startswith(("Gpu.Pow(", "MathF.Pow(")) and any("Fract(" in m.text for m in n.args[0].walk() if m.kind == "op") and may_be_large(n.args[1]):
            # The GPU's pow of a base next to 1 (Fract gives 0.99999994) and a large exponent
            # overflows where the result is finite.
            return "PowNearOne"
        if "near" in n.flags and any(m.kind == "op" and m.text.startswith(BITS_TO_FLOAT) and elem_of(m.args[0].t).kind == "int" for m in n.walk()):
            # Policy: the Near check allows a flushed intermediate result on a thread whose float
            # inputs come within 2^-64 of zero; a float made from the bits of an integer can be
            # subnormal (Gpu.AsFloat(65568) is 9.2e-41) without such an input, and the GPU flushes
            # what it feeds (Reflect of it: 0 where ForCpu gives -0.0156).
            return "SubnormalFromBits"
        if "tol" in n.flags and len({render_key(a) for a in n.args}) < len(n.args):
            # Policy: the GPU simplifies mix(x, x, t) to x; ForCpu evaluates the GPU's formula, which cancels.
            return "SameOperands"
        if "f2h" in n.flags and any("Fract(" in m.text for m in n.args[0].walk() if m.kind == "op"):
            return "HalfOfFract"
        if "l2h" in n.flags:
            return "LongToHalf"
        if n.text.startswith(("Gpu.AsFloat(", "BitConverter.Int32BitsToSingle(", "BitConverter.UInt32BitsToSingle(", "Gpu.AsHalf(")) and may_be_constant(n.args[0]):
            return "ConstantSubnormal"
    return None


# ---- cases ---------------------------------------------------------------------------------------

ROOT_TYPES = [(t, w) for t, w in [(BOOL, 1.5), (BYTE, 0.7), (SBYTE, 0.7), (SHORT, 0.7), (USHORT, 0.7), (INT, 3), (UINT, 2), (LONG, 1.5), (ULONG, 1.2),
                                  (FLOAT, 3.5), (HALF, 1.5)]] + [(v, 0.45) for v in VECTORS]


@dataclass
class Case:
    id: str
    root: Node

    @property
    def t(self) -> Ty:
        return self.root.t


def generate_case(seed: int, index: int) -> Case:
    rng = random.Random(f"{seed}:{index}")
    g = Gen(rng)
    for _ in range(100):
        t = rng.choices([t for t, _ in ROOT_TYPES], [w for _, w in ROOT_TYPES])[0]
        root = g.root(t)
        if root.kind in ("var", "lit"):
            continue
        if root.size() > 40:
            continue
        if len(fused_variants(root)) > MAX_FUSED_VARIANTS:
            continue
        if known_difference(root) is not None:
            continue
        return Case(f"{seed}:{index}", root)
    raise RuntimeError(f"no case for {seed}:{index}")


# ---- fused multiply-add candidates --------------------------------------------------------------

def mul_child(n: Node) -> tuple[Node, bool] | None:
    """The multiplication a GPU may contract into the add or subtract that consumes n, and whether it
    is negated on the way: n itself, through a local, or through a negation."""
    negated = False
    while True:
        if n.kind == "let":
            n = n.args[0]
        elif n.kind == "op" and "neg" in n.flags and n.t.floating:
            negated = not negated
            n = n.args[0]
        elif n.kind == "op" and "pos" in n.flags:
            n = n.args[0]
        elif is_ternary(n) and n.args[0].kind == "lit":
            n = n.args[1] if n.args[0].text == "true" else n.args[2]
        else:
            break
    if n.kind == "op" and "mul" in n.flags:
        return n, negated
    return None


def fusion_sites(root: Node) -> list[tuple[int, list[str]]]:
    """The adds and subtracts with a multiplication operand, by id(node), with the operands that
    can be contracted: L, R (an op), or R for a compound assignment's value."""
    sites = []
    for n in root.walk():
        if not n.t.floating:
            continue
        if n.kind == "op" and ("add" in n.flags or "sub" in n.flags):
            sides = [s for s, a in zip("LR", n.args) if mul_child(a) is not None]
            if sides:
                sites.append((id(n), sides))
        elif n.kind == "compound" and n.text in ("+=", "-=") and mul_child(n.args[1]) is not None:
            sites.append((id(n), ["R"]))
    return sites


def fused_variants(root: Node) -> list[dict[int, str]]:
    """Every combination of contractions, except none at all."""
    sites = fusion_sites(root)
    options = [[None] + sides for _, sides in sites]
    variants = []
    for combo in itertools.product(*options):
        chosen = {site: side for (site, _), side in zip(sites, combo) if side is not None}
        if chosen:
            variants.append(chosen)
        if len(variants) > MAX_FUSED_VARIANTS:
            break
    return variants


# ---- rendering -----------------------------------------------------------------------------------

class Ctx:
    def __init__(self, prefix: str, flush: int = 0, fuse: dict[int, str] | None = None):
        self.prefix = prefix
        self.flush = flush
        self.fuse = fuse or {}
        self.lines: list[str] = []
        self.n = 0

    def temp(self, t: Ty, value: str) -> str:
        name = f"{self.prefix}{self.n}"
        self.n += 1
        self.lines.append(f"{t.cs} {name} = {value};")
        return name

    def name(self) -> str:
        name = f"{self.prefix}{self.n}"
        self.n += 1
        return name


def flushes(t: Ty) -> bool:
    return elem_of(t) is FLOAT


def F(ctx: Ctx, t: Ty, text: str, result: bool = False) -> str:
    """A float operand (or with `result`, the result) of a float operation in a flushed model.
    Model 1 flushes the operands and the result. Models 2 and 3 flush the result of a rounded
    operation through `rounded` instead; model 3 leaves the operands as they are."""
    if not (ctx.flush and flushes(t)) or (ctx.flush == 3 and not result):
        return text
    return f"GpuModel.Flush({text})"


def rounded_kind(n: Node) -> str | None:
    """The GpuModel helper that decides the tininess of n's result, for the operations whose result
    is rounded and can so round up to the smallest normal: a multiplication, a division and a fused
    multiply-add. The remainder (% and Fmod) is exact, and an add or subtract of floats is exact
    wherever its result is that small, so their results are tiny only if they are subnormal."""
    if n.kind == "compound":
        return {"*=": "Product", "/=": "Quotient"}.get(n.text)
    if n.kind != "op":
        return None
    if "mul" in n.flags:
        return "Product"
    if "div" in n.flags and n.text == "({0} / {1})":
        return "Quotient"
    if n.text.startswith(("Gpu.Fma(", "MathF.FusedMultiplyAdd(")):
        return "Fma"
    return None


def rounded(ctx: Ctx, t: Ty, kind: str | None, text: str, operands: list[tuple[str, Ty]]) -> str:
    """The result `text` of a float operation on `operands` in a flushed model. In models 2 and 3 a
    product, quotient or fused multiply-add is also flushed when it is the smallest normal and
    rounded up to it: the GPU decides tininess before rounding. GpuModel tells from the operands,
    which are bound to locals so that they are evaluated once."""
    if not (ctx.flush and flushes(t)):
        return text
    if ctx.flush < 2 or kind is None:
        return f"GpuModel.Flush({text})"
    names = [o if source is t and re.fullmatch(r"\w+", o) else ctx.temp(t, convert(o, source, t)) for o, source in operands]
    return f"GpuModel.Flush{kind}({text}, {', '.join(names)})"


def convert(text: str, source: Ty, target: Ty) -> str:
    """An operand of a fused multiply-add, as a value of the add's type."""
    if source is target:
        return text
    if not target.vector:
        return f"(({target.cs}){text})"
    e = elem_of(target)
    scalar = text if source is e else f"(({e.cs}){text})"
    return f"new {target.cs}({scalar})"


def fma(t: Ty, a: str, b: str, c: str) -> str:
    if t is HALF:
        return f"GpuModel.Fma({a}, {b}, {c})"
    return f"Gpu.Fma({a}, {b}, {c})"


def render(n: Node, ctx: Ctx) -> str:
    if n.kind in ("var", "lit"):
        return n.text
    if n.kind == "let":
        return ctx.temp(n.t, render(n.args[0], ctx))
    if n.kind == "compound":
        side = ctx.fuse.get(id(n))
        return render_fused(n, side, ctx) if side is not None else render_compound(n, ctx)
    if n.kind == "inc":
        return render_inc(n, ctx)
    side = ctx.fuse.get(id(n))
    if side is not None:
        return render_fused(n, side, ctx)
    arith = ctx.flush and "arith" in n.flags
    parts = []
    for a in n.args:
        text = render(a, ctx)
        parts.append(F(ctx, a.t, text) if arith else text)
    for k in n.bind:
        if n.args[k].kind != "var":
            parts[k] = ctx.temp(n.args[k].t, parts[k])
    kind = rounded_kind(n) if arith and ctx.flush >= 2 and flushes(n.t) else None
    if kind:
        # The operands go to the operation and to GpuModel: evaluate each once.
        parts = [p if re.fullmatch(r"\w+", p) else ctx.temp(a.t, p) for p, a in zip(parts, n.args)]
    text = n.text.format(*parts)
    return rounded(ctx, n.t, kind, text, [(p, a.t) for p, a in zip(parts, n.args)]) if arith else text


def render_fused(n: Node, side: str, ctx: Ctx) -> str:
    if n.kind == "compound":
        target = ctx.temp(n.t, render(n.args[0], ctx))
        m, negated = mul_child(n.args[1])
        if n.text == "-=":
            negated = not negated
        a, b = (F(ctx, x.t, render(x, ctx)) for x in m.args)
        a, b = convert(a, m.args[0].t, n.t), convert(b, m.args[1].t, n.t)
        if negated:
            a = f"(-{a})"
        ctx.lines.append(f"{target} = {fused(ctx, n.t, a, b, F(ctx, n.t, target))};")
        return target
    left, right = n.args
    mul_side, other = (left, right) if side == "L" else (right, left)
    m, negated = mul_child(mul_side)
    # Render in source order: the operands' locals keep their order.
    texts = {}
    for which in ("L", "R"):
        if which == side:
            texts["a"] = F(ctx, m.args[0].t, render(m.args[0], ctx))
            texts["b"] = F(ctx, m.args[1].t, render(m.args[1], ctx))
        else:
            texts["c"] = F(ctx, other.t, render(other, ctx))
    a = convert(texts["a"], m.args[0].t, n.t)
    b = convert(texts["b"], m.args[1].t, n.t)
    c = convert(texts["c"], other.t, n.t)
    if "sub" in n.flags:
        if side == "L":
            c = f"(-{c})"  # a * b - c
        else:
            negated = not negated  # c - a * b
    if negated:
        a = f"(-{a})"
    return fused(ctx, n.t, a, b, c)


def fused(ctx: Ctx, t: Ty, a: str, b: str, c: str) -> str:
    """The fused multiply-add a * b + c of three values of type t, flushed as the model does."""
    if ctx.flush >= 2 and flushes(t):
        a, b, c = (ctx.temp(t, x) for x in (a, b, c))
    return rounded(ctx, t, "Fma", fma(t, a, b, c), [(a, t), (b, t), (c, t)])


def render_compound(n: Node, ctx: Ctx) -> str:
    target = ctx.temp(n.t, render(n.args[0], ctx))
    value = render(n.args[1], ctx)
    if n.args[1].kind != "var" and n.guard:
        value = ctx.temp(n.args[1].t, value)
    o = n.text
    if ctx.flush and flushes(n.t):
        # t op= v is t = t op v, which flushes like any float arithmetic.
        left, right = F(ctx, n.t, target), F(ctx, n.args[1].t, value)
        kind = rounded_kind(n) if ctx.flush >= 2 else None
        if kind:
            left, right = ctx.temp(n.t, left), ctx.temp(n.args[1].t, right)
        ctx.lines.append(f"{target} = {rounded(ctx, n.t, kind, f'{left} {o[:-1]} {right}', [(left, n.t), (right, n.args[1].t)])};")
    elif n.guard:
        ctx.lines.append(f"if (!({n.guard.format(t=target, v=value)})) {{ {target} {o} {value}; }}")
    else:
        ctx.lines.append(f"{target} {o} {value};")
    return target


def render_inc(n: Node, ctx: Ctx) -> str:
    target = ctx.temp(n.t, render(n.args[0], ctx))
    form = n.text
    statement = form.endswith(";")
    form = form.rstrip(";")
    expr = form.replace("t", target)
    if ctx.flush and flushes(n.t):
        step = "+" if "++" in form else "-"
        update = f"{target} = {F(ctx, n.t, f'{F(ctx, n.t, target)} {step} 1f', True)};"
        if statement:
            ctx.lines.append(update)
            return target
        if form.startswith("t"):  # postfix: the old value
            old = ctx.temp(n.t, target)
            ctx.lines.append(update)
            return old
        ctx.lines.append(update)
        return ctx.temp(n.t, target)
    if statement:
        ctx.lines.append(f"{expr};")
        return target
    return ctx.temp(n.t, expr)


def store(t: Ty, text: str) -> str:
    if t is BOOL:
        return f"({text}) ? 1L : 0L"
    if t is FLOAT:
        return f"Gpu.AsUInt({text})"
    if t is HALF:
        return f"Gpu.AsUShort({text})"
    return f"(long)({text})"


def emit_case(root: Node, ctx: Ctx, offset: int, output: str = "output", base: str = "p") -> list[str]:
    """The statements of a case and the stores of its lanes to output[base + offset ...]."""
    value = render(root, ctx)
    lines = list(ctx.lines)
    ctx.lines.clear()

    def at(k: int) -> str:
        return f"{base} + {offset + k}" if base else str(offset + k)

    if root.t.vector:
        name = ctx.name()
        lines.append(f"{root.t.cs} {name} = {value};")
        e = elem_of(root.t)
        for k in range(root.t.lanes):
            lane = "XYZW"[k]
            lines.append(f"{output}[{at(k)}] = {store(e, name + '.' + lane)};")
    else:
        lines.append(f"{output}[{at(0)}] = {store(root.t, value)};")
    return lines


def used_vars(nodes) -> list[Var]:
    names = {n.text for root in nodes for n in root.walk() if n.kind == "var"}
    return [v for v in VARIABLES if v.name in names]


def result_kind(t: Ty) -> str:
    e = elem_of(t)
    return {"float": "Float", "half": "Half"}.get(e.kind, "Integer")


# Step: the GPU compiler writes the product of a Step and a constant as a select, whose zero is +0
# where a zero Step times a negative constant is -0 (step(2, 1) * -2.5f is +0).
ZERO_SIGN_OPEN = ("Min(", "Max(", "Clamp(", "Saturate(", "Step(")


def zero_sign_open(root: Node) -> bool:
    """Whether a float or half Min, Max, Clamp, Saturate or Step is in the tree: which zero they return
    for zeros of both signs is open (IEEE leaves it, and the GPU compares flushed operands), and the
    zero of a product with a Step."""
    for n in root.walk():
        if n.kind == "op" and n.t.floating and any(f in n.text for f in ZERO_SIGN_OPEN):
            return True
    return False


def check_of(c: Case) -> str:
    if "near" in c.root.flags:
        return "Near"
    if "tol" in c.root.flags:
        return "Tolerance"
    if not c.root.has_floating():
        return "Exact"
    return "Value" if zero_sign_open(c.root) else "Model"


def model_variants(c: Case) -> list[tuple[int, dict[int, str]]]:
    """The model variants of a case run with ForCpu, besides the case itself: flushed (two ways) or
    not, fused or not."""
    if not c.root.has_floating():
        return []
    fused = fused_variants(c.root)
    flush_options = [0, 1, 2, 3] if any(flushes(n.t) for n in c.root.walk()) else [0]
    variants = []
    for flush in flush_options:
        for f in [{}] + fused:
            if not flush and not f:
                continue
            variants.append((flush, f))
    return variants


def case_text(c: Case) -> str:
    """The case as C# statements, as it appears in its shader, for reports."""
    ctx = Ctx("t")
    lines = emit_case(c.root, ctx, 0, base="")
    return "\n".join(lines)


def cs_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


@dataclass
class ShaderSpec:
    name: str
    cases: list[Case]


def emit(shaders: list[ShaderSpec], title: str) -> str:
    out = [HEADER, "using System;", "using System.Numerics;", "using SharpCompute.Tests.Conformance;", "", f"namespace {NAMESPACE};", ""]
    stride = len(SLOTS)
    entries = []
    for s in shaders:
        offset = 0
        model_offset = 0
        body: list[str] = []
        model_body: list[str] = []
        metadata = []
        for k, c in enumerate(s.cases):
            lanes = c.t.lanes
            body.append(f"// case {c.id}")
            body.extend(emit_case(c.root, Ctx(f"c{k}_"), offset))
            variants = model_variants(c)
            for v, (flush, fuse) in enumerate(variants):
                model_body.append(f"// case {c.id}, {['as written', 'flushed', 'flushed, tininess before rounding', 'results flushed, tininess before rounding'][flush]}{', fused' if fuse else ''}")
                model_body.extend(emit_case(c.root, Ctx(f"c{k}_v{v}_", flush, fuse), model_offset + v * lanes))
            metadata.append(f"new({cs_string(c.id)}, {cs_string(case_text(c))}, ResultKind.{result_kind(c.t)}, {lanes}, DifferentialCheck.{check_of(c)}, {c.root.ulps}, {offset}, {model_offset}, {len(variants)})")
            offset += lanes
            model_offset += len(variants) * lanes
        roots = [c.root for c in s.cases]
        prologue = [declare(v, "o") for v in used_vars(roots)]
        out.extend(shader_struct(s.name, offset, stride, prologue, body, f"{len(s.cases)} random cases"))
        model = "null"
        if model_offset:
            out.extend(shader_struct(s.name + "Model", model_offset, stride, prologue, model_body, f"the models of {s.name}, run with ForCpu only"))
            model = f"static (device, threads, input, output) => device.ForCpu(threads, new {s.name}Model(input, output))"
        entries.append(
            f"        new({cs_string(s.name)}, {offset}, {model_offset},\n"
            f"            [\n" + "".join(f"                {m},\n" for m in metadata) + "            ],\n"
            f"            static (device, cpu, threads, input, output) => DifferentialHarness.Dispatch(device, cpu, threads, new {s.name}(input, output)),\n"
            f"            {model}),")
    out.append("/// <summary>The generated shaders and their cases.</summary>")
    out.append("internal static partial class DifferentialShaders")
    out.append("{")
    out.append(f"    public const string Title = {cs_string(title)};")
    out.append("")
    out.append("    /// <summary>The element type of each slot of a thread's row of the input buffer.</summary>")
    out.append(f"    public static readonly string[] InputSlots = [{', '.join(cs_string(s) for s in SLOTS)}];")
    out.append("")
    out.append("    /// <summary>The input variable each slot belongs to, for reports.</summary>")
    names = []
    for v in VARIABLES:
        names.extend([v.name] if not v.t.vector else [f"{v.name}.{'XYZW'[k]}" for k in range(v.t.lanes)])
    out.append(f"    public static readonly string[] InputNames = [{', '.join(cs_string(n) for n in names)}];")
    out.append("")
    out.append("    public static readonly DifferentialShader[] All =")
    out.append("    [")
    out.extend(entries)
    out.append("    ];")
    out.append("}")
    return "\n".join(out) + "\n"


def shader_struct(name: str, slots: int, stride: int, prologue: list[str], body: list[str], summary: str) -> list[str]:
    out = [f"/// <summary>{summary}.</summary>", "[GeneratedComputeShaderDescriptor]",
           f"public readonly partial struct {name}(ReadOnlyBuffer<ulong> input, ReadWriteBuffer<long> output) : IComputeShader", "{",
           f"    public const int Slots = {slots};", "", "    public void Execute()", "    {",
           f"        int o = ThreadIds.X * {stride};", "        int p = ThreadIds.X * Slots;"]
    out.extend("        " + line for line in prologue)
    out.extend("        " + line for line in body)
    out.extend(["    }", "}", ""])
    return out


def shaders_for(seed: int, start: int, count: int, prefix: str) -> list[ShaderSpec]:
    cases = [generate_case(seed, i) for i in range(start, start + count)]
    return [ShaderSpec(f"{prefix}{k // CASES_PER_SHADER}", cases[k:k + CASES_PER_SHADER]) for k in range(0, len(cases), CASES_PER_SHADER)]


def write_if_changed(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text() == text:
        return
    path.write_text(text)


