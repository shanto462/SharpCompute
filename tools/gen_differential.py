def int_literal(t: Ty, value: int) -> str:
    if t is INT:
        if value == -2147483648:
            return "int.MinValue"
        return f"({value})" if value < 0 else str(value)
    if t is UINT:
        return "uint.MaxValue" if value == 0xFFFFFFFF else f"{value}u"
    if t is LONG:
        if value == -(1 << 63):
            return "long.MinValue"
        return f"({value}L)" if value < 0 else f"{value}L"
    if t is ULONG:
        return "ulong.MaxValue" if value == (1 << 64) - 1 else f"{value}UL"
    return f"(({t.cs})({value}))" if value < 0 else f"(({t.cs}){value})"


# ---- expression trees ----------------------------------------------------------------------------


@dataclass
class Node:
    t: Ty
    kind: str  # var, lit, op, let, compound, inc
    text: str = ""  # var: name; lit: C#; op: format with {0}, {1}, ...; compound: operator; inc: form
    args: list["Node"] = field(default_factory=list)
    flags: frozenset = frozenset()
    bind: tuple = ()  # op: the arguments bound to locals first (they are used more than once)
    guard: str = ""  # compound: a condition (with {t} and {v}) under which the assignment is skipped
    ulps: int = 0

    def size(self) -> int:
        return 1 + sum(a.size() for a in self.args)

    def walk(self):
        yield self
        for a in self.args:
            yield from a.walk()

    def copy(self) -> "Node":
        return Node(self.t, self.kind, self.text, [a.copy() for a in self.args], self.flags, self.bind, self.guard, self.ulps)

    def has_floating(self) -> bool:
        return any(n.t.floating for n in self.walk())

    def is_lit(self) -> bool:
        return self.kind == "lit"


def var(v: Var) -> Node:
    return Node(v.t, "var", v.name)


def lit(t: Ty, text: str) -> Node:
    return Node(t, "lit", text)


def op(t: Ty, fmt: str, args: list[Node], flags=(), bind=()) -> Node:
    return Node(t, "op", fmt, args, frozenset(flags), tuple(bind))


class Reject(Exception):
    """The generator chose something that does not fit; it retries with another choice."""


class Gen:
    def __init__(self, rng: random.Random):
        self.r = rng

    # -- leaves --

    def leaf(self, t: Ty) -> Node:
        if self.r.random() < 0.8:
            return var(self.r.choice(VARS_BY_TYPE[t]))
        return self.literal(t)

    def literal(self, t: Ty) -> Node:
        if t.vector:
            lanes = ", ".join(self.literal(elem_of(t)).text for _ in range(t.lanes))
            return lit(t, f"new {t.cs}({lanes})")
        if t is BOOL:
            return lit(t, self.r.choice(["true", "false"]))
        if t is FLOAT:
            text = self.r.choice(FLOAT_LITERALS)
            return lit(t, f"({text})" if text.startswith("-") else text)
        if t is HALF:
            text = self.r.choice(HALF_LITERALS)
            return lit(t, f"((Half)({text}))" if text.startswith("-") else f"((Half){text})")
        return lit(t, int_literal(t, self.r.choice(INT_LITERALS[t.cs])))

    def bits_operand(self, t: Ty) -> Node:
        """A float or half operand of a bit cast: an input, possibly negated or with its sign changed.
        Arithmetic NaN results have no defined bits (the GPU's are canonical), so no arithmetic here."""
        v = var(self.r.choice(VARS_BY_TYPE[t]))
        c = self.r.random()
        if c < 0.6 or elem_of(t) is HALF:
            return v
        if c < 0.8:
            return op(t, "(-{0})", [v], ["neg"])
        return op(t, "Gpu.Abs({0})", [v])

    # -- expressions --

    def expr(self, t: Ty, depth: int) -> Node:
        if depth <= 0 or self.r.random() < 0.12:
            return self.leaf(t)
        table = PRODUCTIONS[t]
        weights = [w for w, _ in table]
        for _ in range(30):
            _, fn = self.r.choices(table, weights)[0]
            try:
                n = fn(self, t, depth - 1)
            except Reject:
                continue
            if n.kind == "op" and n.args and all(a.is_lit() for a in n.args):
                continue  # a constant: C# folds it, and refuses some conversions of constants
            return n
        return self.leaf(t)

    def root(self, t: Ty) -> Node:
        if t in ROOT_PRODUCTIONS and self.r.random() < 0.2:
            for _ in range(30):
                try:
                    n = self.r.choice(ROOT_PRODUCTIONS[t])(self, t, 2)
                except Reject:
                    continue
                if not all(a.is_lit() for a in n.args):
                    return n
        return self.expr(t, MAX_DEPTH)

    def any_scalar(self, kinds=("int", "float", "half")) -> Ty:
        return self.r.choice([t for t in NUMERIC if t.kind in kinds])


# ---- productions ---------------------------------------------------------------------------------

PRODUCTIONS: dict[Ty, list] = {t: [] for t in ALL_TYPES}
ROOT_PRODUCTIONS: dict[Ty, list] = {}


def production(types, weight=1.0, root=False):
    def register(fn):
        for t in types:
            if root:
                ROOT_PRODUCTIONS.setdefault(t, []).append(fn)
            else:
                PRODUCTIONS[t].append((weight, fn))
        return fn
    return register


# -- shared by every type --

@production(ALL_TYPES, 0.6)
def p_ternary(g: Gen, t: Ty, d: int) -> Node:
    return op(t, "({0} ? {1} : {2})", [g.expr(BOOL, d), g.expr(t, d), g.expr(t, d)])


@production(ALL_TYPES, 0.5)
def p_let(g: Gen, t: Ty, d: int) -> Node:
    return Node(t, "let", "", [g.expr(t, d)])


# -- integers --

def binary_operand_types(g: Gen, result: Ty, ops_allow_mixed=True) -> tuple[Ty, Ty]:
    """Two integer operand types whose promotion is `result`."""
    if not ops_allow_mixed or g.r.random() < 0.55:
        if result is INT:
            a = g.r.choice([INT, BYTE, SBYTE, SHORT, USHORT])
            b = g.r.choice([INT, BYTE, SBYTE, SHORT, USHORT])
            return a, b
        return result, result
    for _ in range(20):
        a, b = g.r.choice(INTEGERS), g.r.choice(INTEGERS)
        if promote_binary(a, b) is result:
            return a, b
    raise Reject()


@production((INT, UINT, LONG, ULONG), 3)
def p_int_arith(g: Gen, t: Ty, d: int) -> Node:
    a, b = binary_operand_types(g, t)
    o = g.r.choice(["+", "-", "*", "&", "|", "^", "+", "-", "*"])
    return op(t, f"({{0}} {o} {{1}})", [g.expr(a, d), g.expr(b, d)])


@production((INT, UINT, LONG, ULONG), 1)
def p_int_divide(g: Gen, t: Ty, d: int) -> Node:
    a, b = binary_operand_types(g, t)
    o = g.r.choice(["/", "%"])
    # Both operands in locals of the promoted type: the guard reads them twice, and a divisor that
    # is a literal 0 would not compile even where the guard skips it.
    x, y = g.expr(a, d), g.expr(b, d)
    if t.signed:
        guard = f"({{1}} == 0 || ({{0}} == {t.cs}.MinValue && {{1}} == -1))"
    else:
        guard = "({1} == 0)"
    return op(t, f"({guard} ? ({t.cs})0 : {{0}} {o} {{1}})", [cast_to(t, x), cast_to(t, y)], ["div"], bind=(0, 1))


def cast_to(t: Ty, n: Node) -> Node:
    """n converted implicitly to t (as C# would for an operand), written as a cast if the types differ."""
    if n.t is t:
        return n
    return op(t, f"(({t.cs}){{0}})", [n], ["arith", "f2i"] if n.t.floating and t.kind == "int" else [])


@production((INT, UINT, LONG, ULONG), 1.2)
def p_int_shift(g: Gen, t: Ty, d: int) -> Node:
    left = [x for x in INTEGERS if promote_unary(x) is t]
    a = g.r.choice(left)
    o = g.r.choice(["<<", ">>", ">>>"])
    return op(t, f"({{0}} {o} {{1}})", [g.expr(a, d), g.expr(INT, d)])


@production((INT, UINT, LONG, ULONG), 0.8)
def p_int_unary(g: Gen, t: Ty, d: int) -> Node:
    o = g.r.choice(["-", "~", "+"])
    if o == "-":
        if t is ULONG:
            raise Reject()
        source = {INT: [INT, BYTE, SBYTE, SHORT, USHORT], UINT: [], LONG: [LONG, UINT], ULONG: []}[t]
        if not source:
            raise Reject()
        a = g.r.choice(source)
        return op(t, "(-{0})", [g.expr(a, d)], ["neg"])
    source = [x for x in INTEGERS if promote_unary(x) is t]
    return op(t, f"({o}{{0}})", [g.expr(g.r.choice(source), d)])


@production(INTEGERS, 1.5)
def p_int_cast(g: Gen, t: Ty, d: int) -> Node:
    source = g.r.choice([x for x in NUMERIC if x is not t])
    n = g.expr(source, d)
    return op(t, f"(({t.cs}){{0}})", [n], (["arith"] if source is FLOAT else []) + (["f2i"] if source.floating else []))


@production(INTEGERS, 1.5)
def p_int_gpu(g: Gen, t: Ty, d: int) -> Node:
    fn = g.r.choice(["Abs", "CountBits", "LeadingZeroCount", "TrailingZeroCount", "ReverseBits", "Min", "Max", "Clamp", "RotateLeft", "RotateRight"])
    if fn in ("Min", "Max"):
        return op(t, f"Gpu.{fn}({{0}}, {{1}})", [g.expr(t, d), g.expr(t, d)])
    if fn == "Clamp":
        return op(t, "Gpu.Clamp({0}, {1}, {2})", [g.expr(t, d), g.expr(t, d), g.expr(t, d)])
    if fn.startswith("Rotate"):
        return op(t, f"Gpu.{fn}({{0}}, {{1}})", [g.expr(t, d), g.expr(INT, d)], ["bits"])
    return op(t, f"Gpu.{fn}({{0}})", [g.expr(t, d)], ["bits"] if fn != "Abs" else [])


@production(INTEGERS, 0.7)
def p_int_math(g: Gen, t: Ty, d: int) -> Node:
    fn = g.r.choice(["Min", "Max", "Clamp", "Abs"])
    if fn in ("Min", "Max"):
        return op(t, f"Math.{fn}({{0}}, {{1}})", [g.expr(t, d), g.expr(t, d)])
    if fn == "Clamp":
        # Ordered bounds: Math.Clamp throws for min > max.
        return op(t, "Math.Clamp({0}, Math.Min({1}, {2}), Math.Max({1}, {2}))", [g.expr(t, d), g.expr(t, d), g.expr(t, d)], bind=(1, 2))
    if t not in (SBYTE, SHORT, INT, LONG):
        raise Reject()
    # Math.Abs of the minimum throws OverflowException.
    return op(t, f"({{0}} == {t.cs}.MinValue ? ({t.cs})0 : Math.Abs({{0}}))", [g.expr(t, d)], bind=(0,))


@production((INT, UINT), 0.6)
def p_int_bits(g: Gen, t: Ty, d: int) -> Node:
    if g.r.random() < 0.5:
        fn = "Gpu.AsInt" if t is INT else "Gpu.AsUInt"
        if g.r.random() < 0.3:
            fn = "BitConverter.SingleToInt32Bits" if t is INT else "BitConverter.SingleToUInt32Bits"
        return op(t, f"{fn}({{0}})", [g.bits_operand(FLOAT)])
    if t is UINT:
        raise Reject()
    fn = g.r.choice(["PopCount", "LeadingZeroCount", "TrailingZeroCount"])
    source = g.r.choice([UINT, ULONG] if fn != "TrailingZeroCount" else [INT, UINT, LONG, ULONG])
    return op(t, f"BitOperations.{fn}({{0}})", [g.expr(source, d)], ["bits"])


@production((UINT, ULONG), 0.3)
def p_int_bitops_rotate(g: Gen, t: Ty, d: int) -> Node:
    fn = g.r.choice(["RotateLeft", "RotateRight"])
    return op(t, f"BitOperations.{fn}({{0}}, {{1}})", [g.expr(t, d), g.expr(INT, d)], ["bits"])


@production((USHORT, SHORT), 0.4)
def p_half_bits(g: Gen, t: Ty, d: int) -> Node:
    fn = "Gpu.AsUShort" if t is USHORT else "Gpu.AsShort"
    return op(t, f"{fn}({{0}})", [g.bits_operand(HALF)])


@production((INT,), 0.5)
def p_int_from_float(g: Gen, t: Ty, d: int) -> Node:
    if g.r.random() < 0.5:
        # ilogb reads the exponent of a subnormal without flushing it, so its operand is an input:
        # the GPU's Min and Max may return either of two operands that are equal once flushed.
        return op(t, "MathF.ILogB({0})", [g.bits_operand(FLOAT)])
    # MathF.Sign throws ArithmeticException for NaN.
    return op(t, "(float.IsNaN({0}) ? 0 : MathF.Sign({0}))", [g.expr(FLOAT, d)], ["arith"], bind=(0,))


@production((INT, UINT), 0.5)
def p_lane(g: Gen, t: Ty, d: int) -> Node:
    v = with_lanes(t, g.r.choice([2, 3, 4]))
    return op(t, f"{{0}}.{'XYZW'[g.r.randrange(v.lanes)]}", [g.expr(v, d)])


@production((FLOAT, HALF, BOOL), 0.5)
def p_lane_other(g: Gen, t: Ty, d: int) -> Node:
    return p_lane(g, t, d)


INT_COMPOUND = ["+=", "-=", "*=", "&=", "|=", "^=", "<<=", ">>=", ">>>=", "/=", "%="]


@production(INTEGERS, 1.0)
def p_int_compound(g: Gen, t: Ty, d: int) -> Node:
    o = g.r.choice(INT_COMPOUND)
    if o in ("<<=", ">>=", ">>>="):
        return Node(t, "compound", o, [g.expr(t, d), g.expr(INT, d)])
    guard = ""
    if o in ("/=", "%="):
        guard = f"{{v}} == 0 || ({{t}} == {t.cs}.MinValue && {{v}} == -1)" if t in (INT, LONG) else "{v} == 0"
    return Node(t, "compound", o, [g.expr(t, d), g.expr(t, d)], guard=guard)


@production(INTEGERS + (FLOAT, HALF), 0.5)
def p_increment(g: Gen, t: Ty, d: int) -> Node:
    form = g.r.choice(["t++", "t--", "++t", "--t", "t++;", "--t;"])
    return Node(t, "inc", form, [g.expr(t, d)])


# -- floats and halves --

@production((FLOAT, HALF), 4)
def p_float_arith(g: Gen, t: Ty, d: int) -> Node:
    o = g.r.choice(["+", "-", "*", "/", "%", "+", "-", "*", "+", "*"])
    a = b = t
    if t is FLOAT and g.r.random() < 0.15:
        # An integer operand converted implicitly.
        if g.r.random() < 0.5:
            a = g.any_scalar(("int",))
        else:
            b = g.any_scalar(("int",))
    flags = {"+": ["arith", "add"], "-": ["arith", "sub"], "*": ["arith", "mul"]}.get(o, ["arith", "div"])
    return op(t, f"({{0}} {o} {{1}})", [g.expr(a, d), g.expr(b, d)], flags)


@production((FLOAT, HALF), 0.8)
def p_float_neg(g: Gen, t: Ty, d: int) -> Node:
    if g.r.random() < 0.85:
        return op(t, "(-{0})", [g.expr(t, d)], ["neg"])
    return op(t, "(+{0})", [g.expr(t, d)], ["pos"])


@production((FLOAT, HALF), 1.5)
def p_float_cast(g: Gen, t: Ty, d: int) -> Node:
    source = g.r.choice([x for x in NUMERIC if x is not t])
    if t is HALF and source is FLOAT:
        return op(t, "((Half){0})", [g.expr(FLOAT, d)], ["arith", "f2h"])
    flags = (["arith"] if source is FLOAT else []) + (["l2h"] if t is HALF and source in (LONG, ULONG) else [])
    flags += ["h2f"] if t is FLOAT and source is HALF else []
    return op(t, f"(({t.cs}){{0}})", [g.expr(source, d)], flags)


FLOAT_UNARY = ["Abs", "Sign", "Saturate", "Floor", "Ceil", "Round", "Trunc", "Fract", "Sqrt", "Rsqrt"]


@production((FLOAT,) + tuple(v for v in VECTORS if v.floating), 2)
def p_float_gpu(g: Gen, t: Ty, d: int) -> Node:
    fn = g.r.choice(FLOAT_UNARY + ["Min", "Max", "Fmod", "Step", "CopySign", "Clamp", "Fma", "Min", "Max"])
    bitcopy = fn in ("Abs", "CopySign")
    flags = [] if bitcopy else ["arith"]
    flags += {"Abs": ["abs"], "Rsqrt": ["rsqrt", "sqrt"], "Sqrt": ["sqrt"], "Fmod": ["div"]}.get(fn, [])
    if fn in FLOAT_UNARY:
        return op(t, f"Gpu.{fn}({{0}})", [g.expr(t, d)], flags)
    if fn in ("Clamp", "Fma"):
        third = t
        if fn == "Clamp" and t.vector and g.r.random() < 0.3:
            return op(t, "Gpu.Clamp({0}, {1}, {2})", [g.expr(t, d), g.expr(elem_of(t), d), g.expr(elem_of(t), d)], flags)
        return op(t, f"Gpu.{fn}({{0}}, {{1}}, {{2}})", [g.expr(t, d), g.expr(t, d), g.expr(third, d)], flags)
    if fn in ("Min", "Max") and t.vector and g.r.random() < 0.3:
        return op(t, f"Gpu.{fn}({{0}}, {{1}})", [g.expr(t, d), g.expr(elem_of(t), d)], flags)
    if fn == "CopySign":
        # The sign of a NaN that arithmetic made is not defined (the GPU's are canonical): an input.
        return op(t, "Gpu.CopySign({0}, {1})", [g.expr(t, d), g.bits_operand(t)], flags)
    if fn == "Step" and t.vector and g.r.random() < 0.3:
        return op(t, "Gpu.Step({0}, {1})", [g.expr(elem_of(t), d), g.expr(t, d)], flags)
    return op(t, f"Gpu.{fn}({{0}}, {{1}})", [g.expr(t, d), g.expr(t, d)], flags)


@production((FLOAT,), 1.2)
def p_float_math(g: Gen, t: Ty, d: int) -> Node:
    fn = g.r.choice(["MathF.Abs", "MathF.Max", "MathF.Min", "Math.Max", "Math.Min", "float.Max", "float.Min", "Math.Clamp", "float.Clamp",
                     "MathF.Sqrt", "MathF.Floor", "MathF.Ceiling", "MathF.Truncate", "MathF.Round", "MathF.CopySign", "MathF.FusedMultiplyAdd", "MathF.ScaleB"])
    bitcopy = fn in ("MathF.Abs", "MathF.CopySign")
    flags = ([] if bitcopy else ["arith"]) + (["abs"] if fn == "MathF.Abs" else []) + (["sqrt"] if fn == "MathF.Sqrt" else [])
    if fn in ("MathF.Abs", "MathF.Sqrt", "MathF.Floor", "MathF.Ceiling", "MathF.Truncate", "MathF.Round"):
        return op(t, f"{fn}({{0}})", [g.expr(t, d)], flags)
    if fn == "MathF.ScaleB":
        return op(t, "MathF.ScaleB({0}, {1})", [g.expr(t, d), g.expr(INT, d)], flags)
    if fn == "MathF.CopySign":
        return op(t, "MathF.CopySign({0}, {1})", [g.expr(t, d), g.bits_operand(t)], flags)
    if fn == "MathF.FusedMultiplyAdd":
        return op(t, f"{fn}({{0}}, {{1}}, {{2}})", [g.expr(t, d), g.expr(t, d), g.expr(t, d)], flags)
    if fn in ("Math.Clamp", "float.Clamp"):
        # Inverted bounds throw in .NET; a NaN bound does not.
        return op(t, f"({{1}} > {{2}} ? 0f : {fn}({{0}}, {{1}}, {{2}}))", [g.expr(t, d), g.expr(t, d), g.expr(t, d)], flags, bind=(1, 2))
    return op(t, f"{fn}({{0}}, {{1}})", [g.expr(t, d), g.expr(t, d)], flags)


@production((FLOAT,), 0.4)
def p_float_bits(g: Gen, t: Ty, d: int) -> Node:
    source = g.r.choice([INT, UINT])
