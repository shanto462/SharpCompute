@production(VECTORS, 1.2)
def p_vec_construct(g: Gen, t: Ty, d: int) -> Node:
    e = elem_of(t)
    c = g.r.random()
    if c < 0.25:
        return op(t, f"new {t.cs}({{0}})", [g.expr(e, d)])
    if c < 0.45 and t.lanes >= 3:
        rest = with_lanes(t, t.lanes - 1)
        if g.r.random() < 0.5:
            return op(t, f"new {t.cs}({{0}}, {{1}})", [g.expr(e, d), g.expr(rest, d)])
        return op(t, f"new {t.cs}({{0}}, {{1}})", [g.expr(rest, d), g.expr(e, d)])
    parts = ", ".join(f"{{{k}}}" for k in range(t.lanes))
    return op(t, f"new {t.cs}({parts})", [g.expr(e, d - 1) for _ in range(t.lanes)])


