#!/usr/bin/env python3
"""Random-expression differential testing of the shader language: the GPU against ForCpu.

Usage (from the repo root; paths are resolved relative to this script, so any cwd works):

    python3 -I tools/gen_differential.py generate --out FILE
        Writes the shaders of the default (fast) mode, fixed seeds, to FILE. The build of
        tests/SharpCompute.Differential.Tests runs this into its obj folder; FILE is rewritten only
        when its text changes.

    python3 -I tools/gen_differential.py fuzz --seed S --count N
        The long mode (scripts/fuzz-differential.sh): N expressions from seed S, in batches, each
        built through the real source generator and run on the GPU and with ForCpu. Every
        mismatch is shrunk while it still mismatches and printed as a self-contained repro
        shader. Exits 1 if anything mismatched.

What it generates. Each case is one random, well-typed C# expression over the shader's inputs, with
the local temporaries, compound assignments and increments it needs: the integer types of every
width, bool, float, Half and their vectors; unary, binary, shift and comparison operators with C#'s
promotions; casts; the ternary; the Gpu.*, Math, MathF and BitOperations members the translator
supports. Operations that throw in C# (integer division by zero, MinValue / -1, Math.Abs of a
signed minimum, Math.Clamp with inverted bounds, MathF.Sign of NaN) are guarded, so ForCpu never
throws. A case is generated from (seed, index) alone, so a batch can be rebuilt and a case shrunk.

How a case is compared. An integer or bool case with no float or half in it must give the same bits
(Exact). Any other case is compared with its models: ForCpu's value of the case itself and of
variants of it, run with ForCpu in a second shader:
    - the flushed variants: every float operation flushes its float operands and its result to a
      zero of the same sign, as an Apple GPU's float arithmetic does; the same with a product, a
      quotient or a fused multiply-add that rounds up to the smallest normal flushed as well (the
      GPU decides tininess before rounding: GpuModel decides it from the operands, exactly); and
      that one with the operands as they are;
    - the fused variants: every multiply that the GPU may contract into a following add or
      subtract (directly, through a local, a negation or a constant ternary) computed as one fused
      multiply-add, in every combination, each also flushed.
The GPU's value must equal one of them, NaN-sign-insensitively and up to the flushing of the result
(the conformance suite's Ftz policy); -0 equals +0 where a float Min, Max, Clamp or Saturate is in
the case (Value). Transcendental and composite functions appear only at the root of a case, and are
compared within 4 float or 1 half ULP of one of the models (Tolerance; Near for the composite ones,
which also skips threads with tiny inputs).

Known differences. What the GPU computes differently and is not fixed is left out of the generated
cases (known_difference), each with a repro in KnownDifferencesTests.cs, so a long run reports only
what is new. Requires only the Python 3 standard library.
"""

