using System;

namespace SharpCompute.Samples.SimdGroups;

/// <summary>
/// A 5 × 7 pixel font for the lab's on-screen text: digits, capitals (lowercase is drawn as
/// capitals) and punctuation. A glyph is a 35-bit mask, row by row from the top, bit 0 the top-left
/// pixel, stored as two <c>uint</c>s (bits 0..31, then 32..34) because buffers hold 32-bit elements.
/// </summary>
public static class PixelFont
{
    public const int GlyphWidth = 5;
    public const int GlyphHeight = 7;

    private const string Characters = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ.,:;!?-+*/=<>()[]%#'_|&^~";

    // Seven rows of five pixels per character, in the order of Characters.
    private static readonly string[] Rows =
    [
        ".....|.....|.....|.....|.....|.....|.....", // space
        ".###.|#...#|#..##|#.#.#|##..#|#...#|.###.", // 0
        "..#..|.##..|..#..|..#..|..#..|..#..|.###.", // 1
        ".###.|#...#|....#|...#.|..#..|.#...|#####", // 2
        "####.|....#|....#|.###.|....#|....#|####.", // 3
        "...#.|..##.|.#.#.|#..#.|#####|...#.|...#.", // 4
        "#####|#....|####.|....#|....#|#...#|.###.", // 5
