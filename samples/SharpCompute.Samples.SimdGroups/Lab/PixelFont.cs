        ".##..|#..#.|#.#..|.#...|#.#.#|#..#.|.##.#", // &
        "..#..|.#.#.|#...#|.....|.....|.....|.....", // ^
        ".....|.....|.#...|#.#.#|...#.|.....|.....", // ~
    ];

    /// <summary>The glyph masks: two words per glyph, indexed by <c>2 * <see cref="Index"/></c>.</summary>
    public static uint[] Masks { get; } = Build();

    /// <summary>The number of glyphs.</summary>
    public static int Count => Characters.Length;

    /// <summary>The glyph index of <paramref name="c"/> (letters case-insensitive); 0, a blank, for anything unknown.</summary>
    public static int Index(char c) => Math.Max(0, Characters.IndexOf(char.ToUpperInvariant(c), StringComparison.Ordinal));

    /// <summary>The 35-bit mask of a glyph, for tests and CPU-side drawing.</summary>
    public static ulong Mask(int glyph) => Masks[glyph * 2] | ((ulong)Masks[(glyph * 2) + 1] << 32);

    private static uint[] Build()
    {
        if (Rows.Length != Characters.Length)
        {
            throw new InvalidOperationException("The font has a row set per character.");
        }

        uint[] masks = new uint[Characters.Length * 2];

        for (int g = 0; g < Rows.Length; g++)
        {
            string[] rows = Rows[g].Split('|');

            for (int r = 0; r < GlyphHeight; r++)
            {
                for (int c = 0; c < GlyphWidth; c++)
                {
                    if (rows[r][c] == '#')
                    {
                        int bit = (r * GlyphWidth) + c;
                        masks[(g * 2) + (bit >> 5)] |= 1u << (bit & 31);
                    }
                }
            }
        }

        return masks;
    }
}
