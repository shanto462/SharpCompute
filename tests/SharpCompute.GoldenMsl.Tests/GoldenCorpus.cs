using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using SharpCompute.Build;

namespace SharpCompute.GoldenMsl.Tests;

/// <summary>
/// One shader of the corpus: the snapshot file it belongs in, relative to the snapshot folder with
/// <c>/</c> separators, and the exact text that file must hold.
/// </summary>
internal sealed record GoldenShader(string Assembly, string TypeName, string RelativePath, string Text);

/// <summary>
/// The golden MSL corpus: every shader the source generator emitted into an assembly of the
/// solution, read from the built assemblies, and the snapshots of them in <c>tests/golden-msl</c>.
/// </summary>
/// <remarks>
/// <para>
/// The MSL comes from the assemblies' metadata, through the reader the precompile step uses: it is
/// the very string the runtime hands to the Metal compiler, so nothing is regenerated by a second
/// path that could disagree with the build, no assembly is loaded and no GPU is needed. Which
/// assemblies to read is a list the build of this project writes next to it (see the project file).
/// </para>
/// <para>
/// Everything here is ordered with ordinal comparisons and writes only names and text that come out
/// of the assemblies, so the snapshots do not depend on the machine, the checkout path, the build
/// configuration or the order of a hash table. All members are thread-safe: they keep no state.
/// </para>
/// </remarks>
internal static class GoldenCorpus
{
    /// <summary>Set to <c>1</c> (or <c>true</c>) to rewrite the snapshots instead of comparing with them.</summary>
    internal const string UpdateVariable = "SHARPCOMPUTE_UPDATE_GOLDEN";

    /// <summary>The snapshot folder, relative to the repository root.</summary>
    internal const string SnapshotFolder = "tests/golden-msl";

    internal const string Extension = ".metal";

    private const string AssemblyList = "GoldenMslAssemblies.txt";

    // The one record in the solution that the generator did not write: a fixture of the build tool's
    // tests whose MSL is deliberately computed at run time, which the reader reports and skips.
    private const string HandWrittenRecord = "'SharpCompute.Build.Tests.ComputedSource' ";

    private static readonly UTF8Encoding s_utf8 = new(encoderShouldEmitUTF8Identifier: false, throwOnInvalidBytes: true);

    private static readonly Lazy<string> s_root = new(FindRoot);

    /// <summary>The repository root: the nearest folder above the test output that holds <c>SharpCompute.slnx</c>.</summary>
    internal static string Root => s_root.Value;

    internal static string SnapshotDirectory => Path.Combine(Root, "tests", "golden-msl");

    /// <summary>True when this run was asked to rewrite the snapshots. Never true by default.</summary>
    internal static bool IsUpdateRequested =>
        Environment.GetEnvironmentVariable(UpdateVariable) is { } value
        && (value == "1" || value.Equals("true", StringComparison.OrdinalIgnoreCase));

    /// <summary>The built assemblies of the solution's projects, as the build of this project listed them, by name.</summary>
    internal static IReadOnlyList<string> AssemblyPaths()
    {
        string list = Path.Combine(AppContext.BaseDirectory, AssemblyList);

        if (!File.Exists(list))
        {
            throw new InvalidOperationException($"{AssemblyList} is not next to the test assembly: build SharpCompute.GoldenMsl.Tests, which writes it.");
        }

        return [.. File.ReadAllLines(list)
            .Where(static line => line.Length > 0)
            .OrderBy(static path => Path.GetFileNameWithoutExtension(path), StringComparer.Ordinal)];
    }

    /// <summary>
    /// Every generated shader of the solution, ordered by snapshot path.
    /// </summary>
    /// <exception cref="InvalidOperationException">
    /// An assembly is missing, a shader's MSL could not be read from its assembly, or two shaders
    /// would share a snapshot file. Each of these would otherwise drop a shader out of the corpus
    /// without a trace.
    /// </exception>
    internal static IReadOnlyList<GoldenShader> Read()
    {
        List<GoldenShader> shaders = [];
        List<string> problems = [];

        foreach (string path in AssemblyPaths())
        {
            if (!File.Exists(path))
            {
                problems.Add($"'{path}' is not built.");
                continue;
            }

            string assembly = Path.GetFileNameWithoutExtension(path);

            foreach (ShaderRecord record in ShaderRecordReader.Read(path, skipped => AddUnlessHandWritten(problems, skipped)))
            {
                shaders.Add(new GoldenShader(assembly, record.TypeName, RelativePath(assembly, record.TypeName), Render(assembly, record)));
            }
        }

        // The file system of a Mac ignores case by default, so two names that differ only in case are one file.
        problems.AddRange(shaders
            .GroupBy(static shader => shader.RelativePath, StringComparer.OrdinalIgnoreCase)
            .Where(static group => group.Count() > 1)
            .Select(static group => $"{string.Join(" and ", group.Select(static shader => $"'{shader.TypeName}'"))} share the snapshot file '{group.Key}'."));

        if (problems.Count > 0)
        {
            throw new InvalidOperationException("The golden MSL corpus could not be read:\n" + string.Join('\n', problems));
        }

        shaders.Sort(static (a, b) => string.CompareOrdinal(a.RelativePath, b.RelativePath));
        return shaders;
    }

    /// <summary>
    /// The snapshot file of a shader: a folder per assembly, and the type's full name with every
    /// character outside <c>A-Z a-z 0-9 . _ -</c> replaced by <c>_</c>.
    /// </summary>
    internal static string RelativePath(string assembly, string typeName) => Sanitize(assembly) + "/" + Sanitize(typeName) + Extension;

    /// <summary>
    /// The text of a snapshot: a comment line that names the shader and gives what its record says
    /// besides the source (the entry point and the compile options, which change the compiled kernel
    /// without changing a character of the MSL), then the MSL exactly as emitted, then a line feed.
    /// </summary>
    internal static string Render(string assembly, ShaderRecord record) =>
        $"// {record.TypeName} ({assembly}): entry point {record.EntryPoint}, compile options {Options(record.CompileOptions)}\n{record.MslSource}\n";

    /// <summary>The snapshot files that exist, as paths relative to the snapshot folder with <c>/</c> separators, in ordinal order.</summary>
    internal static IReadOnlyList<string> SnapshotFiles()
    {
        string directory = SnapshotDirectory;

        if (!Directory.Exists(directory))
        {
            return [];
        }

        return [.. Directory.EnumerateFiles(directory, "*" + Extension, SearchOption.AllDirectories)
            .Select(file => Path.GetRelativePath(directory, file).Replace(Path.DirectorySeparatorChar, '/'))
            .Order(StringComparer.Ordinal)];
    }

    /// <summary>The text of a snapshot file, or null when it does not exist.</summary>
    internal static string? ReadSnapshot(string relativePath)
    {
        string file = FullPath(relativePath);
        return File.Exists(file) ? File.ReadAllText(file, s_utf8) : null;
    }

    /// <summary>
    /// Makes the snapshot folder hold exactly <paramref name="shaders"/>: writes the files that are
    /// missing or different, and deletes the snapshots (only <c>.metal</c> files) of shaders that no
    /// longer exist. A file that is already right is not touched.
    /// </summary>
    /// <returns>How many files were written and how many were deleted.</returns>
    internal static (int Written, int Deleted) Update(IReadOnlyList<GoldenShader> shaders)
    {
        int written = 0;
        int deleted = 0;
        HashSet<string> wanted = new(StringComparer.OrdinalIgnoreCase);

        foreach (GoldenShader shader in shaders)
        {
            wanted.Add(shader.RelativePath);

            if (ReadSnapshot(shader.RelativePath) != shader.Text)
            {
                string file = FullPath(shader.RelativePath);
                Directory.CreateDirectory(Path.GetDirectoryName(file)!);
                File.WriteAllText(file, shader.Text, s_utf8);
                written++;
            }
        }

        foreach (string stale in SnapshotFiles().Where(file => !wanted.Contains(file)))
        {
            string file = FullPath(stale);
            File.Delete(file);
            deleted++;

            // An assembly that lost its last shader leaves no empty folder behind.
            if (Path.GetDirectoryName(file) is { } folder && !Directory.EnumerateFileSystemEntries(folder).Any())
            {
                Directory.Delete(folder);
            }
        }

        return (written, deleted);
    }

    /// <summary>
    /// Where <paramref name="expected"/> and <paramref name="actual"/> first differ, as the snapshot
    /// file's 1-based line number and up to <paramref name="context"/> lines of each from there on,
    /// or null when they are equal.
    /// </summary>
    internal static (int Line, string[] Expected, string[] Actual)? FirstDifference(string expected, string actual, int context = 3)
    {
        if (expected == actual)
        {
            return null;
        }

        string[] expectedLines = expected.Split('\n');
        string[] actualLines = actual.Split('\n');
        int line = 0;

        while (line < expectedLines.Length && line < actualLines.Length && expectedLines[line] == actualLines[line])
        {
            line++;
        }

        return (line + 1, [.. expectedLines.Skip(line).Take(context)], [.. actualLines.Skip(line).Take(context)]);
    }

    /// <summary>
    /// A generated shader always returns its MSL as a literal, so a record the reader skipped is a
    /// problem (the corpus would silently lose the shader) unless it is the hand-written fixture.
    /// </summary>
    private static void AddUnlessHandWritten(List<string> problems, string skipped)
    {
        if (!skipped.StartsWith(HandWrittenRecord, StringComparison.Ordinal))
        {
            problems.Add(skipped);
        }
    }

    private static string FullPath(string relativePath) => Path.Combine(SnapshotDirectory, relativePath.Replace('/', Path.DirectorySeparatorChar));

    private static string Sanitize(string name)
    {
        StringBuilder builder = new(name.Length);

        foreach (char c in name)
        {
            builder.Append(char.IsAsciiLetterOrDigit(c) || c is '.' or '_' or '-' ? c : '_');
        }

        return builder.ToString();
    }

    /// <summary>The names of <c>ShaderCompileOptions</c> flags, as the enum would print them; a bit without a name prints as its number.</summary>
    private static string Options(int options)
    {
        List<string> names = [];

        if ((options & PrecompiledShaderContract.FastMath) != 0)
        {
            names.Add("FastMath");
        }

        if ((options & PrecompiledShaderContract.NoFpContract) != 0)
        {
            names.Add("NoFpContract");
        }

        int unnamed = options & ~(PrecompiledShaderContract.FastMath | PrecompiledShaderContract.NoFpContract);

        if (unnamed != 0)
        {
            names.Add(unnamed.ToString(System.Globalization.CultureInfo.InvariantCulture));
        }

        return names.Count == 0 ? "None" : string.Join(", ", names);
    }

    private static string FindRoot()
    {
        for (DirectoryInfo? directory = new(AppContext.BaseDirectory); directory is not null; directory = directory.Parent)
        {
            if (File.Exists(Path.Combine(directory.FullName, "SharpCompute.slnx")))
            {
                return directory.FullName;
            }
        }

        throw new InvalidOperationException("SharpCompute.slnx not found above the test output.");
    }
}
